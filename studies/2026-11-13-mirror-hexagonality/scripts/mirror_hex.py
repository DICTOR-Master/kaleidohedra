def types(word):
    n = len(word); return ['h' if word[(k - 1) % n] == word[(k + 1) % n] else 'c' for k in range(n)]
def modl(p): return (p[0] % 1, p[1] % 1, p[2] % 1)
def balls(word):
    n = len(word); return [(POS[word[k]][0], POS[word[k]][1], Fr(k, n)) for k in range(n)]

def maps(word, k):
    n = len(word); zk = Fr(k, n); p = POS[word[k]]; zm = Fr(2 * k + 1, 2 * n)
    return {'sigma': lambda x: (x[0], x[1], 2 * zk - x[2]),
            'iota': lambda x: (2 * p[0] - x[0], 2 * p[1] - x[1], 2 * zk - x[2]),
            'mid': lambda x: (x[0], x[1], 2 * zm - x[2])}

# ---------- T1, T2: balls
def ball_tests(word, k):
    n = len(word); B = balls(word); out = {}
    for name, g in maps(word, k).items():
        loc = all(modl(g(B[(k + e) % n][:2] + (Fr(k + e, n),))) in {modl(B[(k - e) % n][:2] + (Fr(k - e, n),))} for e in (-1, 0, 1)) \
              if name != 'mid' else all(modl(g(B[(k + e) % n][:2] + (Fr(k + e, n),))) == modl(B[(k + 1 - e) % n][:2] + (Fr(k + 1 - e, n),)) for e in (0, 1))
        S = {modl(b) for b in B}
        glob = all(modl(g(b)) in S for b in B)
        out[name] = {'local': loc, 'global': glob}
    return out

# ---------- T3: site group of a ball of layer k inside its triple; is it generated by its reflections?
G3 = [[1, Fr(1, 2), 0], [Fr(1, 2), 1, 0], [0, 0, 1]]
def mm(A, B): return [[sum(A[i][t] * B[t][j] for t in range(3)) for j in range(3)] for i in range(3)]
def mT(A): return [list(r) for r in zip(*A)]
R60 = [[0, -1, 0], [1, 1, 0], [0, 0, 1]]         # a1 -> a2, a2 -> a2 - a1 (columns), rotation by 60 degrees
SW = [[0, 1, 0], [1, 0, 0], [0, 0, 1]]           # a1 <-> a2
FZ = [[1, 0, 0], [0, 1, 0], [0, 0, -1]]
def gen_group(gens):
    I = [[1, 0, 0], [0, 1, 0], [0, 0, 1]]; seen = {str(I): I}; fr = [I]
    while fr:
        nf = []
        for A in fr:
            for g in gens:
                C = mm(g, A)
                if str(C) not in seen: seen[str(C)] = C; nf.append(C)
        fr = nf
    return list(seen.values())
POINT24 = gen_group([R60, SW, FZ]); assert len(POINT24) == 24
for A in POINT24:                                  # each is an isometry of the metric (exact)
    assert mm(mT(A), mm(G3, A)) == G3
def site_group(word, k):
    n = len(word); p = POS[word[k]]
    lay = {e: (POS[word[(k + e) % n]], e) for e in (-1, 0, 1)}    # in-plane coset and relative layer
    def ok(A):
        for e in (-1, 0, 1):
            q, _ = lay[e]; v = (q[0] - p[0], q[1] - p[1], e)
            w = tuple(sum(A[i][j] * v[j] for j in range(3)) for i in range(3))
            e2 = int(w[2]); q2 = POS[word[(k + e2) % n]]
            if ((p[0] + w[0] - q2[0]) % 1, (p[1] + w[1] - q2[1]) % 1) != (0, 0): return False
        return True
    H = [A for A in POINT24 if ok(A)]
    refl = [A for A in H if A[0][0] + A[1][1] + A[2][2] == 1 and mm(A, A) == [[1, 0, 0], [0, 1, 0], [0, 0, 1]] and A != [[1, 0, 0], [0, 1, 0], [0, 0, 1]]]
    W = gen_group(refl) if refl else [[[1, 0, 0], [0, 1, 0], [0, 0, 1]]]
    hasFZ = FZ in H; hasInv = [[-1, 0, 0], [0, -1, 0], [0, 0, -1]] in H
    return {'order': len(H), 'reflections': len(refl), 'reflection_subgroup': len(W), 'coxeter': len(W) == len(H),
            'sigma_h': hasFZ, 'inversion': hasInv}

# ---------- T4, T5: pieces
def corners_at(c, lam): return [tuple(aff_eval(p['P'][r], (lam,)) for r in range(3)) for p in c.corners]
def edges(c):
    F = set(c.faces()); E = []
    for a, b in itertools.combinations(range(len(c.corners)), 2):
        if len(c.corners[a]['on'] & c.corners[b]['on'] & F) >= 2: E.append((a, b))
    return E
def half(X, E, zc, up):
    keep = [x for x in X if (x[2] >= zc if up else x[2] <= zc)]
    for a, b in E:
        za, zb = X[a][2], X[b][2]
        if (za - zc) * (zb - zc) < 0:
            t = (zc - za) / (zb - za); keep.append(tuple(X[a][r] + t * (X[b][r] - X[a][r]) for r in range(3)))
    return frozenset(keep)

def cell_job(args):
    word, i, lam = args
    spec = net_for(word); net = Net(word, spec['G'], spec['T'], spec['motif'], spec['w'])
    c = Cell(net, i, (lam,), Fr(12))
    if c.empty: return (word, i, lam, None)
    X = corners_at(c, lam); E = edges(c); F = c.faces()
    faces = [[X[c.corners.index(p)] for p in pts] for pts in F.values()]
    return (word, i, lam, {'X': X, 'E': E, 'faces': faces})

def same_mod(A, B):   # point sets equal up to one lattice translation (A, B frozensets of points)
    if A is None or B is None: return A is None and B is None
    if len(A) != len(B): return False
    a0 = min(A);
    for b0 in B:
        t = tuple(b0[r] - a0[r] for r in range(3))
        if any(x.denominator != 1 for x in t): continue
        if frozenset(tuple(p[r] + t[r] for r in range(3)) for p in A) == B: return True
    return False

def piece_tests(word, k, lam, cells):
    """cells[(i)] = dict or None for the sites of this word at lam. Sites of gap g: 3g (oct, mid), 3g+1 (tet over X at 3/4), 3g+2 (tet at 1/4)."""
    n = len(word); zk = Fr(k, n); gu, gd = k % n, (k - 1) % n
    res = {}
    for name, g in maps(word, k).items():
        if name == 'mid': continue
        # near halves of oct pieces: bottom half of gap k (cut at its hole's plane) vs top half of gap k-1
        def lift(i, gap_shift):  # corners of cell i, shifted by gap_shift periods in z (to place gap k-1 below layer k when k = 0)
            c = cells[i]
            if c is None: return None
            return {'X': [(x[0], x[1], x[2] + gap_shift) for x in c['X']], 'E': c['E'],
                    'faces': [[(x[0], x[1], x[2] + gap_shift) for x in f] for f in c['faces']]}   # fixed 13 Nov: faces shifted too
        sd = -1 if k == 0 else 0
        up_oct = lift(3 * gu, 0); dn_oct = lift(3 * gd, sd)
        zo_u = Fr(2 * k + 1, 2 * n); zo_d = Fr(2 * k - 1, 2 * n)
        hu = half(up_oct['X'], up_oct['E'], zo_u, False) if up_oct else None
        hd = half(dn_oct['X'], dn_oct['E'], zo_d, True) if dn_oct else None
        img = frozenset(g(x) for x in hu) if hu is not None else None
        oct_half = same_mod(img, hd)
        tu = lift(3 * gu + 2, 0); td = lift(3 * gd + 1, sd)       # tets nearest layer k
        tet = same_mod(frozenset(g(x) for x in tu['X']) if tu else None, frozenset(td['X']) if td else None)
        whole_oct = same_mod(frozenset(g(x) for x in up_oct['X']) if up_oct else None, frozenset(dn_oct['X']) if dn_oct else None)
        res[name] = {'oct_near_halves': oct_half, 'tet_near': tet, 'oct_whole': whole_oct}
    # negative control: the gap mid-plane mirror maps gap k's top tet to its bottom tet? (never: X != Y positions)
    g = maps(word, k)['mid']; c1, c2 = cells[3 * gu + 1], cells[3 * gu + 2]
    res['mid'] = {'tet_pair': same_mod(frozenset(g(x) for x in c1['X']) if c1 else None, frozenset(c2['X']) if c2 else None)}
    # T5: pieces of gaps k-1, k with corners / edges / faces IN the layer plane z = zk
    census = {}
    for gap, sh in ((gu, 0), (gd, sd)):
        for j, kind in ((0, 'oct'), (1, 'tet_far' if gap == gd else 'tet_far'), (2, 'tet')):
            c = lift(3 * gap + j, sh)
            if c is None: continue
            kname = ('oct' if j == 0 else ('tet_near' if (gap == gu and j == 2) or (gap == gd and j == 1) else 'tet_far'))
            X = c['X']; on = [x for x in X if x[2] == zk]
            ed = [e for e in c['E'] if X[e[0]][2] == zk and X[e[1]][2] == zk]
            fc = [f for f in c['faces'] if all(x[2] - sh * 0 == zk for x in f)]
            cross = any((x[2] - zk) * (y[2] - zk) < 0 for x in X for y in X)
            key = f"{'up' if gap == gu else 'down'}_{kname}"
            census[key] = {'corners_on': len(on), 'edges_on': len(ed), 'faces_on': len(fc), 'crosses_plane': cross}
    return res, census

def main():
    t0 = time.time(); checks = []; out = {'words': {}, 'lams': [str(l) for l in LAMS]}
    def chk(ok, msg):
        checks.append((ok, msg))
        if not ok: print('CHECK FAIL', msg, flush=True)
    # T1-T3
    for w in WORDS:
        T = types(w); rows = []
        for k in range(len(w)):
            bt = ball_tests(w, k); sg = site_group(w, k)
            rows.append({'k': k, 'type': T[k], 'balls': bt, 'site_group': sg})
            chk(bt['sigma']['local'] == (T[k] == 'h'), f'{w} layer {k} ({T[k]}): mirror of the triple iff h')
            chk(bt['iota']['local'] == (T[k] == 'c'), f'{w} layer {k} ({T[k]}): inversion of the triple iff c')
            chk(not bt['mid']['local'], f'{w} layer {k}: gap mid-plane mirror is never a symmetry (negative control)')
            pal = all(w[(k + e) % len(w)] == w[(k - e) % len(w)] for e in range(len(w)))
            chk(bt['sigma']['global'] == pal, f'{w} layer {k}: global mirror iff word palindromic about k')
            chk(sg['sigma_h'] == (T[k] == 'h') and sg['inversion'] == (T[k] == 'c'), f'{w} layer {k}: site group has sigma_h iff h, -I iff c')
            chk(sg['order'] == 12 and sg['coxeter'] == (T[k] == 'h'), f'{w} layer {k}: site group order 12, generated by reflections iff h')
        out['words'][w] = {'types': ''.join(T), 'layers': rows}
    print(f'PROGRESS 0.05 ball and site-group tests done ({len(checks)} checks)', flush=True)
    # T4-T5: cells
    jobs = [(w, i, lam) for w in WORDS for lam in LAMS for i in range(3 * len(w))]
    cells = {}; done = 0
    with Pool(int(os.environ.get('NPROC', '8'))) as pool:
        for w, i, lam, c in pool.imap_unordered(cell_job, jobs, chunksize=2):
            cells[(w, i, lam)] = c; done += 1
            if done % max(1, len(jobs) // 20) == 0: print(f'PROGRESS {0.05 + 0.85 * done / len(jobs):.2f} cells {done}/{len(jobs)} ({time.time() - t0:.0f} s)', flush=True)
    tally = {}
    for w in WORDS:
        T = types(w); out['words'][w]['pieces'] = []
        for lam in LAMS:
            cw = {i: cells[(w, i, lam)] for i in range(3 * len(w))}
            for k in range(len(w)):
                r, cen = piece_tests(w, k, lam, cw)
                out['words'][w]['pieces'].append({'k': k, 'type': T[k], 'lam': str(lam), 'maps': r, 'plane_census': cen})
                t = T[k]
                # predictions: near halves and near tets mapped by sigma iff h, by iota iff c (when the pieces exist)
                present = cw[3 * (k % len(w))] is not None
                if present:
                    chk(r['sigma']['oct_near_halves'] == (t == 'h'), f'{w} k={k} lam={lam}: sigma maps near oct halves iff h')
                    chk(r['iota']['oct_near_halves'] == (t == 'c'), f'{w} k={k} lam={lam}: iota maps near oct halves iff c')
                if cw[3 * (k % len(w)) + 2] is not None:
                    chk(r['sigma']['tet_near'] == (t == 'h'), f'{w} k={k} lam={lam}: sigma maps near tets iff h')
                    chk(r['iota']['tet_near'] == (t == 'c'), f'{w} k={k} lam={lam}: iota maps near tets iff c')
                if cw[3 * (k % len(w)) + 1] is not None: chk(not r['mid']['tet_pair'], f'{w} k={k} lam={lam}: mid-plane control fails')
                n = len(w); lo, hi = T[(k - 1) % n], T[(k + 1) % n]
                key = (t, lo + t + hi, str(lam))
                tally.setdefault(key, {'sigma_whole_oct': set(), 'census': []})
                tally[key]['sigma_whole_oct'].add((r['sigma']['oct_whole'], r['iota']['oct_whole']))
                tally[key]['census'].append(cen)
                if t == 'h': chk(not any(c['crosses_plane'] for c in cen.values()), f'{w} k={k} lam={lam}: no piece crosses an h layer plane (mirror argument)')
                fu = sum(c['faces_on'] for kk, c in cen.items() if kk.startswith('up')); fd = sum(c['faces_on'] for kk, c in cen.items() if kk.startswith('down'))
                chk(fu == fd, f'{w} k={k} lam={lam}: faces on the layer plane equal above and below ({fu}, {fd})')
                if t == 'c': chk(fu == 0, f'{w} k={k} lam={lam}: no piece face in a c layer plane (observed in the pilot)')
    # summarise T5 by layer type: does any piece have a FACE in the layer plane? edges? does any cross it?
    summ = {}
    for (t, win, lam), v in tally.items():
        s = summ.setdefault(t, {'faces_on': set(), 'edges_on': set(), 'crossing': set(), 'crossing_at_lam': set(), 'whole_oct_maps': set()})
        for cen in v['census']:
            for key, c in cen.items():
                s['faces_on'].add((key, c['faces_on'])); s['edges_on'].add((key, c['edges_on'])); s['crossing'].add((key, c['crosses_plane']))
                if c['crosses_plane']: s['crossing_at_lam'].add((lam, key))
        s['whole_oct_maps'] |= {(win, a, b) for a, b in v['sigma_whole_oct']}
    out['plane_summary'] = {t: {k2: sorted(map(str, v2)) for k2, v2 in s.items()} for t, s in summ.items()}
    for t, s in out['plane_summary'].items():
        print(f'== layer type {t}:'); [print(f'   {k2}: {v2}') for k2, v2 in s.items()]
    nok = sum(1 for o, _ in checks if o); nbad = len(checks) - nok
    out['checks'] = {'ok': nok, 'fail': nbad, 'failures': [m for o, m in checks if not o][:50]}
    json.dump(out, open(os.path.join(HERE, '..', 'data', f'{MODE}.json'), 'w'), indent=1, default=str)
    print(f'PROGRESS 1.00 {nok} checks ok, {nbad} failed, {time.time() - t0:.0f} s', flush=True)
    sys.exit(0 if nbad == 0 else 1)

if __name__ == '__main__':
    main()
