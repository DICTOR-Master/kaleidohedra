# Mirror <-> Hexagonality link (13 Nov 2026; queued 11 Nov with DICTO's yes; swaps-and-fixed-points LEAD 1).
# Question: in a close-packed stacking, is an h layer (neighbours equal, ABA) a MIRROR of its surroundings and a c layer (ABC) an
# off-mirror exchange, as in the Mirror Law (#107: faces between like cells on mirrors, middle-bond faces off them)? And does that
# carry the Hexagonality Law (#66, #67)?
# Exact rational arithmetic throughout: fractional coordinates (a1, a2 at 60 degrees, z in units of the cell height), metric G of
# stackings.net_for, the power cells of the census engine (../../2026-10-25-stackings/scripts/engine.py: floats only choose
# candidate corners, every corner solved and tested exactly). Equality of point sets is exact, modulo the lattice.
# Maps through layer k (height z_k):  sigma_k (a, b, z) -> (a, b, 2 z_k - z)            the horizontal mirror
#                                     iota_k  (a, b, z) -> (2p - (a, b), 2 z_k - z)      inversion through a ball p of layer k
#                                     mid_k   mirror through the mid-plane of gap k      (negative control: never a symmetry)
# Tests per layer k of each word: T1 the three layers k-1, k, k+1 (balls) are mapped onto themselves; T2 the whole periodic stacking;
# T3 the site group of a ball (24 candidate point operations) and whether its reflections generate it (a Coxeter group = Wythoff);
# T4 the hole pieces at sampled weights lam: the near halves of the octahedral pieces of gaps k-1 and k, the near tetrahedral pieces
# (whole, #57) and the whole pieces; T5 faces, edges and corners of pieces lying IN the layer plane z = z_k (Mirror Law census).
# Usage: mirror_hex.py pilot|full  -> PROGRESS lines, data/<mode>.json, FINAL ok only if every prediction and control holds.
