"""Item 5, exact: Proposition 5 (half-cats): all 25 x 60 x 60 = 90,000 cases.
S5s in a 600-cell: the groups generated by an A4 set of its reflections
(chain r1-r2-r3-r4, consecutive roots at 120 deg, others at 90 deg), found
by enumerating every such chain; distinct groups are told apart by their
20 roots.  Orbits under each S5 are computed from the exact reflection
permutations.  Orbit kinds: the root orbit (C3), the two other 20-orbits
(A-type: A and -A), the two 30-orbits (B-type: B and -B)."""
import gzip, collections
from common import *

L = Log('logs/s5_prop5.log')
B = load_base()
Q = B['Q']
RQ2 = B['RQ2']
D = np.load('data/thmB.npz')
Pi, state = D['Pi'], D['state']
GQ = gram(Q)
half = zmul(RQ2, np.array([1, 0])) // 2
M120 = -half

def s5s_of(s):
    X = Q[s]
    ix = {canon_point(x): i for i, x in enumerate(X)}
    refl = [reflect_perm(X, X[k], ix) for k in range(120)]
    assert all(r is not None for r in refl)
    G = GQ[np.ix_(s, s)]
    is120 = zeq(G, M120[None, None])
    is90 = zeq(G, np.zeros(2, int)[None, None])
    groups = {}
    for r2 in range(120):
        for r3 in np.nonzero(is120[r2])[0]:
            for r1 in np.nonzero(is120[r2] & is90[r3])[0]:
                for r4 in np.nonzero(is120[r3] & is90[r1] & is90[r2])[0]:
                    R = {r1, r2, r3, r4}
                    while True:
                        new = R | {int(refl[a][b]) for a in R for b in R}
                        if new == R:
                            break
                        R = new
                    key = tuple(sorted(R))
                    if key not in groups:
                        groups[key] = (r1, r2, r3, r4)
    out = []
    for key, ch in sorted(groups.items()):
        gens = [refl[r] for r in ch]
        order = len(close_group(gens))
        # orbits
        lab = -np.ones(120, int)
        orbs = []
        for v in range(120):
            if lab[v] >= 0:
                continue
            st, o = [v], set()
            while st:
                x = st.pop()
                if x in o:
                    continue
                o.add(x)
                st += [int(g[x]) for g in gens]
            for x in o:
                lab[x] = len(orbs)
            orbs.append(sorted(o))
        roots = set(key)
        kind = []
        for o in orbs:
            if set(o) == roots:
                kind.append('C3')
            elif len(o) == 20:
                kind.append('A')
            elif len(o) == 30:
                kind.append('B')
            else:
                kind.append('?')
        out.append(dict(roots=key, order=order, orbs=[[s[x] for x in o] for o in orbs], kind=kind,
                        lab={s[x]: lab[x] for x in range(120)}))
    return out

S5 = [s5s_of(list(s)) for s in Pi]
L.check('S5s per 600-cell', [len(x) for x in S5], [60] * 10)
L.check('each generated group has order 120', {g['order'] for x in S5 for g in x}, {120})
L.check('orbit sizes of every S5', {tuple(sorted(len(o) for o in g['orbs'])) for x in S5 for g in x},
        {(20, 20, 20, 30, 30)})
L.check('kinds of orbits', {tuple(sorted(g['kind'])) for x in S5 for g in x}, {('A', 'A', 'B', 'B', 'C3')})
# the orbits are exactly the copies of Theorem B (b)
cA = {tuple(sorted(c)) for c in D['copiesA']}
cB = {tuple(sorted(c)) for c in D['copiesB']}
cC = {tuple(sorted(c)) for c in D['copiesC3']}
oA = [tuple(o) for x in S5 for g in x for o, k in zip(g['orbs'], g['kind']) if k == 'A']
oB = [tuple(o) for x in S5 for g in x for o, k in zip(g['orbs'], g['kind']) if k == 'B']
oC = [tuple(o) for x in S5 for g in x for o, k in zip(g['orbs'], g['kind']) if k == 'C3']
L.check('A-type orbits = the 1200 A copies, each from one S5', (len(oA), set(oA) == cA), (1200, True))
L.check('B-type orbits = the 1200 B copies, each from one S5', (len(oB), set(oB) == cB), (1200, True))
L.check('C3 orbits = the 600 C3 copies, each from one S5', (len(oC), set(oC) == cC), (600, True))

first = [i for i in range(10) if state[i] == 0]
second = [i for i in range(10) if state[i] == 1]
inc = np.zeros((10, 600), bool)
for i, s in enumerate(Pi):
    inc[i, s] = True
# split of the 5 shared 24-cells for each S5 of each 600-cell
splits = set()
for i in range(10):
    others = [j for j in range(10) if state[j] != state[i]]
    for g in S5[i]:
        sp = []
        for j in others:
            T = np.nonzero(inc[i] & inc[j])[0]
            c = collections.Counter(g['kind'][g['lab'][x]] for x in T)
            sp.append((c['A'], c['C3'], c['B']))
        splits.add(tuple(sorted(sp)))
L.check('every S5 of every 600-cell splits its 5 shared 24-cells as (A,C3,B)',
        splits, {tuple(sorted([(0, 12, 12)] + [(10, 2, 12)] * 4))})

# the 90,000 cases
KT = {'A': 'A', 'B': 'B', 'C3': 'C3'}
patterns_type = {}
patterns_orb = {}
rows = []
n_typematch = n_partmatch = 0
n_case = 0
for i in first:
    for j in second:
        T = np.nonzero(inc[i] & inc[j])[0]
        assert len(T) == 24
        for a, g in enumerate(S5[i]):
            for b, h in enumerate(S5[j]):
                n_case += 1
                ka = [g['kind'][g['lab'][x]] for x in T]
                kb = [h['kind'][h['lab'][x]] for x in T]
                pt = tuple(sorted(collections.Counter(zip(ka, kb)).items()))
                pid = patterns_type.setdefault(pt, len(patterns_type))
                tm = ka == kb
                # partition of T by orbits in g vs in h
                pa = {frozenset(x for x in T if g['lab'][x] == g['lab'][y]) for y in T}
                pb = {frozenset(x for x in T if h['lab'][x] == h['lab'][y]) for y in T}
                pm = pa == pb
                # orbit-level pattern: sizes of the blocks of the common refinement,
                # labelled by kinds (independent of the A/-A, B/-B naming)
                blocks = collections.Counter()
                for y in T:
                    blocks[(g['kind'][g['lab'][y]], h['kind'][h['lab'][y]], g['lab'][y], h['lab'][y])] += 1
                po = tuple(sorted(collections.Counter((k1, k2, n) for (k1, k2, _, _), n in blocks.items()).items()))
                oid = patterns_orb.setdefault(po, len(patterns_orb))
                n_typematch += tm
                n_partmatch += pm
                rows.append((i, j, a, b, pid, oid, int(tm), int(pm)))
L.check('cases', n_case, 90000)
L(f'distinct patterns of (kind in first, kind in second) counts [kinds A-type, C3, B-type]: {len(patterns_type)}')
L(f'distinct patterns at orbit level (blocks of the common refinement, by kinds and size): {len(patterns_orb)}')
L(f'cases where every corner has the same kind in both: {n_typematch}')
L(f'cases where the two S5s cut the 24-cell into the same orbit pieces: {n_partmatch}')
both = sum(1 for r in rows if r[6] and r[7])
L(f'cases with both: {both}')
with gzip.open('data/prop5_cases.csv.gz', 'wt') as f:
    f.write('P_first,P_second,S5_first,S5_second,kind_pattern,orbit_pattern,same_kind_every_corner,same_orbit_pieces\n')
    for r in rows:
        f.write(','.join(map(str, r)) + '\n')
cntp = collections.Counter(r[4] for r in rows)
cnto = collections.Counter(r[5] for r in rows)
with open('data/prop5_patterns.txt', 'w') as f:
    f.write('# kind patterns: id, cases, {(kind first, kind second): corners}\n')
    for pt, pid in patterns_type.items():
        f.write(f'K{pid}\t{cntp[pid]}\t{dict(pt)}\n')
    f.write('# orbit-level patterns: id, cases, {(kind first, kind second, block size): number of blocks}\n')
    for po, oid in patterns_orb.items():
        f.write(f'O{oid}\t{cnto[oid]}\t{dict(po)}\n')
L('pattern tables written to data/prop5_patterns.txt')

# per-pair matched cases: for each S5 in the first state, how many in the second match
per = collections.Counter()
for r in rows:
    if r[6]:
        per[(r[0], r[1], r[2])] += 1
L(f'for each (pair, first S5): number of second S5 with the same kinds: {sorted(set(per.values()))}, '
  f'over {len(per)} of {25*60}')

# copies from the two states: shared corners and shared walls
def incm(c):
    M = np.zeros((len(c), 600), np.int32)
    for k, cc in enumerate(c):
        M[k, cc] = 1
    return M

def wallm(pl):
    M = np.zeros((len(pl), 1560), np.int32)
    for k, p in enumerate(pl):
        M[k, list(set(p.tolist()))] = 1
    return M

data = {}
for nm in ['A', 'B', 'C3']:
    c = D['copies' + nm]
    h = D['host' + nm]
    st = state[h]
    data[nm] = (incm(c), wallm(D['plates' + nm]), st)
for x, y in [('A', 'A'), ('A', 'B'), ('B', 'B'), ('A', 'C3'), ('B', 'C3'), ('C3', 'C3')]:
    Ix, Wx, sx = data[x]
    Iy, Wy, sy = data[y]
    m0, m1 = sx == 0, sy == 1
    corners = Ix[m0] @ Iy[m1].T
    walls = Wx[m0] @ Wy[m1].T
    L(f'{x} (first state) vs {y} (second state): shared corners max {corners.max()}, '
      f'shared walls min {walls.min()} max {walls.max()}')
    if x == 'C3' or y == 'C3':
        continue
    want = {'AA': 2, 'AB': 1, 'BB': 5}[x + y]
    L.check(f'{x}-{y}: max shared corners <= 6', bool(corners.max() <= 6), True)
    L.check(f'{x}-{y}: min shared walls', int(walls.min()), want)
mx = max(int((data[x][0][data[x][2] == 0] @ data[y][0][data[y][2] == 1].T).max())
         for x in ['A', 'B'] for y in ['A', 'B'])
L.check('A and B copies from the two states share at most 6 corners (max over all pairs)', mx, 6)
L('NOTE: the bound 6 is for A and B copies; two C3 copies from the two states can share 12 corners '
  '(and share 0 walls), see the lines above.')
L.final()
