"""Base objects, exact: the 600-cell P0 from the paper's five S5-orbits, its
reflection group W(H4) as permutations of the 120 corners, its cells, the
dual 120-cell Q (corners = cell centres), Q's pentagons, and the wall sets.
Writes cache/base.npz (large, not copied back)."""
import os, sys
import numpy as np
from common import *

os.makedirs('cache', exist_ok=True)
L = Log('logs/s0_base.log')
P, lab = build_P0()
L('P0 corners:', len(P), {k: int((lab == k).sum()) for k in sorted(set(lab))})
idx = {canon_point(p): i for i, p in enumerate(P)}
L.check('P0 corners distinct', len(idx), 120)
G = gram(P)
nrm = G[np.arange(120), np.arange(120)]
L.check('all corners on one sphere (|y|^2 = 50 phi^2, i.e. radius phi*sqrt2 at scale 5)',
        bool(np.all(nrm == np.array([50, 50]))), True)
R2 = np.array([50, 50])
EDGE_IP = np.array([25, 50])      # R^2 cos36 = 50 phi^2 * phi/2 = 25 phi^3
uniq, lbl = value_labels(G)
L('distinct inner products (a,b)=a+b*phi:', [tuple(int(t) for t in u) for u in uniq])
adj = zeq(G, EDGE_IP[None, None])
L.check('every corner has 12 neighbours at the edge angle (36 deg)', set(adj.sum(1).tolist()), {12})
# edge length sqrt2 at scale 5: |a-b|^2 = 2R^2 - 2 a.b = 50
L.check('edge^2 = 50 (= 25*2, edge sqrt2)', tuple(2 * R2 - 2 * EDGE_IP), (50, 0))

# reflections in all corners, exact
refl = []
for r in P:
    pm = reflect_perm(P, r, idx)
    assert pm is not None
    refl.append(pm)
refl = np.array(refl)
L.check('P0 closed under reflection in every corner (exact): root system', len(refl), 120)
gens = [refl[i] for i in range(120)]
uniqgens = {tuple(g) for g in gens}
L('distinct reflections:', len(uniqgens))
Wg = close_group([np.array(g) for g in sorted(uniqgens)])
L.check('|W| generated by the reflections (W(H4))', len(Wg), 14400)
# -1 in W
neg = np.array([idx[canon_point(-p)] for p in P])
L.check('-1 in W', any(np.array_equal(g, neg) for g in Wg), True)

edges = [(i, j) for i in range(120) for j in range(i + 1, 120) if adj[i, j]]
tris = cliques(adj, 3)
cells = cliques(adj, 4)
L.check('edges', len(edges), 720)
L.check('edge triangles', len(tris), 1200)
L.check('tetrahedral cells (4-cliques)', len(cells), 600)
cells = np.array(cells)
# exact facet check for the 600 cells: supporting hyperplanes
Pc = P[cells]
D = Pc[:, 1:] - Pc[:, :1]
Rm = np.concatenate([np.broadcast_to(ONES5, (600, 1, 5, 2)), D], axis=1)
n = gcross(Rm)
h = zdot(n, Pc[:, 0])
sg = zsign(zdot(n[:, None], P[None]) - h[:, None])
ok = ~((sg > 0).any(1) & (sg < 0).any(1)) & ((sg == 0).sum(1) == 4)
L.check('each 4-clique is a facet with exactly 4 corners (exact)', int(ok.sum()), 600)
tri_in = {}
for c in cells:
    for t in itertools.combinations(c, 3):
        tri_in[t] = tri_in.get(t, 0) + 1
L.check('each triangle in exactly 2 cells (closed boundary, so these are all facets)',
        set(tri_in.values()), {2})

# Q: the dual 120-cell, corners = cell centres (sum of the 4 corners)
Q = P[cells].sum(axis=1)
qidx = {canon_point(q): i for i, q in enumerate(Q)}
L.check('Q corners distinct', len(qidx), 600)
GQ = gram(Q)
qn = GQ[np.arange(600), np.arange(600)]
L.check('Q corners on one sphere', len(np.unique(qn, axis=0)), 1)
RQ2 = qn[0]
L('|Q corner|^2 =', tuple(RQ2))
# Q edges: cells sharing a triangle
cell_of_tri = {}
for ci, c in enumerate(cells):
    for t in itertools.combinations(c, 3):
        cell_of_tri.setdefault(t, []).append(ci)
qedges = sorted(tuple(sorted(v)) for v in cell_of_tri.values())
L.check('Q edges (dual to triangles)', len(qedges), 1200)
qadj = np.zeros((600, 600), bool)
for a, b in qedges:
    qadj[a, b] = qadj[b, a] = True
L.check('Q: 4 edges at each corner', set(qadj.sum(1).tolist()), {4})
qe_ip = {zkey(GQ[a, b]) for a, b in qedges}
L.check('Q edges all one length (one inner product value)', len(qe_ip), 1)
# pentagons of Q: dual to edges of P0: the 5 cells round an edge
pent = []
for (a, b) in edges:
    cs = [ci for ci, c in enumerate(cells) if a in c and b in c]
    pent.append(cs)
pent = np.array(pent)
L.check('pentagons of Q (5 cells round each P0 edge)', (len(pent), pent.shape[1]), (720, 5))
okp = 0
for pc in pent:
    sub = qadj[np.ix_(pc, pc)]
    if (sub.sum(1) == 2).all():
        okp += 1
L.check('each pentagon is a 5-cycle of Q edges', okp, 720)

# group acting on Q corners (via cells)
cellkey = {tuple(c): i for i, c in enumerate(cells)}
WQ = np.zeros((len(Wg), 600), dtype=np.int16)
for gi, g in enumerate(Wg):
    im = np.sort(g[cells], axis=1)
    WQ[gi] = [cellkey[tuple(r)] for r in im]
L.check('W acts on Q corners as 14400 distinct permutations', len({tuple(r) for r in WQ}), 14400)

# walls
mir = sorted({canon_dir(p) for p in P})
crs = sorted({canon_dir(q) for q in Q})
L.check('mirrors of P0 (normals along corners)', len(mir), 60)
L.check('cross walls of P0 (normals along cell centres)', len(crs), 300)
L.check('no cross wall is a mirror', len(set(mir) & set(crs)), 0)

np.savez_compressed('cache/base.npz', P=P, lab=lab, refl=refl, W=Wg.astype(np.int16),
                    cells=cells, Q=Q, WQ=WQ, edges=np.array(edges), tris=np.array(tris),
                    pent=pent, qedges=np.array(qedges), RQ2=RQ2)
L.final()
