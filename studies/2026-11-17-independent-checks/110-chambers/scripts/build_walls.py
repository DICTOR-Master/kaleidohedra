#!/usr/bin/env python3
"""Build the wall arrangements of #110 exactly in Z[phi] (written from scratch).

P0 = 600-cell, corners scaled to radius 2:  perms of (+-2,0,0,0); (+-1,+-1,+-1,+-1);
even perms of (+-phi, +-1, +-1/phi, 0).  W = W(H4) generated by the reflections in its corners.
A60   : the 60 mirrors of P0 (normals along its corners).
A360  : A60 + the 300 cross walls of P0 (normals along its cell centres = dual 120-cell corners).
Q     : the 120-cell whose corners are P0's 600 cell centres (sums of the 4 corners of a cell);
        W(Q) = W(P0).  P1..P10 : the 600-cells inscribed in Q (on Q's corners).
A1560 : union over i of W(P_i) (60 mirrors + 300 cross walls of each P_i).
Saves data/walls.npz with normals, the 4 simple roots, generator permutations of each arrangement.
"""
import sys, os, json, itertools
import numpy as np
sys.path.insert(0, os.path.dirname(__file__))
import zphi as Z

OUT = sys.argv[1] if len(sys.argv) > 1 else 'data/walls.npz'
log = []
def say(*a):
    s = ' '.join(str(x) for x in a); print(s, flush=True); log.append(s)

def zp(a, b=0): return [a, b]
PHI, IPHI, ONE, ZERO = zp(0, 1), zp(-1, 1), zp(1), zp(0)

# ---- P0 ----
V = set()
for i in range(4):
    for s in (2, -2):
        v = [ZERO] * 4; v[i] = zp(s); V.add(tuple(map(tuple, v)))
for signs in itertools.product((1, -1), repeat=4):
    V.add(tuple(tuple(zp(s)) for s in signs))
base = [PHI, ONE, IPHI, ZERO]
even = [p for p in itertools.permutations(range(4))
        if sum(1 for i in range(4) for j in range(i + 1, 4) if p[i] > p[j]) % 2 == 0]
for p in even:
    for signs in itertools.product((1, -1), repeat=3):
        v = [None] * 4
        k = 0
        for pos in range(4):
            c = base[p[pos]]
            if c == ZERO: v[pos] = (0, 0)
            else: v[pos] = (signs[k] * c[0], signs[k] * c[1]); k += 1
        V.add(tuple(v))
P0 = np.array(sorted(V), dtype=np.int64)
assert P0.shape == (120, 4, 2), P0.shape
nrm = Z.dot(P0, P0)
assert np.all(nrm == [4, 0]), 'P0 not on radius 2'
say('P0 corners', len(P0), 'all with |v|^2 = 4 (exact)')

def adjacency(X):
    """36-degree adjacency: 2 v.w = phi |v|^2  (exact)"""
    G = Z.dot(X[:, None], X[None, :])
    R = Z.dot(X[0], X[0])
    target = Z.times_phi(R[None, :])
    return np.all(2 * G == target, axis=-1)

def cells(X, A):
    out = []
    n = len(X)
    nb = [set(np.nonzero(A[i])[0]) for i in range(n)]
    for i in range(n):
        for j in nb[i]:
            if j <= i: continue
            for k in nb[i] & nb[j]:
                if k <= j: continue
                for l in nb[i] & nb[j] & nb[k]:
                    if l <= k: continue
                    out.append((i, j, k, l))
    return out

A0 = adjacency(P0)
assert np.all(A0.sum(1) == 12)
C0 = cells(P0, A0)
assert len(C0) == 600, len(C0)
centres0 = np.array([P0[list(c)].sum(0) for c in C0])
say('P0: 12 neighbours per corner, 600 tetrahedral cells (exact)')

# ---- the group: simple roots of P0 ----
def refl_vec(r, x):
    """2 * s_r(x) * (r.r)/... : returns (r.r) x - 2 (x.r) r, a positive multiple of s_r(x)"""
    rr = Z.dot(r, r)
    return Z.mul(x, rr[..., None, :] if rr.ndim else rr) - 2 * Z.mul(Z.dot(x, r)[..., None, :], r)

v0 = np.array([1.0, 0.31, 0.071, 0.0113])
fl = Z.tofloat(P0)
pos = [i for i in range(120) if fl[i] @ v0 > 1e-6]
assert len(pos) == 60 and all(abs(fl[i] @ v0) > 1e-6 for i in range(120))
keyP0 = {tuple(P0[i].ravel()): i for i in range(120)}
def s_exact(r, x):        # s_r(x) for r a P0 corner (r.r = 4): x - (x.r)/2 r, exact
    d = Z.dot(x, r)
    assert np.all(d % 2 == 0)
    return x - Z.mul((d // 2)[..., None, :], r)
simple = []
posset = set(pos)
for i in pos:
    img = s_exact(P0[i], P0[pos])
    imgi = [keyP0[tuple(y.ravel())] for y in img]
    if set(imgi) - {keyP0[tuple((-P0[i]).ravel())]} == posset - {i}:
        simple.append(i)
assert len(simple) == 4, simple
alpha = P0[simple]
say('simple roots (indices into P0):', simple, 'Gram (a+b*phi):',
    Z.dot(alpha[:, None], alpha[None, :]).tolist())

# ---- Q and its inscribed 600-cells ----
Qv = centres0.copy()                    # 600 corners, all same norm
qn = Z.dot(Qv, Qv); assert np.all(qn == qn[0])
assert len({tuple(x.ravel()) for x in Qv}) == 600
keyQ = {tuple(Qv[i].ravel()): i for i in range(600)}
genQ = []
for a in alpha:
    img = s_exact(a, Qv)
    genQ.append(np.array([keyQ[tuple(y.ravel())] for y in img]))
AQ = adjacency(Qv)
say('Q: 600 corners; 36-degree neighbours per corner:', sorted(set(AQ.sum(1).tolist())))
nb = [set(np.nonzero(AQ[i])[0]) for i in range(600)]
def split12(i):
    rest = set(nb[i]); comps = []
    while rest:
        s = rest.pop(); comp = {s}; stack = [s]
        while stack:
            x = stack.pop()
            for y in nb[x] & rest:
                rest.discard(y); comp.add(y); stack.append(y)
        comps.append(comp)
    return comps
comps0 = split12(0)
assert sorted(len(c) for c in comps0) == [12, 12], [len(c) for c in comps0]
assert not any(AQ[a, b] for a in comps0[0] for b in comps0[1])
def grow(start, first12):
    """BFS: x's neighbours in P are the 12-set of x that contains a known P-neighbour."""
    P = {start}; nbP = {start: first12}; queue = [start]
    while queue:
        x = queue.pop()
        for y in nbP[x]:
            if y not in nbP:
                cs = split12(y)
                c = [c for c in cs if x in c]; assert len(c) == 1
                nbP[y] = c[0]; queue.append(y)
    return sorted(nbP)
P1 = grow(0, comps0[0])
assert len(P1) == 120, len(P1)
# exact check: P1 is a 600-cell: closed under its own reflections (s_u(x) = x - 2(x.u)/(u.u) u)
X = Qv[P1]; keyX = {tuple(x.ravel()) for x in X}
uu = Z.dot(X[0], X[0])                     # common norm (a, b)
Nn = uu[0] ** 2 + uu[0] * uu[1] - uu[1] ** 2
conj = np.array([uu[0] + uu[1], -uu[1]])   # uu * conj = Nn (rational)
closed = True
for u in X:
    c = Z.mul(2 * Z.dot(X, u), conj[None, :])          # 2(x.u)/(u.u) = c / Nn
    y = Nn * X - Z.mul(c[:, None, :], u[None, :, :])   # Nn * s_u(x)
    if np.any(y % Nn != 0): closed = False; break
    for yy in (y // Nn):
        if tuple(yy.ravel()) not in keyX: closed = False; break
say('P1 grown from corner 0: 120 corners; closed under its own 120 reflections (exact):', closed)
assert closed
# all inscribed 600-cells = W-orbit of P1
orbit = {tuple(P1)}; queue = [tuple(P1)]
while queue:
    s = queue.pop()
    for g in genQ:
        t = tuple(sorted(int(g[i]) for i in s))
        if t not in orbit: orbit.add(t); queue.append(t)
Ps = sorted(orbit)
cover = np.zeros(600, int)
for s in Ps: cover[list(s)] += 1
say('inscribed 600-cells in the W-orbit of P1:', len(Ps), '; corners covered', sorted(set(cover.tolist())), 'times')
# also: from every corner exactly 2 (the two 12-sets) -- check both 12-sets of corner 0 grow 600-cells in the orbit
P1b = grow(0, comps0[1])
say('second 12-set of corner 0 grows a 600-cell in the orbit:', tuple(P1b) in orbit)

# ---- walls ----
class Arr:
    def __init__(self):
        self.keys = {}; self.normals = []; self.tags = []
    def add(self, vecs, tag):
        ks = Z.canon(vecs)
        for v, k in zip(vecs, ks):
            k = tuple(k)
            if k not in self.keys:
                self.keys[k] = len(self.normals); self.normals.append(Z.reduce(v)); self.tags.append(set())
            self.tags[self.keys[k]].add(tag)
    def arr(self): return np.array(self.normals)

A60 = Arr(); A60.add(P0, 'P0mirror')
A360 = Arr(); A360.add(P0, 'P0mirror'); A360.add(centres0, 'P0cross')
say('A60:', len(A60.normals), ' A360:', len(A360.normals))
A1560 = Arr()
A1560.add(P0, 'Qmirror')            # Q's mirrors (normals = corners of the dual 600-cell P0)
A1560.add(Qv, 'Qaxis')              # Q's corner-axis walls
nQ = len(A1560.normals)
for i, s in enumerate(Ps):
    Xi = Qv[list(s)]
    Ai = adjacency(Xi); assert np.all(Ai.sum(1) == 12)
    Ci = cells(Xi, Ai); assert len(Ci) == 600
    ci = np.array([Xi[list(c)].sum(0) for c in Ci])
    A1560.add(Xi, f'P{i}mirror'); A1560.add(ci, f'P{i}cross')
allwalls = len(A1560.normals)
say('W(Q) walls:', nQ, ' union of W(P_i):', allwalls)
# is W(Q) inside the union? walls of the union only from P_i:
onlyQ = [t for t in A1560.tags if not any(x.startswith('P') for x in t)]
say('walls of W(Q) that are in no W(P_i):', len(onlyQ))
from collections import Counter
def cls(t):
    q = 'M' if 'Qmirror' in t else ('X' if 'Qaxis' in t else 'N')
    nm = sum(1 for x in t if x.endswith('mirror') and x.startswith('P'))
    nc = sum(1 for x in t if x.endswith('cross') and x.startswith('P'))
    return (q, nm, nc)
cc = Counter(cls(t) for t in A1560.tags)
say('classes (Q-class, #P_i with it as mirror, #P_i with it as cross wall): count')
for k, v in sorted(cc.items()): say('   ', k, v)
# the 1560 arrangement must equal A360 (as W(Q)) plus 1200 more
same360 = set(A360.keys) <= set(A1560.keys)
say('A360 (= W(Q) as hyperplanes) contained in A1560:', same360)

def gens_on(arr):
    N = arr.arr(); out = []
    for a in alpha:
        img = refl_vec(a, N)
        ks = Z.canon(img)
        out.append(np.array([arr.keys[tuple(k)] for k in ks]))
    return out

res = {}
for name, arr in (('A60', A60), ('A360', A360), ('A1560', A1560)):
    g = gens_on(arr)
    for p in g: assert sorted(p.tolist()) == list(range(len(p)))
    res[name] = arr.arr(); res[name + '_gens'] = np.array(g)
    # pairwise distinctness re-check (exact canonical keys unique)
    ks = Z.canon(arr.arr()); assert len({tuple(k) for k in ks}) == len(ks)
res['alpha'] = alpha
np.savez(OUT, **res)
json.dump(dict(log=log, classes={str(k): v for k, v in cc.items()}), open(OUT.replace('.npz', '_build.json'), 'w'), indent=1)
ok = (len(A60.normals) == 60 and len(A360.normals) == 360 and allwalls == 1560 and len(Ps) == 10
      and set(cover.tolist()) == {2} and same360)
print('FINAL ok' if ok else 'FINAL FAIL arrangement sizes')
