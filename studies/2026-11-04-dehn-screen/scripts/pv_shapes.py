"""Generate krp-core src/polyhedra/narcissus-echo.js (DICTO 4 Nov 2026: Narcissus and Echo in Polyhedraverse). Corners from the HexOct tiles at λ = 3/8 (tiles.py,
exact build; Narcissus = h-tile piece, Echo = c-tile piece), Cartesian (layer height √(2/3)), centred on the corner centroid, scaled to circumradius 1.1 (PV display size,
proportions intact). Faces: convex hull, each face's corners ordered counter-clockwise seen from outside."""
import os, sys, math, json, numpy as np
from fractions import Fraction as Fr
from scipy.spatial import ConvexHull
HEX = os.path.expanduser('~/kres-tmp/hexoct-scripts'); sys.path.insert(0, HEX); here = os.getcwd(); os.chdir(HEX)
import tiles as T
os.chdir(here); H = math.sqrt(2/3)
def cart(p): return np.array([float(p[0]) + float(p[1])/2, float(p[1])*math.sqrt(3)/2, float(p[2])*H])
def piece(word, L):
    os.chdir(HEX); pcs, _ = T.tile(word, L, Fr(3, 8)); os.chdir(here)
    return np.unique(np.round(np.array([cart(p) for p in pcs[0][3]]), 12), axis=0)
def spec(P, name):
    P = P - P.mean(0); P = P*(1.1/np.max(np.linalg.norm(P, axis=1))); h = ConvexHull(P); fs = {}
    for eq, s in zip(h.equations, h.simplices): fs.setdefault(tuple(np.round(eq, 7)), set()).update(s)
    F = []
    for k, idx in fs.items():
        n = np.array(k[:3]); idx = list(idx); c = P[idx].mean(0); u = P[idx[0]] - c; w = np.cross(n, u)
        F.append([int(x) for x in sorted(idx, key=lambda i: math.atan2((P[i] - c) @ w, (P[i] - c) @ u))])   # CCW about the outward normal
    return {'name': name, 'vertices': np.round(P, 12).tolist(), 'faces': F}
R = {'DICTO_NARCISSUS': spec(piece('AB', 0), 'Narcissus'), 'DICTO_ECHO': spec(piece('ABC', 1), 'Echo')}
for k, v in R.items(): print(k, len(v['vertices']), 'corners', sorted(len(f) for f in v['faces']))
hdr = """// Generated by k-research studies/2026-11-04-dehn-screen/scripts/pv_shapes.py (DICTO 2026-11-04). Do not edit.
// Narcissus and Echo (DICTO's names, 4 November 2026): the two pieces the HexOct layer tiles (#75) reach once the stretch saturates (λ ≥ 3/8):
// Narcissus fills an h layer (two copies per h-tile), Echo a c layer (two copies per c-tile). Narcissus is its own mirror image (three mirror planes),
// so copies of one piece fill space. Corners from the exact build, centred, shown at circumradius 1.1 (proportions intact). Credit: DICTO. CC BY-SA 4.0.
import { specOf } from './stellaJewel.js';
"""
js = hdr + 'const RAW = ' + json.dumps(R, separators=(',', ':')) + ';\n' + \
 "export const NARCISSUS_ECHO_ADDITIONS = Object.fromEntries(Object.entries(RAW).map(([id, p]) => [id, specOf(id, p.name, p.vertices, p.faces, false, 1)]));\n" + \
 "export const NARCISSUS_ECHO_IDS = ['DICTO_NARCISSUS', 'DICTO_ECHO'];\n"
open('data/narcissus-echo.js', 'w').write(js); print('written', len(js), 'bytes')
E = np.array(R['DICTO_ECHO']['vertices']); F = R['DICTO_ECHO']['faces']
def para(f):
    a, b, c, d = (E[i] for i in f); return np.allclose(a + c, b + d, atol=1e-9)
print('Echo faces parallelograms:', [para(f) for f in F])
L = sorted({round(float(np.linalg.norm(E[f[i]] - E[f[(i + 1) % 4]])), 9) for f in F for i in range(4)}); print('Echo edge lengths:', L)
ang = sorted({round(math.degrees(math.acos(np.clip((E[f[1]] - E[f[0]]) @ (E[f[3]] - E[f[0]])/np.linalg.norm(E[f[1]] - E[f[0]])/np.linalg.norm(E[f[3]] - E[f[0]]), -1, 1))), 4) for f in F})
print('Echo face corner angles:', ang)
