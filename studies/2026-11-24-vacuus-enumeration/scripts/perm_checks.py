"""Exact checks for the three 3D permutahedra and their duals (24 Nov 2026).

Coxeter mirrors: for a permutahedron, the symmetry mirrors that carry no corner (for the
truncated octahedron these are the 6 mirrors of A3; its 3 coordinate mirrors carry corners).
For a dual (Catalan), the mirrors that carry no face-normal direction.
W = the group generated by the Coxeter mirrors' reflections (closure of exact matrices).
"""
from vacuus_exact import dot, vsub, scal, vkey

def refl_matrix(m):
    mm = dot(m, m)
    I = [[1 if i == j else 0 for j in range(3)] for i in range(3)]
    return tuple(tuple(I[i][j] - 2 * m[i] * m[j] / mm for j in range(3)) for i in range(3))

def mmul(A, B):
    return tuple(tuple(sum((A[i][k] * B[k][j] for k in range(3)), A[0][0] * 0) for j in range(3)) for i in range(3))

def mkey(F, A): return tuple(F.key(x) for row in A for x in row)

def closure(F, gens):
    one = F.one; z = F.zero
    I = tuple(tuple(one if i == j else z for j in range(3)) for i in range(3))
    seen = {mkey(F, I): I}; frontier = [I]
    while frontier:
        nf = []
        for A in frontier:
            for g in gens:
                B = mmul(g, A); k = mkey(F, B)
                if k not in seen: seen[k] = B; nf.append(B)
        frontier = nf
    return list(seen.values())

def apply(A, v): return tuple(sum((A[i][k] * v[k] for k in range(3)), v[0] * 0) for i in range(3))

def order(F, A):
    B = A
    for k in range(1, 13):
        if all((B[i][j] == (F.one if i == j else F.zero)) for i in range(3) for j in range(3)):
            return k
        B = mmul(A, B)
    return None

def perm_extra(F, V, edges, faces, mirrors, keys):
    cox = [m for m in mirrors.values() if all(F.sign(dot(m, v)) != 0 for v in V)]
    W = closure(F, [refl_matrix(m) for m in cox])
    sv = [tuple(F.sign(dot(m, v)) for m in cox) for v in V]
    one_per_chamber = len(set(sv)) == len(V) == len(W)
    orbit = {vkey(F, apply(A, V[0])) for A in W}
    transitive = len(orbit) == len(V)
    cross_ok = True; refl_ok = True
    emir = {}
    for a, b in edges:
        ch = [i for i in range(len(cox)) if sv[a][i] != sv[b][i]]
        if len(ch) != 1: cross_ok = False; continue
        emir[(a, b)] = ch[0]
        if vkey(F, apply(refl_matrix(cox[ch[0]]), V[a])) != vkey(F, V[b]): refl_ok = False
    braid = {}
    braid_ok = True
    for f in faces:
        p = f["verts"]; seq = [emir.get((min(p[j], p[(j+1) % len(p)]), max(p[j], p[(j+1) % len(p)]))) for j in range(len(p))]
        # the 2m edges of a 2m-gon cross the m Coxeter mirrors through the face's axis, each twice
        # (opposite edges); two neighbouring crossed mirrors s, t satisfy (st)^m = 1, m minimal
        ms = set(seq); m2 = len(p) // 2
        ok = (None not in ms and len(ms) == m2 and all(seq.count(x) == 2 for x in ms)
              and all(F.sign(dot(cox[x], f["N"])) == 0 for x in ms)
              and order(F, mmul(refl_matrix(cox[seq[0]]), refl_matrix(cox[seq[1]]))) == m2)
        if not ok: braid_ok = False
        braid[len(p)] = braid.get(len(p), 0) + 1
    return {"perm": {"coxeter_mirrors": len(cox), "W_order": len(W), "corners_one_per_chamber": one_per_chamber,
                     "W_transitive_on_corners": transitive, "every_edge_crosses_exactly_one_coxeter_mirror": cross_ok,
                     "edge_reflection_swaps_ends": refl_ok,
                     "every_2m_gon_face_crosses_its_m_axis_mirrors_twice_each_and_(st)^m=1": braid_ok,
                     "faces_by_sides": braid}}

def dual_extra(F, D, edges, faces, mirrors, keys):
    cox = [m for m in mirrors.values() if all(F.sign(dot(m, f["N"])) != 0 for f in faces)]
    R = [refl_matrix(m) for m in cox]
    W = closure(F, R)
    n = len(D)
    # face-transitivity: orbit of the first face's corner set
    fkey = lambda vs: frozenset(vs)
    fsets = {fkey(f["verts"]): i for i, f in enumerate(faces)}
    def img(A, idx): return keys[vkey(F, apply(A, D[idx]))]
    orb = {fkey(img(A, i) for i in faces[0]["verts"]) for A in W}
    transitive = len(orb) == len(faces) and all(o in fsets for o in orb)
    # each face = one chamber
    chambers = set(); face_chamber_ok = True
    on = [[i for i in range(len(cox)) if F.sign(dot(cox[i], v)) == 0] for v in D]
    for f in faces:
        c = tuple(F.sign(dot(m, f["N"])) for m in cox)
        chambers.add(c)
        for vi in f["verts"]:
            s = [F.sign(dot(m, D[vi])) for m in cox]
            if any(s[i] != 0 and s[i] != c[i] for i in range(len(cox))) or len(on[vi]) < 2:
                face_chamber_ok = False
    face_chamber_ok = face_chamber_ok and len(chambers) == len(faces) == len(W)
    # rolling: each edge on exactly one Coxeter mirror; its reflection maps one face onto the other
    eface = {}
    for fi, f in enumerate(faces):
        p = f["verts"]
        for j in range(len(p)):
            a, b = p[j], p[(j+1) % len(p)]
            eface.setdefault((min(a, b), max(a, b)), []).append(fi)
    roll_ok = True; emir = {}
    for (a, b), fs in eface.items():
        common = [i for i in on[a] if i in on[b]]
        if len(common) != 1 or len(fs) != 2: roll_ok = False; continue
        emir[(a, b)] = common[0]
        if fkey(img(R[common[0]], i) for i in faces[fs[0]]["verts"]) != fkey(faces[fs[1]]["verts"]): roll_ok = False
    # wall types: propagate labels from face 0 by rolling
    lab = {}
    p0 = faces[0]["verts"]
    for j in range(len(p0)):
        a, b = p0[j], p0[(j+1) % len(p0)]
        lab[(min(a, b), max(a, b))] = j
    done = {0}; stack = [0]; label_ok = True
    while stack:
        fi = stack.pop(); p = faces[fi]["verts"]
        for j in range(len(p)):
            e = (min(p[j], p[(j+1) % len(p)]), max(p[j], p[(j+1) % len(p)]))
            fs = eface[e]; fj = fs[0] if fs[1] == fi else fs[1]
            A = R[emir[e]]
            for k in range(len(p)):
                e2 = (min(p[k], p[(k+1) % len(p)]), max(p[k], p[(k+1) % len(p)]))
                a2, b2 = img(A, e2[0]), img(A, e2[1]); e3 = (min(a2, b2), max(a2, b2))
                if e3 in lab and lab[e3] != lab[e2]: label_ok = False
                lab[e3] = lab[e2]
            if fj not in done: done.add(fj); stack.append(fj)
    # corners: valence 2k, labels alternate between two types, k = order of the product
    corner = {}; braid_ok = True
    for vi in range(n):
        es = [e for e in eface if vi in e]
        types = sorted({lab[e] for e in es})
        k = len(es) // 2
        cnt = [sum(1 for e in es if lab[e] == t) for t in types]
        ms = sorted({emir[e] for e in es})
        A = None
        if len(types) != 2 or cnt != [k, k] or len(ms) != k: braid_ok = False
        corner[len(es)] = corner.get(len(es), 0) + 1
        # order of the rotation about this corner = k (product of two reflections at angle pi/k)
        ea = [e for e in es if lab[e] == types[0]][0]; eb = [e for e in es if lab[e] == types[1]][0]
        # adjacent walls of one face at the corner
        for f in faces:
            if vi in f["verts"]:
                p = f["verts"]; j = p.index(vi)
                e1 = (min(p[j-1], vi), max(p[j-1], vi)); e2 = (min(vi, p[(j+1) % len(p)]), max(vi, p[(j+1) % len(p)]))
                if order(F, mmul(R[emir[e1]], R[emir[e2]])) != k: braid_ok = False
                break
    return {"dual": {"coxeter_mirrors": len(cox), "W_order": len(W), "face_transitive_under_W": transitive,
                     "each_face_is_one_chamber": face_chamber_ok, "roll_across_edge_is_one_reflection": roll_ok,
                     "wall_types_consistent": label_ok, "corners_by_valence": corner,
                     "round_each_corner_two_wall_types_alternate_and_(st)^k=1": braid_ok}}
