"""Step 2: the arithmetic signature of the ten golden cuts (#88), exact in K = Q(sqrt2, sqrt5).
A. Corners of the ten cut Platonic solids (D, I, C, T, O; greater and lesser) in their standard frames.
   Distance field = field generated by all ratios of squared corner distances (a similarity invariant).
   Expected: Q(sqrt5) for D, I, T, O; Q(sqrt2, sqrt5) (degree 4) for both Golden Cut Cubes.
B. Truncated cube with corners (+-1, +-1, +-t) and permutations: distance field = Q(t) (t^2 and (1-t)^2/2 are ratios).
   Greater: t = 1/(1 + sqrt2 phi), lesser: t = 1/(1 + sqrt2/phi); minimal polynomials of degree 4.
   Octagon lemma: if t lies in a field L, the octagon side ratio (corner side / original side) = (1-t)/(sqrt2 t)
   lies in sqrt2 L; so a golden octagon needs sqrt2 phi in L.
C. Corner modules: M = Z-span of the corners. Rank (over Z) and golden inflation: smallest k <= 6 with phi^k M in M.
   D, I, T, O: rank 6 and inflation exists. Cubes: rank 6, and no real lambda other than an integer has lambda M in M
   (proof in the README: lambda (2,0,0) in M forces lambda in (Z + Z t)/2, then lambda t in Q + Q t forces t quadratic).
D. The octahedron's pair as compounds: Icosaxes corners = all permutations of (+-phi, +-1, 0) = the corners of the two
   pyritohedral twin icosahedra (UC46, compound of two icosahedra); Unborn Axes corners = all permutations of
   (+-phi^2, +-1, 0) = the 24 corners of the two twin dodecahedra that are not cube corners.
usage (compute-host): python3 s2_field_signature.py -> ../data/s2-field-signature.json
"""
from sixd_lib import *          # noqa
import sympy as sp
from sympy.matrices.normalforms import hermite_normal_form

out = {'solids': {}}
sq2, sq5 = sp.sqrt(2), sp.sqrt(5)
def tosym(x): a, b, c, d = x.v; return sp.Rational(a.numerator, a.denominator) + sp.Rational(b.numerator, b.denominator) * sq2 \
    + sp.Rational(c.numerator, c.denominator) * sq5 + sp.Rational(d.numerator, d.denominator) * sq2 * sq5
def degree(x): return sp.degree(sp.minimal_polynomial(tosym(x), sp.Symbol('z')))


def ratcoords(p):
    return [c for x in p for c in x.v]          # 12 rationals per point


def module(P):
    """Z-basis (rows, rational) of the Z-span of the points P (in 12 rational coordinates)"""
    rows = [ratcoords(p) for p in P]
    den = 1
    for r in rows:
        for x in r: den = sp.ilcm(den, x.denominator)
    M = sp.Matrix([[int(x * den) for x in r] for r in rows]).T
    Hn = hermite_normal_form(M)
    return Hn, den


def contains(Hn, den, p):
    v = sp.Matrix([sp.Rational((x * den).numerator, (x * den).denominator) for x in ratcoords(p)])
    # solve Hn c = v on the nonzero rows
    try:
        c, params = Hn.gauss_jordan_solve(v)
    except ValueError:
        return False
    return all(x.is_integer for x in c)


solids = platonic()
for name, (V, n) in solids.items():
    for lab, x in zip(('greater', 'lesser'), x_golden(n)):
        P = cut_solid(V, x)
        R = dist_ratios(P)
        f5 = all(in_q5(r) for r in R); fq = all(in_q(r) for r in R)
        degs = max(degree(r) for r in R)
        Hn, den = module(P); rank = Hn.shape[1]
        infl = None
        for k in range(1, 7):
            lam = ONE
            for _ in range(k): lam = lam * PHI
            if all(contains(Hn, den, vscale(lam, p)) for p in P): infl = k; break
        rec = {'corners': len(P), 'cut_x': kstr(x), 'distance_field_degree': degs,
               'distance_field': 'Q' if fq else ('Q(sqrt5)' if f5 else 'Q(sqrt2, sqrt5)'),
               'module_rank': rank, 'golden_inflation_k': infl}
        out['solids'][f'{lab} golden cut {name}'] = rec
        print(f'{lab:8s} {name:13s} corners {len(P):3d} field {rec["distance_field"]:16s} deg {degs}  rank {rank}  '
              f'phi^k M in M: k = {infl}', flush=True)
        if name == 'cube':
            check(f'{lab} Golden Cut Cube: distance field Q(sqrt2, sqrt5) (degree 4), module rank 6, no phi^k (k <= 6) '
                  f'maps the corner module into itself', not f5 and degs == 4 and rank == 6 and infl is None)
        else:
            check(f'{lab} golden cut {name}: distance field inside Q(sqrt5), module rank 6, golden inflation phi^{infl}',
                  f5 and degs <= 2 and rank == 6 and infl is not None)

# ---------------------------------------------------------------- B. truncated cube in t
t = sp.Symbol('t', positive=True)
cor = [p for s in itertools.product((1, -1), repeat=3) for p in
       set(itertools.permutations((s[0], s[1], s[2] * t)))]
cor = list({tuple(sp.expand(c) for c in p) for p in cor})
D = {sp.factor(sum((a - b) ** 2 for a, b in zip(p, q))) for p, q in itertools.combinations(cor, 2)}
check(f'truncated cube corners (+-1,+-1,+-t) perms: squared distances include 4, 4t^2 and 2(1-t)^2, so the distance field is Q(t)',
      {sp.Integer(4), 4 * t ** 2, 2 * (t - 1) ** 2} <= D)
phi = (1 + sq5) / 2
tG, tL = 1 / (1 + sq2 * phi), 1 / (1 + sq2 / phi)
z = sp.Symbol('z')
mG, mL = sp.minimal_polynomial(tG, z), sp.minimal_polynomial(tL, z)
check(f'greater t = 1/(1 + sqrt2 phi): minimal polynomial {mG} (degree 4); lesser t = 1/(1 + sqrt2/phi): {mL} (degree 4)',
      sp.degree(mG, z) == 4 and sp.degree(mL, z) == 4)
# consistency with #88/#89 depths: unit edge x = (1 - t)/2
xG, xL = x_golden(4)
check('t = 1 - 2x agrees with #88 x_G(4), x_L(4)', sp.simplify(tosym(1 - 2 * xG) - tG) == 0 and sp.simplify(tosym(1 - 2 * xL) - tL) == 0)
ratio = (1 - t) / (sq2 * t)
check('octagon corner side / original side = (1 - t)/(sqrt2 t): phi at t_G, 1/phi at t_L',
      sp.simplify(ratio.subs(t, tG) - phi) == 0 and sp.simplify(ratio.subs(t, tL) - 1 / phi) == 0)
out['truncated_cube'] = {'tG_minpoly': str(mG), 'tL_minpoly': str(mL)}

# ---------------------------------------------------------------- D. octahedron pair = twin compounds
Icos = cut_solid(solids['octahedron'][0], x_golden(3)[0]); Unb = cut_solid(solids['octahedron'][0], x_golden(3)[1])
def allperms(a, b):
    return uniq([tuple(p) for s1 in (1, -1) for s2 in (1, -1) for p in itertools.permutations((a * s1, b * s2, ZERO))])
ico, dod = solids['icosahedron'][0], solids['dodecahedron'][0]
twin = lambda P: [(p[1], p[0], p[2]) for p in P]               # mirror x <-> y: the other coset of T_h in O_h
def sameset(A, B): return {key(a) for a in A} == {key(b) for b in B}
okI = similar(Icos, allperms(PHI, ONE))[0] and sameset(allperms(PHI, ONE), ico + twin(ico)) and not sameset(ico, twin(ico))
cubec = [p for p in dod if all(not c.iszero() and (c == 1 or c == -1) for c in p)]
nonc = [p for p in dod if p not in cubec]
okU = similar(Unb, allperms(PHI * PHI, ONE))[0] and sameset(allperms(PHI.inv(), PHI), nonc + twin(nonc))
check('Icosaxes (greater golden cut octahedron) ~ all perms of (+-phi, +-1, 0) = corners of the two twin icosahedra', okI)
check('Unborn Axes (lesser golden cut octahedron) ~ all perms of (+-phi^2, +-1, 0) = the 24 non-cube corners of the two twin dodecahedra', okU)
dump('s2-field-signature.json', out)
