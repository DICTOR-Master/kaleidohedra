#!/usr/bin/env python3
"""Generate the roll tables of the three fair dice (A3, B3, H3).

Faces = group elements, listed in breadth-first order from the identity
(face 0).  r[i][x] = the face reached from face x by rolling across an edge
of type i (right multiplication by the simple reflection s_i).  d[x] = the
breadth-first distance.  The numbers are only DATA: every property used is
re-checked exactly by the Lean kernel, so floating point here cannot leak
into any theorem.  Coxeter matrices follow Mathlib (CoxeterMatrix.A 3,
CoxeterMatrix.B 3, CoxeterMatrix.H₃)."""
import math, sys, os
GROUPS = {
  'A3': {(0,1):3,(1,2):3,(0,2):2},
  'B3': {(0,1):3,(1,2):4,(0,2):2},
  'H3': {(0,1):3,(1,2):5,(0,2):2},
}
def mats(m):
    G=[[1.0 if i==j else -math.cos(math.pi/m[tuple(sorted((i,j)))]) for j in range(3)] for i in range(3)]
    S=[]
    for i in range(3):  # s_i(a_j) = a_j - 2 G_ij a_i, columns = images
        A=[[float(r==c) for c in range(3)] for r in range(3)]
        for j in range(3): A[i][j]-=2*G[i][j]
        S.append(A)
    return S
def mul(A,B): return [[sum(A[r][k]*B[k][c] for k in range(3)) for c in range(3)] for r in range(3)]
def key(A): return tuple(round(v,6)+0.0 for row in A for v in row)
def build(m):
    S=mats(m); I=[[float(r==c) for c in range(3)] for r in range(3)]
    els=[I]; idx={key(I):0}; d=[0]; q=0
    while q<len(els):
        for s in S:
            y=mul(els[q],s); k=key(y)
            if k not in idx: idx[k]=len(els); els.append(y); d.append(d[q]+1)
        q+=1
    r=[[idx[key(mul(x,s))] for x in els] for s in S]
    return r,d
out=sys.argv[1]
for name,m in GROUPS.items():
    r,d=build(m); N=len(d)
    with open(os.path.join(out,name+'.lean'),'w') as f:
        f.write(f"""/-
Roll tables of the {name} die ({N} faces), generated by gen/rolls.py.
Faces are numbered in breadth-first order from face 0. Data only: every
property is checked by the Lean kernel in RollingLaw/Dice.lean.
-/
namespace RollingLaw.Data.{name}

/-- number of faces -/
def N : Nat := {N}

/-- `rt[i][x]`: the face reached from face `x` by rolling across an edge of type `i`. -/
def rt : List (List Nat) :=
  [{(','+chr(10)+'   ').join(str(row).replace(' ','') for row in r)}]

/-- `dt[x]`: the number of rolls on a shortest roll from face 0 to face `x`. -/
def dt : List Nat :=
  {str(d).replace(' ','')}

end RollingLaw.Data.{name}
""")
    print(name,N,max(d))
