    for G in sorted({r["group"] for r in rows}, key=lambda g: -{"T": 12, "Th": 24, "Td": 24, "O": 24, "Oh": 48, "I": 60, "Ih": 120}[g.split("_")[0]]):
        a = [tab[(G, x)] for x in ("heart", "inherited heart", "non-heart")]
