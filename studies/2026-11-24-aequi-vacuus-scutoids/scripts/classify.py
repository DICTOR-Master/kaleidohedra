def closure(start, U, g):
    S = set(start); frontier = list(start)
    while frontier:
        i = frontier.pop(); gi = mat(g, U[i])
        for j in range(len(U)):
            if j not in S and same_ray(gi, U[j]): S.add(j); frontier.append(j)
    return sorted(S)

