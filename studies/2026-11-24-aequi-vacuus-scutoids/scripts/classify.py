"""Study 1 (24 Nov 2026): classify all 1232 Aequi (149 main catalogue + 1083 with both icosahedron placements).

For each die: full symmetry group (exact), centrally symmetric or not, Vacuus kind, plates, face count, icosahedral core.

Exact method.
 * Directions: the 122 face directions of the Aequi picker data, each matched to an exact vector u in Q(phi)^3 from six base
   patterns (all coordinate permutations and signs): (1,0,0) (1,1,1) (1,1,0) (phi,1,0) (0,1/phi,phi) (1/phi,1,phi).
   The match is unique (checked) and exact parallelism of float and exact vector is not needed afterwards: every later test is
   on the exact vectors.
 * Die = the planes n.x <= d over its face directions, one depth per face orbit (by construction).  Depths: the 60-digit values
   of the two search studies (2026-11-19-aequi-complete, 2026-11-20-aequi-two-placements), matched to every app record.
 * Symmetry.  Every die is invariant under the frame rotation group T (checked: generators (x,y,z)->(z,x,y), diag(1,-1,-1)).
   A finite subgroup of O(3) containing this T is one of T, Th, Td, O, Oh, I_A, I_B, Ih_A, Ih_B (I_A, I_B = the rotation groups
   of the two icosahedra whose 3-fold axes include the cube diagonals).  Each is generated by T and some of
   -I, s = (x,y,z)->(y,x,z) (mirror of Td), r = (x,y,z)->(-y,x,z) (4-fold of O), f_A, f_B (a 5-fold rotation of each icosahedron).
   So the full group is fixed by which of these five maps the die to itself.  A map g preserves the die iff for every face i,
   g u_i is exactly parallel (same sense) to some face u_j of the die, and d_i = d_j.  Parallelism is exact in Q(sqrt5).
   d_i = d_j is exact when i, j lie in one orbit; for different orbits the 60-digit depths are compared (gap must exceed 1e-40;
   none falls below it, see log).
 * Centrally symmetric = -I in the group.  Vacuus kind: heart (centrally symmetric); inherited heart (not centrally symmetric,
   yet some face has a parallel opposite face, so its plate carries two faces); non-heart (no two faces parallel).
   Plates = number of lines through the centre carrying face normals = N - (number of opposite face pairs).
 * Icosahedral core: groups I_A/Ih_A (or B): dodecahedron, icosahedron, icosidodecahedron, Fullerene Star all share the symmetry;
   the core whose face normals all lie among the die's face normals is listed as the parallel core.  Other groups: no icosahedral
   symmetry; the core sits in a subgroup (the die's group is a subgroup of Oh; its T part lies in both Ih_A and Ih_B).
Usage: python classify.py APPDICE STUDY1DIR STUDY2DIR OUTDIR"""
import itertools, json, os, sys, glob
from collections import Counter
from fractions import Fraction as Fr
import mpmath as mp
mp.mp.dps = 70

class Q:  # a + b sqrt5, exact
    __slots__ = ("a", "b")
    def __init__(s, a=0, b=0): s.a = Fr(a); s.b = Fr(b)
    def __add__(s, o): o = o if isinstance(o, Q) else Q(o); return Q(s.a + o.a, s.b + o.b)
    __radd__ = __add__
    def __neg__(s): return Q(-s.a, -s.b)
    def __sub__(s, o): o = o if isinstance(o, Q) else Q(o); return Q(s.a - o.a, s.b - o.b)
    def __mul__(s, o): o = o if isinstance(o, Q) else Q(o); return Q(s.a*o.a + 5*s.b*o.b, s.a*o.b + s.b*o.a)
    __rmul__ = __mul__
    def __truediv__(s, o):
        o = o if isinstance(o, Q) else Q(o); n = o.a*o.a - 5*o.b*o.b
        return Q((s.a*o.a - 5*s.b*o.b)/n, (s.b*o.a - s.a*o.b)/n)
    def iszero(s): return s.a == 0 and s.b == 0
    def sign(s):
        a, b = s.a, s.b
        if a >= 0 and b >= 0: return 0 if (a == 0 and b == 0) else 1
        if a <= 0 and b <= 0: return -1
        d = a*a - 5*b*b
        return (1 if d > 0 else -1) * (1 if a > 0 else -1)
    def __float__(s): return float(s.a) + float(s.b)*5**0.5
PHI = Q(Fr(1, 2), Fr(1, 2)); IPHI = PHI - 1; Z = Q(0); ONE = Q(1)
def dot(u, v): return u[0]*v[0] + u[1]*v[1] + u[2]*v[2]
def cross(u, v): return [u[1]*v[2]-u[2]*v[1], u[2]*v[0]-u[0]*v[2], u[0]*v[1]-u[1]*v[0]]
def same_ray(u, v): return all(c.iszero() for c in cross(u, v)) and dot(u, v).sign() > 0
def mat(M, v): return [M[i][0]*v[0] + M[i][1]*v[1] + M[i][2]*v[2] for i in range(3)]
def mul(A, B): return [[sum((A[i][k]*B[k][j] for k in range(3)), Z) for j in range(3)] for i in range(3)]
def orth(M): return all((dot(M[i], M[j]) - (1 if i == j else 0)).iszero() for i in range(3) for j in range(3))

BASES = {"C6": [1, 0, 0], "O8": [1, 1, 1], "RD12": [1, 1, 0], "D12": [PHI, 1, 0], "I12": [0, IPHI, PHI], "RT24": [IPHI, 1, PHI]}
def exact_dirs(fdirs):
    cands = []
    for fam, b in BASES.items():
        b = [x if isinstance(x, Q) else Q(x) for x in b]
        for p in itertools.permutations(range(3)):
            for sg in itertools.product((1, -1), repeat=3):
                v = [b[p[i]]*sg[i] for i in range(3)]
                if not any(same_ray(v, w) for w, f in cands): cands.append((v, fam))
    out = []
    for fd in fdirs:
        hits = []
        for v, fam in cands:
            fv = [float(x) for x in v]; nv = sum(x*x for x in fv)**0.5
            if sum((fv[i]/nv - fd[i])**2 for i in range(3)) < 1e-18: hits.append((v, fam))
        assert len(hits) == 1, ("direction match not unique", fd, len(hits))
        out.append(hits[0])
    return out

h = Fr(1, 2)
def M(rows): return [[x if isinstance(x, Q) else Q(x) for x in r] for r in rows]
GEN = {
    "c3": M([[0, 0, 1], [1, 0, 0], [0, 1, 0]]),           # (x,y,z)->(z,x,y)
    "d2": M([[1, 0, 0], [0, -1, 0], [0, 0, -1]]),
    "-I": M([[-1, 0, 0], [0, -1, 0], [0, 0, -1]]),
    "s":  M([[0, 1, 0], [1, 0, 0], [0, 0, 1]]),            # mirror x<->y (Td)
    "r4": M([[0, -1, 0], [1, 0, 0], [0, 0, 1]]),           # 4-fold about z (O)
}
def ico_rotation(verts):
    """an exact order-5 rotation preserving the 12 vertices `verts` (Q(sqrt5)^3, scaled equal length): send a vertex v0 and its
    neighbour v1 to v0 and the next neighbour v2 around v0; solve exactly; check orthogonality."""
    v0 = verts[0]
    L = dot(v0, v0)
    nbrs = sorted([v for v in verts[1:] if (dot(v, v0)*5 - L*Q(0, 1)).iszero()], key=lambda v: 0)  # <v,v0> = L/sqrt5
    assert len(nbrs) == 5, len(nbrs)
    v1 = nbrs[0]
    for v2 in nbrs[1:]:
        if not (dot(v1, v2)*5 - L*Q(0, 1)).iszero(): continue
        # g: v0->v0, v1->v2, v0xv1 -> v0xv2
        A = [v0, v1, cross(v0, v1)]; B = [v0, v2, cross(v0, v2)]
        # g = B^T-cols * inv(A^T-cols): solve g A_k = B_k, rows: g = Bc * Ac^-1
        Ac = [[A[k][i] for k in range(3)] for i in range(3)]; Bc = [[B[k][i] for k in range(3)] for i in range(3)]
        det = dot(Ac[0], cross(Ac[1], Ac[2]))
        cof = [cross(Ac[1], Ac[2]), cross(Ac[2], Ac[0]), cross(Ac[0], Ac[1])]  # rows of adj^T
        inv = [[cof[j][i]/det for j in range(3)] for i in range(3)]
        g = mul(Bc, inv)
        if not orth(g): continue
        gk = g; order = 1
        while not all((gk[i][j] - (1 if i == j else 0)).iszero() for i in range(3) for j in range(3)): gk = mul(gk, g); order += 1
        if order == 5 and all(any(same_ray(mat(g, v), w) for w in verts) for v in verts): return g
    raise RuntimeError("no 5-fold found")

def main():
    app, s1, s2, out = sys.argv[1:5]
    D = json.load(open(app)); ED = exact_dirs(D["dirs"]); U = [v for v, f in ED]; FAM = [f for v, f in ED]
    # icosahedron vertices (5-fold axes) of placements A and B: D12 directions grouped by which T-orbit (A: (phi,1,0) cyclic family)
    def cyc_family(base):
        s = []
        for sg in itertools.product((1, -1), repeat=3):
            t = [base[i]*sg[i] for i in range(3)]
            for c in ([t[0], t[1], t[2]], [t[2], t[0], t[1]], [t[1], t[2], t[0]]): s.append(c)
        return [i for i in range(len(U)) if any(same_ray(U[i], c) for c in s)]
    DA = cyc_family([PHI, Q(1), Z]); DB = cyc_family([Q(1), PHI, Z])
    assert len(DA) == 12 and len(DB) == 12 and not set(DA) & set(DB)
    GEN["fA"] = ico_rotation([U[i] for i in DA]); GEN["fB"] = ico_rotation([U[i] for i in DB])
    # which placement is the app's Ih: the Ih D12 orbit
    # exact action of every generator on the 122 directions (None = image outside the 122), computed once
    PERM = {g: [next((j for j in range(len(U)) if same_ray(mat(GEN[g], U[i]), U[j])), None) for i in range(len(U))] for g in GEN}
    for g in ("c3", "d2", "-I", "s", "r4"): assert None not in PERM[g] and sorted(PERM[g]) == list(range(len(U))), g
    ihD = set(D["groups"]["Ih"][0]["dirs"]); place_of_Ih = "A" if ihD == set(DA) else "B" if ihD == set(DB) else "?"
    # 60-digit depths
    recs = []
    for d_ in (s1, s2):
        for f in sorted(glob.glob(os.path.join(d_, "data/dice/*.json"))):
            r = json.load(open(f))
            if d_ == s1 and r["group"] not in ("Ih", "Oh", "Td", "Th", "T"): continue
            recs.append(r)
    log = open(os.path.join(out, "classify.log"), "w")
    def pr(*a):
        print(*a, flush=True); print(*a, file=log, flush=True)
    pr(f"directions 122 matched exactly; families {dict(Counter(FAM))}; Ih placement of the app data: {place_of_Ih}")
    pr(f"study records: {len(recs)} (main catalogue frame groups + both placements)")
    idx = {}
    for r in recs: idx.setdefault((r["group"], frozenset(r["face_directions"])), []).append(r)
    rows = []; mingap = None; problems = []; tie_notes = []
    for k, e in enumerate(D["dice"]):
        orbs = [D["groups"][e["g"]][oi]["dirs"] for oi in e["o"]]
        fdir = [i for ob in orbs for i in ob]; N = len(fdir)
        assert len(set(fdir)) == N
        cand = idx.get((e["g"], frozenset(fdir)), [])
        cand = [r for r in cand if len(r["depths_60_digits"]) == len(e["d"])]
        good = []
        for r in cand:
            dd = [mp.mpf(x) for x in r["depths_60_digits"]]
            # orbit order may differ: match each app depth to a study depth
            perm = []
            for x in e["d"]:
                j = [t for t in range(len(dd)) if abs(dd[t] - x) < 1e-9 and t not in perm]
                if len(j) != 1: break
                perm.append(j[0])
            if len(perm) == len(dd): good.append((r, [dd[t] for t in perm]))
            elif all(abs(dd[t] - e["d"][t]) < 1e-9 for t in range(len(dd))): good.append((r, dd))   # equal depths: same orbit order
        if len(good) != 1: problems.append((k, "record match", len(good))); continue
        r, dep = good[0]
        depth = {}; orbit = {}
        for oi, ob in enumerate(orbs):
            for i in ob: depth[i] = dep[oi]; orbit[i] = oi
        ties = []
        def preserves(g, tie_equal=False):
            nonlocal mingap
            for i in fdir:
                j = PERM[g][i]
                if j is None or j not in depth: return False
                if orbit[j] == orbit[i]: continue
                gap = abs(depth[i] - depth[j])
                if gap < mp.mpf("1e-40"):
                    ties.append((oi_name(i), oi_name(j)))
                    if tie_equal: continue
                    return False
                if mingap is None or gap < mingap: mingap = gap
                return False
            return True
        assert preserves("c3") and preserves("d2"), "T invariance"
        def oi_name(i): return D["groups"][e["g"]][e["o"][orbit[i]]]["lab"]
        has = {g: preserves(g) for g in ("-I", "s", "r4", "fA", "fB")}
        if ties:
            # two different orbits at depths equal to 60 digits: the verdict must not depend on whether they are exactly equal
            has2 = {g: preserves(g, True) for g in ("-I", "s", "r4", "fA", "fB")}
            if has2 != has: problems.append((k, "group depends on a depth tie", sorted(set(ties))))
            tie_notes.append((k + 1, e.get("name", ""), sorted(set(ties))))
        if has["fA"] or has["fB"]:
            assert not (has["s"] or has["r4"])
            pl = "A" if has["fA"] else "B"; G = ("Ih" if has["-I"] else "I") + "_" + pl
        else:
            if has["-I"] and has["s"]: G = "Oh"
            elif has["r4"] and not has["-I"]: G = "O"
            elif has["-I"]: G = "Th"
            elif has["s"]: G = "Td"
            else: G = "T"
            # consistency of the generator pattern with the group found
            want = {"Oh": (1, 1, 1), "O": (0, 0, 1), "Th": (1, 0, 0), "Td": (0, 1, 0), "T": (0, 0, 0)}[G]
