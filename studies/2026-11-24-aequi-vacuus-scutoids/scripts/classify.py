    pr(f"dice with two orbits at equal depth (60 digits) met by a candidate map: {len(tie_notes)} {tie_notes[:20]}; verdicts independent of the tie: checked")
    tab = Counter((r["group"], r["vacuus_kind"]) for r in rows)
