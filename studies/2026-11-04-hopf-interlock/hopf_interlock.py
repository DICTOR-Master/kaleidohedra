#!/usr/bin/env python3
"""(4) Hopf fibrations of the White Queen: the 600-cell's 120 corners are the unit icosians (binary icosahedral group 2I); left cosets q<g> of a cyclic subgroup
of order 10, 6, 4 split them into great-circle rings; the Hopf map sends each ring to one point of S^2. (5) Interlocking (Dyskin et al. 2003): in a slab of the
octet between two (111) layer planes, can a single tetrahedron or octahedron be translated out while its neighbours stay? Kinematic test: a velocity v is free iff
v·n <= 0 for every face shared with a neighbour (n = the piece's outward normal there); free directions exist iff this cone is not {0}."""
import itertools, math, json, os, sys
sys.path.insert(0, os.path.expanduser('~/kres-tmp/_lib')); import methods as M
import numpy as np
from scipy.optimize import linprog
phi = M.PHI
tess = np.array(list(itertools.product((1, -1), repeat=4)), float)
V = np.unique(np.round(np.vstack([tess/2, M.perms((1, 0, 0, 0)), M.even_perms((phi/2, .5, 1/(2*phi), 0))]), 12), axis=0)
def qmul(a, b):
    a1, b1, c1, d1 = a; a2, b2, c2, d2 = b
    return np.array([a1*a2 - b1*b2 - c1*c2 - d1*d2, a1*b2 + b1*a2 + c1*d2 - d1*c2, a1*c2 - b1*d2 + c1*a2 + d1*b2, a1*d2 + b1*c2 - c1*b2 + d1*a2])
key = lambda q: tuple(np.round(q, 9))
S = {key(v) for v in V}; assert all(key(qmul(a, b)) in S for a in V[:10] for b in V[:10]), 'not a group'
def order(q):
    p = q.copy()
    for n in range(1, 121):
        if np.allclose(p, [1, 0, 0, 0]): return n
        p = qmul(p, q)
res = {}
for ordr, name in ((10, 'decagons'), (6, 'hexagons'), (4, 'squares')):
    g = next(v for v in V if order(v) == ordr); C = [np.array([1., 0, 0, 0])]
    while len(C) < ordr: C.append(qmul(C[-1], g))
    cos = []; seen = set()
    for q in V:
        if key(q) in seen: continue
        ring = [qmul(q, c) for c in C]; seen.update(key(r) for r in ring); cos.append(ring)
    def hopf(q):   # q -> q i q^-1 projected: the Hopf map with the circle generated by g's axis
        a = g[1:] / np.linalg.norm(g[1:])
        u = np.array([0, *a]); qc = q * np.array([1, -1, -1, -1])
        return qmul(qmul(q, u), qc)[1:]
    img = np.unique(np.round(np.array([hopf(r[0]) for r in cos]), 6), axis=0)
    same = all(np.allclose(hopf(r[k]), hopf(r[0]), atol=1e-9) for r in cos for k in range(len(r)))
    great = all(abs(np.linalg.norm(sum(r)) ) < 1e-9 for r in cos)
    D = np.linalg.norm(img[:, None] - img[None], axis=2); dmin = np.min(D[D > 1e-9])
    nn = sorted(set(int(np.sum(np.abs(D[i] - dmin) < 1e-6)) for i in range(len(img))))
    res[name] = {'rings': len(cos), 'ring_size': ordr, 'each_ring_one_point': same, 'rings_centred': great, 'images': len(img), 'neighbours_per_image': nn}
    print(f'Hopf by C{ordr}: {len(cos)} rings of {ordr}; each ring -> one point: {same}; images {len(img)} points, nearest neighbours each {nn}')
# (5) interlocking in an octet (111) slab
H = math.sqrt(2/3); P = {'A': (0, 0), 'B': (.5, math.sqrt(3)/6), 'C': (1, math.sqrt(3)/3)}
pts = []
for z, L in enumerate('AB'):
    ox, oy = P[L]
    for a in range(-4, 5):
        for b in range(-4, 5): pts.append(np.array([ox + a + b/2, oy + b*math.sqrt(3)/2, z*H]))
pts = np.array(pts); nb = lambda i, j: abs(np.linalg.norm(pts[i] - pts[j]) - 1) < 1e-9
n = len(pts); adj = [[j for j in range(n) if j != i and nb(i, j)] for i in range(n)]
tets = {tuple(sorted(q)) for i in range(n) for q in itertools.combinations([i] + adj[i], 4) if all(nb(a, b) for a, b in itertools.combinations(q, 2))}
octs = set()
for i in range(n):
    for q in itertools.combinations(adj[i], 4):
        if sum(nb(a, b) for a, b in itertools.combinations(q, 2)) != 4: continue
        for o in set.intersection(*[set(adj[x]) for x in q]) - {i}:
            if not nb(i, o): octs.add(tuple(sorted((i, o) + q)))
pieces = [('T', list(t)) for t in tets] + [('O', list(o)) for o in octs]
def faces(vs):
    from scipy.spatial import ConvexHull
    h = ConvexHull(pts[vs]); out = {}
    for s, eq in zip(h.simplices, h.equations):
        k = tuple(np.round(eq[:3], 6)); out.setdefault(k, (eq[:3], set(np.array(vs)[s])))
        out[k][1].update(np.array(vs)[s])
    return list(out.values())
centre = np.array([0., 0., H/2])
def free(idx):
    kind, vs = pieces[idx]; cons = []
    for nrm, fv in faces(vs):
        for jdx, (k2, v2) in enumerate(pieces):
            if jdx != idx and fv <= set(v2): cons.append(nrm)          # face shared with a neighbour
    if not cons: return 'no neighbours'
    A = np.array(cons); best = None
    for d in np.vstack([np.eye(3), -np.eye(3)]):                      # is there v with A v <= 0 and d·v = 1 ?
        r = linprog(np.zeros(3), A_ub=A, b_ub=np.zeros(len(A)), A_eq=[d], b_eq=[1], bounds=[(-1, 1)]*3)
        if r.status == 0: best = r.x; break
    return 'locked' if best is None else 'free along ' + str(np.round(best, 3))
mid = [i for i, (k, vs) in enumerate(pieces) if np.linalg.norm(pts[vs].mean(0)[:2]) < 1.2]
out = {}
for i in mid:
    k = pieces[i][0]; out.setdefault(k, []).append(free(i))
for k, v in out.items(): print(f'octet slab, central {k} pieces:', v)
res['interlocking_octet_slab'] = out
json.dump(res, open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'hopf-interlock.json'), 'w'), indent=1, default=str)
