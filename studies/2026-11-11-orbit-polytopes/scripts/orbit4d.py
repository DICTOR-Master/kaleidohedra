"""4D orbit polytopes (DICTO 11 Nov: "go on with the 4D orbits"). Same test as orbit_id.py, scaled for thousands of corners: candidate
symmetries are built from one corner and its edge-neighbours (images: a corner and an ordered set of its neighbours with the same
distances), verified on all corners. Then the reflections among the symmetries, the group they generate, the single-orbit test and the
seed labels (inner products of the corner, moved into a chamber, with the simple roots; zero = mirror unused).
Solids: built independently (600-cell corners from stages.py; truncations as in the queen-stages atlas and #104), not as orbits.
Controls: tesseract, 16-cell, 24-cell, 4D permutohedron (orbits); 24-cell + 16-cell at another size, and a 600-cell with one corner moved (non-orbits)."""
import itertools, json, sys, time
import numpy as np
from scipy.spatial import cKDTree
from scipy.optimize import linprog
def sym_group(V):
    n, d = V.shape; t = cKDTree(V)
    D = np.linalg.norm(V[:, None] - V[None], axis=2) if n <= 1500 else None
    nn = t.query(V, k=min(n, 16))[0][:, 1].min()
    nb = [set(t.query_ball_point(V[i], nn * 1.0001)) - {i} for i in range(n)]
    v0 = int(np.argmin(np.linalg.norm(V, axis=1)))
    frame = [v0]
    for j in sorted(nb[v0]):
        if np.linalg.matrix_rank(V[frame + [j]], tol=1e-7) == len(frame) + 1: frame.append(j)
        if len(frame) == d: break
    if len(frame) < d:                                     # fall back: further corners by distance from v0 until the frame spans
        for j in np.argsort(np.linalg.norm(V - V[v0], axis=1)):
            j = int(j)
            if j in frame: continue
            if np.linalg.matrix_rank(V[frame + [j]], tol=1e-7) == len(frame) + 1: frame.append(j)
            if len(frame) == d: break
    F = V[frame]; G = F @ F.T; Finv = np.linalg.inv(F)
    norms = np.round(np.linalg.norm(V, axis=1), 7); mats = []
    for w in np.where(norms == norms[v0])[0]:
        pools = [[w]] + [list(set(np.where(np.abs(V @ V[w] - G[0, k]) < 1e-7)[0]) & (nb[w] | set(np.where(np.abs(np.linalg.norm(V - V[w], axis=1) - np.linalg.norm(F[k] - F[0])) < 1e-7)[0]))) for k in range(1, d)]
        def rec(k, ch):
            if k == d:
                M = (Finv @ V[ch]).T
                if not np.allclose(M @ M.T, np.eye(d), atol=1e-6): return
                if np.all(t.query(V @ M.T)[0] < 1e-6): mats.append(M)
                return
            for j in pools[k]:
                if j in ch: continue
                if all(abs(V[j] @ V[ch[i]] - G[k, i]) < 1e-7 for i in range(k)): rec(k + 1, ch + [j])
        rec(1, [int(w)])
    return mats
def analyse(name, V, expect=None):
    t0 = time.time(); V = np.array(V, float); V = V - V.mean(0); n, d = V.shape
    mats = sym_group(V)
    R = []
    for M in mats:
        if np.allclose(M, M.T, atol=1e-7) and np.isclose(np.linalg.det(M), -1):
            ev, vec = np.linalg.eigh(M)
            if np.sum(np.isclose(ev, -1, atol=1e-6)) == 1:
                r = vec[:, np.argmin(ev)]; R.append(r / np.linalg.norm(r))
    Rs = []
    for r in R:
        if not any(abs(abs(r @ s) - 1) < 1e-6 for s in Rs): Rs.append(r)
    # group generated by the reflections: closure on the corner V[0] is enough for the orbit test
    t = cKDTree(V); orbit = {0}; frontier = [0]
    S = [np.eye(d) - 2 * np.outer(r, r) for r in Rs]
    while frontier:
        nf = []
        for i in frontier:
            for A in S:
                j = int(t.query(A @ V[i])[1])
                if j not in orbit: orbit.add(j); nf.append(j)
        frontier = nf
    single = len(orbit) == n and len(Rs) > 0
    labels = None
    if single:
        p = np.array([1.0, 0.31, 0.073, 0.0119][:d]) + 1e-3
        Rs = [r if r @ p > 0 else -r for r in Rs]
        x = V[0].copy()
        for _ in range(500):
            bad = [r for r in Rs if r @ x < -1e-9]
            if not bad: break
            x = x - 2 * (bad[0] @ x) * bad[0]
        simple = []
        for r in Rs:
            A = [s for s in Rs if not np.allclose(s, r)]
            Aub = np.hstack([-np.array(A), np.ones((len(A), 1))])
            res = linprog(c=np.r_[np.zeros(d), -1], A_ub=Aub, b_ub=np.zeros(len(A)), A_eq=np.r_[r, 0].reshape(1, -1), b_eq=[0], bounds=[(-1, 1)] * d + [(0, 1)])
            if res.success and -res.fun > 1e-7: simple.append(r)
        # Coxeter graph of the simple roots: angle pi/m between mirrors -> m; report labels in a path/branch order
        m = [[round(np.pi / np.arccos(min(1, abs(a @ b)))) if i != j else 1 for j, b in enumerate(simple)] for i, a in enumerate(simple)]
        labels = {'labels': [round(float(r @ x), 6) for r in simple], 'coxeter_m': m}
    W = {24: 'A3', 48: 'B3', 120: 'H3/A4', 384: 'B4', 1152: 'F4', 14400: 'H4'}
    ver = f'ORBIT: {len(Rs)} mirrors, symmetry group {len(mats)}, seed {labels}' if single else f'NOT an orbit (symmetry group {len(mats)}, {len(Rs)} mirrors, one mirror-orbit holds {len(orbit)} of {n} corners)'
    ok = '' if expect is None else ('  [control PASS]' if expect == single else '  [control FAIL]')
    print(f'{name}: {n} corners: {ver}{ok}  ({time.time() - t0:.1f} s)', flush=True)
    return {'name': name, 'corners': n, 'sym': len(mats), 'mirrors': len(Rs), 'orbit': single, 'seed': labels}, (expect is None or expect == single)
def tesseract(): return np.array(list(itertools.product((1, -1), repeat=4)), float)
def c16(): return np.array([s * np.eye(4)[i] for i in range(4) for s in (1, -1)])
def c24(): return np.array(sorted({tuple(v) for p in itertools.permutations((1, 1, 0, 0)) for sg in itertools.product((1, -1), repeat=4) for v in [tuple(a * b for a, b in zip(p, sg))]}), float)
def perm4():
    P = np.array(list(itertools.permutations(range(1, 6))), float); P -= 3
    B = np.linalg.svd(np.ones((1, 5)))[2][1:]; return P @ B.T
if __name__ == '__main__':
    out = []; ok = True; which = sys.argv[1] if len(sys.argv) > 1 else 'pilot'
    print('CONTROLS', flush=True)
    for name, V, e in [('tesseract', tesseract(), True), ('16-cell', c16(), True), ('24-cell', c24(), True), ('4D permutohedron (orders of 1..5)', perm4(), True),
                       ('24-cell + 16-cell (two kinds)', np.vstack([c24(), 1.7 * c16()]), False)]:
        r, g = analyse(name, V, e); out.append(r); ok &= g
    if which == 'queens':
        exec(open(sys.argv[2]).read().split('keys = ')[0])                    # stages.py: V (600-cell corners), D, e0
        V6 = V.copy(); adj = {i: set(j for j in range(120) if abs(D[i, j] - e0) < 1e-9) for i in range(120)}
        E = [(i, j) for i in range(120) for j in adj[i] if j > i]; T = [(i, j, k) for i, j in E for k in adj[i] & adj[j] if k > j]
        C = [(i, j, k, l) for i, j, k in T for l in adj[i] & adj[j] & adj[k] if l > k]
        cen = lambda q: V6[list(q)].mean(0)
        bad = V6.copy(); bad[0] = bad[0] * 1.05
        r, g = analyse('600-cell with one corner moved', bad, False); out.append(r); ok &= g
        trunc = np.array([(2 * V6[a] + V6[b]) / 3 for a in range(120) for b in adj[a]])
        red = np.array([cen(c) for c in C])
        s_ = (5 - 5 ** .5) / 10; byf = {}
        for ci, c in enumerate(C):
            for f in itertools.combinations(sorted(c), 3): byf.setdefault(f, []).append(ci)
        t120 = np.array([(1 - s_) * cen(C[a]) + s_ * cen(C[b]) for f, (a, b) in byf.items() for (a, b) in [(a, b), (b, a)]])
        bit = np.array([0.4 * (V6[a] + V6[b]) / 2 + 0.6 * cen(t) for t in T for a, b in itertools.combinations(t, 2)])
        for name, X in [('600-cell (White Queen)', V6), ('120-cell (Red Queen)', red), ('truncated 600-cell', trunc), ('truncated 120-cell', t120), ('bitruncated 600-cell', bit)]:
            r, _ = analyse(name, X); out.append(r)
    json.dump(out, open('orbit4d_results_' + which + '.json', 'w'), indent=1, default=str)
    print('FINAL ok' if ok else 'FINAL FAIL (a control failed)')
