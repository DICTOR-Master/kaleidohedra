#!/usr/bin/env python3
"""Roll tables of the A4 die (120 faces) -> Lean data.

The A4 die is the polar of the A4 permutahedron: the convex hull of the 120
permutations of u = (5,4,3,2,1) in the hyperplane x1+...+x5 = 15.  Face x of
the die <-> corner x of the permutahedron (exact integer vectors).  Face 0 is u.
Rolling across a ridge of type i (i = 0..3) takes the face of w to the face of
w s_i, where s_i swaps positions i, i+1 of u: on the corner vector x this swaps
the two entries whose values are u[i] and u[i+1] (consecutive integers), i.e.
it follows one edge of the permutahedron (one ridge of the die).
Faces are numbered breadth-first from face 0; dt = breadth-first distance;
word[x] = the breadth-first shortest roll from face 0 to face x.
Data only: every property used is re-checked by the Lean kernel (RollingLaw/A4.lean)."""
import itertools, sys

u = (5, 4, 3, 2, 1)
n = 4

def roll(x, i):
    a, b = u[i], u[i + 1]
    return tuple(b if v == a else a if v == b else v for v in x)

# breadth-first numbering from u
order = [u]; idx = {u: 0}; dist = {u: 0}; word = {u: []}
k = 0
while k < len(order):
    x = order[k]; k += 1
    for i in range(n):
        y = roll(x, i)
        if y not in idx:
            idx[y] = len(order); order.append(y); dist[y] = dist[x] + 1; word[y] = word[x] + [i]
assert len(order) == 120 and set(order) == set(itertools.permutations(u))
# each roll is an edge of the permutahedron: the corners differ by e_a - e_b
for x in order:
    for i in range(n):
        y = roll(x, i)
        diff = sorted(p - q for p, q in zip(x, y))
        assert diff == [-1, 0, 0, 0, 1]

rt = [[idx[roll(x, i)] for x in order] for i in range(n)]
dt = [dist[x] for x in order]
wd = [word[x] for x in order]
assert max(dt) == 10 and dt.count(10) == 1

def L(xs): return "[" + ",".join(str(v) for v in xs) + "]"
out = sys.argv[1]
with open(f"{out}/A4.lean", "w") as f:
    f.write(f'''/-
Roll tables of the A4 die (120 faces, the polar of the A4 permutahedron), generated by gen/a4.py.
Face `x` is the corner `corner[x]` of the permutahedron (a permutation of (5,4,3,2,1)); faces are
numbered breadth-first from face 0. Data only: every property is checked by the Lean kernel in
RollingLaw/A4.lean.
-/
namespace RollingLaw.Data.A4

set_option maxRecDepth 100000

/-- number of faces -/
def N : Nat := 120

/-- `corner[x]`: the corner of the permutahedron dual to face `x` (exact integer vector). -/
def corner : List (List Nat) :=
  [{",".join(L(x) for x in order)}]

/-- `rt[i][x]`: the face reached from face `x` by rolling across its ridge of type `i`. -/
def rt : List (List Nat) :=
  [{(",\n   ").join(L(r) for r in rt)}]

/-- `dt[x]`: the number of rolls on a shortest roll from face 0 to face `x`. -/
def dt : List Nat :=
  {L(dt)}

/-- `word[x]`: a shortest roll from face 0 to face `x`. -/
def word : List (List Nat) :=
  [{",".join(L(w) for w in wd)}]

end RollingLaw.Data.A4
''')
print("wrote", len(order), "faces; longest", max(dt))
