#!/usr/bin/env python3
"""Part B, shadow echoes: orthogonal projections to 3D (and central slices) of 4D point sets whose 3D images have a classical
polyhedral symmetry group: 24-cell, 600-cell, 120-cell, the H4 shadow of the E8 roots (two concentric 600-cells, radii 1 and 1/phi:
Elser-Sloane 1987, Moody-Patera 1993), and the five S5 orbits of the 600-cell (20+20+20+30+30, Koca et al. 2012; golden A4 study).
Everything exact in Q5: the image inner product is <Px,Py> = <x,y> - (x.d)(y.d)/(d.d).
Directions: every vertex direction and every facet-centre direction of the 4D hull (and, for the S5 orbits, the S4-fixed axis
(1,1,1,1,-4)), deduplicated by the image's shell signature. For each image: symmetry group (computed), shells (squared radius, distinct
points, multiplicity = 4D points per image point), each shell's hull named, orbit split of each shell under the image group, tones of
the whole image with forced/unforced zeros (unforced even zeros re-checked exactly), Dehn and translation tiling of every shell hull.
Central slices: the vertices with x.d = 0, and the polytope section conv(S) ∩ d^perp (from the 4D edges, exact).
Usage: shadow_echoes.py out.json [sets comma-separated]"""
import sys, os, json, time
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from echo_lib import *
from collections import Counter
OUT = sys.argv[1]
WANT = sys.argv[2].split(',') if len(sys.argv) > 2 else ['24-cell', '600-cell', '120-cell', 'E8-shadow', 'S5-orbits']
t0 = time.time(); FAILS = []
def check(c, msg):
    print(('CHECK ok   ' if c else 'CHECK FAIL ') + msg, flush=True)
    if not c: FAILS.append(msg)
H = Q5(1, 0)/2

def cell600():
    P = []
    for i in range(4):
        for s in (1, -1): v = [Q5(0)]*4; v[i] = Q5(s); P.append(tuple(v))
    P += signs((H, H, H, H))
    for t in perms_even((PHI/2, H, IPHI/2, Q5(0))): P += signs(t)
    return uniq(P)
def cell120():
    P = []
    for t in set(itertools.permutations((0, 0, 2, 2))): P += signs(tuple(Q5(x) for x in t))
    for base in ((Q5(1), Q5(1), Q5(1), SQ5), (IPHI*IPHI, PHI, PHI, PHI), (IPHI, IPHI, IPHI, PHI*PHI)):
        for t in set(itertools.permutations(range(4))): P += signs(tuple(base[i] for i in t))
    for base in ((Q5(0), IPHI*IPHI, Q5(1), PHI*PHI), (Q5(0), IPHI, PHI, SQ5), (IPHI, Q5(1), PHI, Q5(2))):
        for t in perms_even(base): P += signs(t)
    return uniq(P)
def cell24():
    P = []
    for i, j in itertools.combinations(range(4), 2):
        for s, t in itertools.product((1, -1), repeat=2): v = [Q5(0)]*4; v[i] = Q5(s); v[j] = Q5(t); P.append(tuple(v))
    return P
def s5_orbits():
    """C1 = perms (phi^2,phi^2,phi^2,phi,0), C2 = -C1, C4 = perms (phi^2,phi^2,1,1,0), C5 = -C4, C3 = the transposition class;
    in R^5 with the centre subtracted (sum-zero hyperplane). C3 found as the rest of the 600-cell generated by C1 (golden A4 study)."""
    P2 = PHI*PHI
    def cen(v): m = sum(v, Q5())/5; return tuple(x - m for x in v)
    C1 = uniq([cen(tuple(t)) for t in set(itertools.permutations((P2, P2, P2, PHI, Q5(0))))])
    C4 = uniq([cen(tuple(t)) for t in set(itertools.permutations((P2, P2, Q5(1), Q5(1), Q5(0))))])
    C2 = [vscale(Q5(-1), p) for p in C1]; C5 = [vscale(Q5(-1), p) for p in C4]
    # closure of C1 under reflections in its own members -> 120 points; C3 = closure minus the others
    S = {vkey(p): p for p in C1}; frontier = list(C1)
    while frontier:
        new = []
        for a in list(S.values()):
            aa = dot(a, a)
            for b in frontier:
                c = vsub(b, vscale(2*dot(a, b)/aa, a))
                if vkey(c) not in S: S[vkey(c)] = c; new.append(c)
        frontier = new
        if len(S) > 200: break
    known = {vkey(p) for p in C1 + C2 + C4 + C5}
    C3 = [p for k, p in S.items() if k not in known]
    return {'C1': C1, 'C2': C2, 'C3': C3, 'C4': C4, 'C5': C5}, len(S)

def basis_perp(d, n):
    """orthonormal float basis of d^perp in R^n (for coordinates of images; exact work uses inner products)"""
    D = np.array([float(x) for x in d]); M = np.eye(n) - np.outer(D, D)/(D @ D)
    U, s, Vt = np.linalg.svd(M); return U[:, :n - 1]

def image(S, d, extra_perp=None):
    """exact projected points (in R^n, inside d^perp) and float 3D coordinates"""
    dd = dot(d, d); n = len(d)
    Pts = [vsub(x, vscale(dot(x, d)/dd, d)) for x in S]
    B = basis_perp(d, n)
    if extra_perp is not None:      # S5 case: ambient R^5 sum-zero; restrict basis to sum-zero and d-perp
        E = np.array([float(x) for x in extra_perp]); D = np.array([float(x) for x in d])
        M = np.eye(n) - np.outer(D, D)/(D @ D) - np.outer(E, E)/(E @ E)
        U, s, Vt = np.linalg.svd(M); B = U[:, :n - 2]
    X = np.array([to_np(p) for p in Pts]) @ B
    return Pts, X

def analyse_image(label, S, d, extra_perp=None):
    Pts, X = image(S, d, extra_perp)
    # merge coincident images (exact)
    M = {}
    for p, x in zip(Pts, X):
        k = vkey(p)
        if k in M: M[k][2] += 1
        else: M[k] = [p, x, 1]
    U = list(M.values()); Pex = [u[0] for u in U]; Xf = np.array([u[1] for u in U]); mult = [u[2] for u in U]
    order, inv, nimp = sym_group(Xf, w=mult); gname = group_name(order, inv, nimp)
    shells = {}
    for p, x, m in U: shells.setdefault(dot(p, p).key(), []).append((p, x, m))
    shl = []
    for key in sorted(shells, key=lambda k: float(Q5(*k))):
        grp = shells[key]; r2 = Q5(*key)
        if r2.iszero(): shl.append({'r2': str(r2), 'points': len(grp), 'multiplicity': sorted(Counter(m for _, _, m in grp).items())}); continue
        Xs = np.array([x for _, x, _ in grp]); info = {'r2': str(r2), 'r': float(r2)**0.5, 'points': len(grp),
                                                      'multiplicity': sorted(Counter(m for _, _, m in grp).items())}
        if len(grp) >= 4 and np.linalg.matrix_rank(Xs - Xs.mean(0), tol=1e-8) == 3:
            Hs = hull3(Xs); info['hull'] = name_of(Hs); info['hull_fvec'] = fvec(Hs); info['hull_faces'] = face_census(Hs)
            info['all_points_are_hull_vertices'] = len(Hs['verts']) == len(grp)
            Pmp = exact3(grp, d, extra_perp)
            info['dehn'] = dehn(Pmp, Hs); info['translation'] = parallelohedron(Hs)
            o2, i2, n2 = sym_group(Xs); info['shell_group'] = group_name(o2, i2, n2)
        shl.append(info)
    pm, wm = [], []
    for p, x, m in U:
        if dot(p, p).iszero(): continue
        pm.append(p); wm.append(m)
    T_ = tones_ip(pm, wm, 30)
    rep = tone_report(T_, gname if gname in GROUPS else 'T') if gname in GROUPS else {'group_not_polyhedral': gname,
          'zero': [k for k in range(1, 31) if abs(T_[k]) < mp.mpf(10)**-40]}
    exact = {}
    for kk in rep.get('unforced_zero', []):
        if kk % 2 == 0:
            e = tones_exact_even_w(pm, wm, kk); exact[kk] = str(e); check(e.iszero(), f'{label}: unforced zero T_{kk} exact')
    return {'label': label, 'group': gname, 'order': order, 'image_points': len(U), 'source_points': len(S),
            'coincident': sum(1 for m in mult if m > 1), 'shells': shl, 'tones': rep, 'exact_unforced': exact,
            'T_nonzero_first': {k: float(T_[k]) for k in range(1, 13) if abs(T_[k]) > mp.mpf(10)**-40}}

def exact3(grp, d, extra_perp):
    """mp 3D coordinates of exact image points via a Gram-Schmidt basis computed in mp from exact vectors"""
    pts = [p for p, _, _ in grp]
    n = len(pts[0]); D = to_mp(d)
    vecs = []
    E = to_mp(extra_perp) if extra_perp is not None else None
    for i in range(n):
        v = [mp.mpf(1) if j == i else mp.mpf(0) for j in range(n)]
        for w in ([D] + ([E] if E else []) + vecs):
            c = sum(a*b for a, b in zip(v, w))/sum(a*a for a in w); v = [a - c*b for a, b in zip(v, w)]
        r = mp.sqrt(sum(a*a for a in v))
        if r > mp.mpf(10)**-30: vecs.append([a/r for a in v])
        if len(vecs) == 3: break
    return [[sum(a*b for a, b in zip(to_mp(p), w)) for w in vecs] for p in pts]

def tones_ip(pts, w, kmax):
    """tones with exact inner products (Q5) -> mp cosines"""
    n2 = [dot(p, p) for p in pts]; groups = {}
    for i in range(len(pts)):
        for j in range(i, len(pts)):
            x = dot(pts[i], pts[j]); key = (x.key(), n2[i].key(), n2[j].key()) if True else None
            c2key = (x*x/(n2[i]*n2[j])).key(); sg = x.sign()
            kk = (c2key, sg); m = w[i]*w[j]*(1 if i == j else 2)
            groups[kk] = groups.get(kk, 0) + m
    W = sum(w); T = [mp.mpf(0)]*(kmax + 1)
    for (c2key, sg), m in groups.items():
        c = sg*mp.sqrt(Q5(*c2key).mpf()); c = min(mp.mpf(1), max(mp.mpf(-1), c))
        P = legendre_all(c, kmax)
        for k in range(kmax + 1): T[k] += m*P[k]
    return [t/(W*W) for t in T]

def tones_exact_even_w(pts, w, k):
    leg = legendre_coeffs(k); n2 = [dot(p, p) for p in pts]; cnt = {}
    for i in range(len(pts)):
        for j in range(i, len(pts)):
            x = dot(pts[i], pts[j]); c2 = (x*x/(n2[i]*n2[j])).key()
            cnt[c2] = cnt.get(c2, 0) + w[i]*w[j]*(1 if i == j else 2)
    tot = Q5()
    for key, m in cnt.items():
        c2 = Q5(*key); s = Q5(); pw = Q5(1)
        for a in leg: s = s + pw*Q5(a); pw = pw*c2
        tot = tot + s*m
    return tot

def hull4_dirs(S):
    """vertex directions and facet-centre directions (exact) of conv(S) in R^4; facets from qhull, centres = mean of facet vertices"""
    from scipy.spatial import ConvexHull
    X = np.array([to_np(p) for p in S]); Hh = ConvexHull(X)
    facets = {}
    for simp, eq in zip(Hh.simplices, Hh.equations):
        key = tuple(np.round(eq, 7)); facets.setdefault(key, set()).update(simp.tolist())
    cents = []
    for key, vs in facets.items():
        c = tuple(sum((S[i][t] for i in vs), Q5())/len(vs) for t in range(4)); cents.append(c)
    return cents

def edges4(S):
    d2 = None; E = []
    for i in range(len(S)):
        for j in range(i + 1, len(S)):
            v = vsub(S[i], S[j]); x = dot(v, v)
            if d2 is None or x < d2: d2 = x; E = [(i, j)]
            elif x == d2: E.append((i, j))
    return E

def section(S, E, d, label):
    """conv(S) ∩ d^perp: vertices = vertices on the hyperplane + edge crossings (exact). Returns analysed 3D polytope."""
    s = [dot(x, d) for x in S]; pts = {}
    for i, x in enumerate(S):
        if s[i].iszero(): pts[vkey(x)] = x
    for i, j in E:
        if s[i].sign()*s[j].sign() < 0:
            t = s[i]/(s[i] - s[j]); p = tuple(a + t*(b - a) for a, b in zip(S[i], S[j])); pts[vkey(p)] = p
    P = list(pts.values())
    if len(P) < 4: return {'label': label, 'points': len(P)}
    Pts, X = image(P, d)
    Hs = hull3(X); o, i_, n_ = sym_group(X); gname = group_name(o, i_, n_)
    Pmp = exact3([(p, None, 1) for p in P], d, None)
    T_ = tones_ip(P, [1]*len(P), 30)
    rep = tone_report(T_, gname) if gname in GROUPS else {'zero': [k for k in range(1, 31) if abs(T_[k]) < mp.mpf(10)**-40]}
    return {'label': label, 'points': len(P), 'group': gname, 'name': name_of(Hs), 'fvec': fvec(Hs), 'faces': face_census(Hs),
            'all_points_vertices': len(Hs['verts']) == len(P), 'dehn': dehn(Pmp, Hs), 'translation': parallelohedron(Hs), 'tones': rep}

def signature(S, d):
    dd = dot(d, d); c = Counter()
    for x in S:
        p = vsub(x, vscale(dot(x, d)/dd, d)); c[dot(p, p).key()] += 1
    return tuple(sorted((float(Q5(*k)), v) for k, v in c.items()))

def run_set(name, S, dirs, out, extra_perp=None, edges=True):
    E = edges4(S) if edges and extra_perp is None else []
    seen = set()
    for kind, d in dirs:
        sig = (signature(S, d), kind)
        if sig in seen: continue
        seen.add(sig)
        lab = f'{name} along {kind}'
        r = analyse_image(lab, S, d, extra_perp); r['set'] = name; r['axis'] = kind; r['axis_vector'] = [str(x) for x in d]
        sl = [x for x in S if dot(x, d).iszero()]
        r['vertex_slice'] = {'points': len(sl)}
        if len(sl) >= 4:
            P, X = image(sl, d, extra_perp)
            if np.linalg.matrix_rank(X - X.mean(0), tol=1e-8) == 3:
                Hs = hull3(X); o, i_, n_ = sym_group(X); r['vertex_slice'].update({'name': name_of(Hs), 'group': group_name(o, i_, n_)})
        if E: r['section'] = section(S, E, d, lab + ' (solid section)')
        out.append(r)
        sh = ' + '.join(f"{s['points']}{'x' + str(s['multiplicity'][0][0]) if s['multiplicity'] and s['multiplicity'][0][0] > 1 else ''}"
                        + (f"[{s['hull']}]" if 'hull' in s else '') for s in r['shells'])
        print(f'IMAGE {lab}: group {r["group"]}, {r["image_points"]} image points ({r["coincident"]} coincident) = {sh}; '
              f'tone zeros {r["tones"].get("zero", [])[:10]} unforced {r["tones"].get("unforced_zero")}'
              + (f'; section {r["section"].get("name")} {r["section"].get("group")}' if 'section' in r else ''), flush=True)

def main():
    out = []; sets = []
    if '24-cell' in WANT: sets.append('24-cell')
    if '600-cell' in WANT: sets.append('600-cell')
    if '120-cell' in WANT: sets.append('120-cell')
    if 'E8-shadow' in WANT: sets.append('E8-shadow')
    if 'S5-orbits' in WANT: sets.append('S5-orbits')
    for si, name in enumerate(sets):
        if name == '24-cell':
            S = cell24(); check(len(S) == 24, '24-cell: 24 vertices')
        elif name == '600-cell':
            S = cell600(); check(len(S) == 120 and all(dot(p, p) == 1 for p in S), '600-cell: 120 unit vertices')
            check(len(edges4(S)) == 720, '600-cell: 720 edges')
        elif name == '120-cell':
            S = cell120(); check(len(S) == 600 and all(dot(p, p) == 8 for p in S), '120-cell: 600 vertices, radius^2 8')
            E = edges4(S); check(len(E) == 1200, f'120-cell: 1200 edges ({len(E)})')
        elif name == 'E8-shadow':
            C = cell600(); S = C + [vscale(IPHI, p) for p in C]; check(len(uniq(S)) == 240, 'E8 shadow: 240 points (600-cell and 600-cell/phi)')
        if name != 'S5-orbits':
            dirs = [('vertex', p) for p in (S if name != 'E8-shadow' else cell600())]
            cents = hull4_dirs(S if name != 'E8-shadow' else cell600())
            dirs += [('facet centre', c) for c in cents]
            if name == '120-cell':
                check(len(cents) == 120, f'120-cell: 120 facets ({len(cents)})')
            if name == '600-cell':
                check(len(cents) == 600, f'600-cell: 600 facets ({len(cents)})')
            run_set(name, S, dirs, out, edges=(name != 'E8-shadow'))
        else:
            orb, ncl = s5_orbits(); check(ncl == 120, f'S5: closure of C1 is 120 points ({ncl})')
            check([len(orb[k]) for k in ('C1', 'C2', 'C3', 'C4', 'C5')] == [20, 20, 20, 30, 30], 'S5 orbits 20+20+20+30+30')
            one = tuple(Q5(1) for _ in range(5))
            def cen(v): m = sum(v, Q5())/5; return tuple(x - m for x in v)
            axis = cen((Q5(0), Q5(0), Q5(0), Q5(0), Q5(1)))          # S4-fixed axis (1,1,1,1,-4) up to sign/scale
            for k in ('C1', 'C3', 'C4'):
                run_set(f'S5 orbit {k}', orb[k], [('S4 axis', axis)], out, extra_perp=one, edges=False)
            run_set('S5 orbits C1+C2', orb['C1'] + orb['C2'], [('S4 axis', axis)], out, extra_perp=one, edges=False)
            run_set('S5 orbits C4+C5', orb['C4'] + orb['C5'], [('S4 axis', axis)], out, extra_perp=one, edges=False)
        print(f'PROGRESS {(si + 1)/len(sets):.3f} {name} done ({time.time() - t0:.0f} s)', flush=True)
    # controls with known answers
    for r in out:
        if r['label'] == '600-cell along vertex':
            check(r['group'] == 'Ih', 'control: 600-cell vertex-first shadow has Ih symmetry')
            check(r.get('vertex_slice', {}).get('name') == 'icosidodecahedron', 'control: 600-cell vertex-first equatorial vertices form an icosidodecahedron (Coxeter; Baez)')
            check(r.get('section', {}).get('points') == 42, 'section of the solid: 30 equatorial vertices + 12 midpoints of the edges joining the two icosahedral layers at heights +-1/(2 phi)')
    json.dump({'images': out, 'fails': FAILS, 'seconds': time.time() - t0}, open(OUT, 'w'), indent=1, default=str)
    print(f'{len(out)} images, {len(FAILS)} failed checks, {time.time() - t0:.0f} s')
    print('FINAL ok' if not FAILS else 'FINAL FAIL')

if __name__ == '__main__': main()
