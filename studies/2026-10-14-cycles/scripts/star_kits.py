# Kits for the dodecahedral stars (DICTO 2026-10-14, Cycles builder): Polyhedraverse's dodecahedron + 12 of its stellation face pieces
# (STELLATION_DODECAHEDRON_2 / _3 / _4) on the 12 faces = the small stellated, great, and great stellated dodecahedron. Writes
# src/krp-core/src/polyhedra/star-kits.js. Checks: every piece's base is a dodecahedron face; no two pieces overlap (sampling).
import itertools, json, math, os, sys
import numpy as np
from scipy.spatial import ConvexHull, Delaunay
K = os.path.expanduser('~/kaleidohedra'); ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
S = json.load(open(sys.argv[1]))
D = np.array(S['DODECAHEDRON']['v'], float); DF = S['DODECAHEDRON']['f']
def quat(Rm):
    tr = np.trace(Rm); m = max(range(4), key=lambda i: [tr, Rm[0, 0], Rm[1, 1], Rm[2, 2]][i])
    if m == 0: w = math.sqrt(1 + tr) / 2; x, y, z = (Rm[2, 1] - Rm[1, 2]) / (4 * w), (Rm[0, 2] - Rm[2, 0]) / (4 * w), (Rm[1, 0] - Rm[0, 1]) / (4 * w)
    elif m == 1: x = math.sqrt(1 + 2 * Rm[0, 0] - tr) / 2; w, y, z = (Rm[2, 1] - Rm[1, 2]) / (4 * x), (Rm[0, 1] + Rm[1, 0]) / (4 * x), (Rm[0, 2] + Rm[2, 0]) / (4 * x)
    elif m == 2: y = math.sqrt(1 + 2 * Rm[1, 1] - tr) / 2; w, x, z = (Rm[0, 2] - Rm[2, 0]) / (4 * y), (Rm[0, 1] + Rm[1, 0]) / (4 * y), (Rm[1, 2] + Rm[2, 1]) / (4 * y)
    else: z = math.sqrt(1 + 2 * Rm[2, 2] - tr) / 2; w, x, y = (Rm[1, 0] - Rm[0, 1]) / (4 * z), (Rm[0, 2] + Rm[2, 0]) / (4 * z), (Rm[1, 2] + Rm[2, 1]) / (4 * z)
    q = np.array([x, y, z, w]); return (q / np.linalg.norm(q)).round(12).tolist()
def kabsch(Sr, Tg):
    a, b = Sr.mean(0), Tg.mean(0); U, _, Wt = np.linalg.svd((Tg - b).T @ (Sr - a)); R = U @ np.diag([1, 1, np.sign(np.linalg.det(U @ Wt))]) @ Wt
    return R, b - a @ R.T
KITS, checks = {}, {}
for k, (key, label) in {'STELLATION_DODECAHEDRON_2': ('stars.ssd', 'Small stellated dodecahedron · dodecahedron + 12 spikes'),
                        'STELLATION_DODECAHEDRON_3': ('stars.gd', 'Great dodecahedron · dodecahedron + 12 stellation pieces'),
                        'STELLATION_DODECAHEDRON_4': ('stars.gsd', 'Great stellated dodecahedron · dodecahedron + 12 stellation pieces')}.items():
    P = np.array(S[k]['v'], float); PF = S[k]['f']
    base = [f for f in PF if len(f) == 5 and abs(np.linalg.norm(P[f[0]] - P[f[1]]) - np.linalg.norm(D[DF[0][0]] - D[DF[0][1]])) < 1e-6]
    assert base, k
    B = P[base[0]]
    entries = [dict(shape='DODECAHEDRON', position=[0, 0, 0], quaternion=[0, 0, 0, 1])]; placed = []
    for f in DF:
        T = D[f]; ok = None
        for r in range(5):
            for order in (T, T[::-1]):
                Tg = np.roll(order, r, axis=0); R, t = kabsch(B, Tg)
                if np.abs(B @ R.T + t - Tg).max() < 1e-6 and np.linalg.det(R) > 0:
                    Q = P @ R.T + t
                    if (Q.mean(0) @ T.mean(0)) > T.mean(0) @ T.mean(0) - 1e-9: ok = (R, t, Q); break
            if ok: break
        assert ok, (k, f)
        R, t, Q = ok; placed.append(Q); entries.append(dict(shape=k, position=[round(float(x), 12) for x in t], quaternion=quat(R)))
    rng = np.random.default_rng(3); rad = max(np.linalg.norm(Q, axis=1).max() for Q in placed); X = rng.uniform(-rad, rad, (300000, 3))
    hulls = [Delaunay(Q) for Q in placed] if all(len(Q) >= 4 for Q in placed) else []
    # non-convex pieces: sample by convex hull is only an upper bound; report overlap of hulls as a warning, not a failure
    cnt = sum((h.find_simplex(X) >= 0).astype(int) for h in hulls)
    checks[key] = dict(pieces=len(entries), tip_radius=round(float(rad), 6), hull_overlap_points=int((cnt > 1).sum()))
    KITS[key] = dict(label=label, group='stars', entries=entries)
js = ('// Generated by studies/2026-10-14-cycles/scripts/star_kits.py (DICTO 2026-10-14). Do not edit.\n'
      '// The dodecahedral stars as kits: Polyhedraverse\'s dodecahedron + 12 of its stellation face pieces.\n'
      f'export const STAR_KITS = {json.dumps(KITS, separators=(",", ":"))};\n')
open(os.path.join(K, 'src/krp-core/src/polyhedra/star-kits.js'), 'w').write(js)
json.dump(checks, open(os.path.join(ROOT, 'star-kits-checks.json'), 'w'), indent=1); print(json.dumps(checks, indent=1))
