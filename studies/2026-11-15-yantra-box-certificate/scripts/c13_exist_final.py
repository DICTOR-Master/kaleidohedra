def parse(s):
    toks = s.replace('(', ' ( ').replace(')', ' ) ').split(); pos = [0]
    def ex():
        pos[0] += 1; op = toks[pos[0]]; pos[0] += 1
        if op == '.v': i = int(toks[pos[0]]); pos[0] += 2; return f'(W {i})'
        if op == '.c': z = int(toks[pos[0] + 1]); pos[0] += 4; return f'(({z} : ℤ) : ℝ)'
        a = ex(); b = ex(); pos[0] += 1
        return f'({a} {dict(add="+", sub="-", mul="*")[op[1:]]} {b})'
    return ex()
