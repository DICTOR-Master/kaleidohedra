LS = [c - R for c in C]; HS = [c + R for c in C]
R3 = PolynomialRing(QQ, 'u,t,S'); Rm = PolynomialRing(QQ, 'u,tau,rho'); um, tm, rm = Rm.gens()
def dec3(p): return sum(QQ(c) * R3.gens()[0]**e[0] * R3.gens()[1]**e[1] * R3.gens()[2]**e[2] for e, c in p)
def decm(p): return sum(QQ(c) * um**e[0] * tm**e[1] * rm**e[2] for e, c in p)
Snum = 1 + rm * (1 - um) * um**2; Sden = 1 + um**2
def substH(f, d): return sum(QQ(c) * um**a * (um * tm)**b * Snum**e * Sden**(d - e) for (a, b, e), c in f.dict().items())
def sign(P):
    """the kernel's boxSign on Xs (exact)"""
    terms = [(e, int(c)) for e, c in P.dict().items()]
    D = [max([e[j] for e, c in terms] + [0]) for j in range(3)]
    def vq(neg, N):
        s = 0
        for e, c in terms:
            if (c < 0) != neg: continue
            m = abs(c)
            for j in range(3): m *= N[j]**e[j] * QS**(D[j] - e[j])
            s += m
        return s
    if vq(True, HS) < vq(False, LS): return 1, D
    if vq(False, HS) < vq(True, LS): return 2, D
    return 0, D
