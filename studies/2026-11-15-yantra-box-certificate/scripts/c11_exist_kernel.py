def parse(s):
    toks = s.replace('(', ' ( ').replace(')', ' ) ').split(); pos = [0]
    def ex():
        pos[0] += 1; op = toks[pos[0]]; pos[0] += 1
        if op == '.v': i = int(toks[pos[0]]); pos[0] += 2; return TAB[i]
        if op == '.c': z = int(toks[pos[0] + 1]); pos[0] += 4; return (R3(z), R3(1))
        (a, b), (c, d) = ex(), ex(); pos[0] += 1
        if op == '.add': return (a + c, b) if b == d else (a * d + c * b, b * d)
        if op == '.sub': return (a - c, b) if b == d else (a * d - c * b, b * d)
        return (a * c, b * d)
    return ex()
