X = '(V y 0) (tau y) (rho y)'
KINDP = {'u': 'linarith [u_pos F]', '1-u': 'linarith [u_lt1 F]', '1+u': 'linarith [u_pos F]', 'tau': 'linarith [tau_pos F]',
         '1-tau': 'linarith [tau_lt1 F]', 'rho': 'linarith [rho_pos F]', '1+u2': 'positivity'}
def factor_lines(name, kind, m, hname):
    """a `have` proving 0 < f^m (or 0 <= f^m for even kinds) at the main-chart point"""
    if kind == 'even':
        return [f'  have {hname} : 0 ≤ {name}.eval {X} ^ {m} := Even.pow_nonneg (by decide) _']
    if kind == 'pos':
        return [f'  have {hname} : 0 < {name}.eval {X} ^ {m} := by',
                f'    apply pow_pos; unfold {name}; exact ZP.allPos_pos (by decide +kernel) (u_pos F) (tau_pos F) (rho_pos F)']
    return [f'  have {hname} : 0 < {name}.eval {X} ^ {m} := by', f'    apply pow_pos; simp [{name}, ZP.eval]; {KINDP[kind]}']
def prodexpr(names_m):
    e = '1'
    for nm, m in reversed(names_m): e = f'{nm}.eval {X} ^ {m} * ' + (e if e == '1' else f'({e})')
    return e
def prodproof(hs, strict):
    pr = 'one_pos' if strict else 'zero_le_one'
    for h, kind in reversed(hs):
        if strict: pr = f'mul_pos {h} ({pr})'
        else: pr = f'mul_nonneg ({h}{".le" if kind != "even" else ""}) ({pr})'
    return pr
SIMPP = 'simp only [ZP.eval_mul, ZP.eval_const, ZP.eval_prod, List.map_cons, List.map_nil, List.prod_cons, List.prod_nil, ZP.eval_pow]'
