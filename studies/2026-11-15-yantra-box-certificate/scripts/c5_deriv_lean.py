"""Lean export of the derivation data (data/lean-deriv.json, from c4_derivation.py).  Writes lean/YantraCert/Deriv/*.lean:
  Data.lean        the table, steps, witnesses, equations, pull-backs, tests and chart data (Lean core only);
  KSteps.lean      kernel checks of the 22 construction steps and the witness factorisations;
  KFinals.lean     kernel checks of the three equations and their pull-backs;
  KTests<n>.lean   kernel checks of the 36 tests at the main chart;
  KChart<c>.lean   kernel checks of the chart identities and of the rescaling of the stored chart polynomials.
Every check is `by decide +kernel` on a ZP.eqv statement (no native_decide)."""
import json, os
from fractions import Fraction as Fq
HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); D_ = lambda *p: os.path.join(HERE, *p)
J = json.load(open(D_('data', 'lean-deriv.json')))
OUT = D_('lean', 'YantraCert', 'Deriv'); os.makedirs(OUT, exist_ok=True)
CHN = {'main': 'Main', 'A': 'A', 'B': 'B', 'C1': 'C1', 'C2': 'C2', 'W': 'W', 'Wt+': 'Wtp', 'Wt-': 'Wtm', 'Wr+': 'Wrp', 'Wr-': 'Wrm'}
def ilit(c):
    c = int(c); return f'(.ofNat {c})' if c >= 0 else f'(.negSucc {-c - 1})'
def zp(P, name=None):
    """sorted ZP literal (chunks of 300 nested terms joined by ZP.app)"""
    terms = sorted(((tuple(e), Fq(c)) for e, c in P), key=lambda t: t[0])
    assert all(c.denominator == 1 and c != 0 for e, c in terms)
    chunks = [terms[k:k + 300] for k in range(0, len(terms), 300)] or [[]]
    lits = []
    for ch in chunks:
        s = '.nil'
        for e, c in reversed(ch): s = f'(.cons {ilit(c)} {e[0]} {e[1]} {e[2]} {s})'
        lits.append(s)
    return lits
def defzp(name, P):
    lits = zp(P); out = []
    if len(lits) == 1: return [f'noncomputable def {name} : ZP := {lits[0]}']
    for k, l in enumerate(lits): out.append(f'noncomputable def {name}_{k} : ZP := {l}')
    expr = f'{name}_{len(lits) - 1}'
    for k in reversed(range(len(lits) - 1)): expr = f'(ZP.app {name}_{k} {expr})'
    return out + [f'noncomputable def {name} : ZP := {expr}']
def rat(c):
    q = Fq(c); return q.numerator, q.denominator
def prodf(facs, var):
    """Lean term: product of factor powers; factor polynomials are emitted as defs named var_j"""
    return 'ZP.prod [' + ', '.join(f'ZP.pow {var}_{j} {f["m"]}' for j, f in enumerate(facs)) + ']'
hdr = ['import YantraCert.ZPoly', '', 'set_option maxRecDepth 200000', 'set_option maxHeartbeats 0', '']
# ---------------- Data ----------------
src = hdr + ['/-! Derivation data (generated by scripts/c5_deriv_lean.py from data/lean-deriv.json). -/', '',
             'namespace YantraCert.Deriv', 'open YantraCert', '']
names = J['names']
for i, row in enumerate(J['table']):
    src += defzp(f'N{i}', row['N']) + defzp(f'D{i}', row['D'])
src.append('noncomputable def T : List (ZP × ZP) := [' + ', '.join(f'(N{i}, D{i})' for i in range(len(names))) + ']')
src.append('-- quantities: ' + ', '.join(f'{i} {n}' for i, n in enumerate(names)))
for s in J['steps']:
    src += [f'noncomputable def d{s["i"]} : Ex := {s["d"]}', f'noncomputable def n{s["i"]} : Ex := {s["n"]}'] + defzp(f'K{s["i"]}', s['K'])
for k, e in J['wit'].items():
    nm = 'W_' + k.replace('+', 'p').replace('-', 'm').replace('1', 'one') if k[0].isdigit() else 'W_' + k.replace('+', 'p').replace('-', 'm')
    src.append(f'noncomputable def {nm} : Ex := {e}   -- {k}')
WNM = {k: ('W_' + k.replace('+', 'p').replace('-', 'm').replace('1', 'one') if k[0].isdigit() else 'W_' + k.replace('+', 'p').replace('-', 'm')) for k in J['wit']}
for k, f in J['finals'].items():
    src.append(f'noncomputable def E_{k} : Ex := {f["e"]}')
    src += defzp(f'Fs_{k}', f['F'])
    for j, g in enumerate(f['facs']):
        src += defzp(f'g{k}_{j}', g['g']) + defzp(f'h{k}_{j}', g['h'])
for k, f in J['pull'].items():
    src += defzp(f'Fm_{k}', f['Fm'])
    for j, g in enumerate(f['facs']): src += defzp(f'pf{k}_{j}', g['g'])
TK = list(J['tests'])
for n_, k in enumerate(TK):
    t = J['tests'][k]
    src.append(f'-- test {n_}: {k}')
    src.append(f'noncomputable def Q_{n_} : Ex := {t["e"]}')
    src += defzp(f'TN_{n_}', t['N']) + defzp(f'TD_{n_}', t['D']) + defzp(f'TG_{n_}', t['G'])
    for j, g in enumerate(t['E1']): src += defzp(f'ea{n_}_{j}', g['g'])
    for j, g in enumerate(t['E2']): src += defzp(f'eb{n_}_{j}', g['g'])
# base substitution for the pull-back: t = u tau, S = Snum / (1 + u^2)
src += ['noncomputable def PX : ZP := (.cons 1 1 0 0 .nil)', 'noncomputable def PY : ZP := (.cons 1 1 1 0 .nil)',
        '-- Snum = 1 + rho u^2 - rho u^3', 'noncomputable def PZn : ZP := (.cons 1 0 0 0 (.cons 1 2 0 1 (.cons (.negSucc 0) 3 0 1 .nil)))',
        'noncomputable def PZd : ZP := (.cons 1 0 0 0 (.cons 1 2 0 0 .nil))']
for ch, cd in J['charts'].items():
    C = CHN[ch]
    for j, m in enumerate(cd['map']): src += defzp(f'M{C}_{j}', m)
    for k, f in cd['F'].items():
        src += defzp(f'Fc{C}_{k}', f['Fc'])
        for j, g in enumerate(f['facs']): src += defzp(f'cf{C}{k}_{j}', g['g'])
    for k, f in cd['T'].items():
        n_ = TK.index(k)
        src += defzp(f'Nc{C}_{n_}', f['Nc']) + defzp(f'Dc{C}_{n_}', f['Dc'])
        for j, g in enumerate(f['EN']): src += defzp(f'en{C}{n_}_{j}', g['g'])
        for j, g in enumerate(f['ED']): src += defzp(f'ed{C}{n_}_{j}', g['g'])
src += ['', 'end YantraCert.Deriv', '']
open(os.path.join(OUT, 'Data.lean'), 'w').write('\n'.join(src))
# ---------------- kernel checks ----------------
def kmod(name, lines, imports=('YantraCert.Deriv.Data',)):
    s = [f'import {m}' for m in imports] + ['', 'set_option maxRecDepth 200000', 'set_option maxHeartbeats 0', '', f'namespace YantraCert.Deriv', 'open YantraCert', ''] + lines + ['', 'end YantraCert.Deriv', '']
    open(os.path.join(OUT, f'{name}.lean'), 'w').write('\n'.join(s))
# steps and witnesses (stepOK lives in Frac, which needs Mathlib; the kernel checks themselves are cheap)
L = []
for s in J['steps']:
    L.append(f'theorem step{s["i"]} : stepOK T {s["i"]} d{s["i"]} n{s["i"]} K{s["i"]} = true := by decide +kernel')
for k, f in J['finals'].items():
    for j, g in enumerate(f['facs']):
        L.append(f'theorem wit{k}_{j} : ZP.eqv (Ex.frac T {WNM[g["w"]]}).1 (ZP.mul g{k}_{j} h{k}_{j}) = true := by decide +kernel')
        L.append(f'theorem witb{k}_{j} : {WNM[g["w"]]}.within {len(names)} = true := by decide +kernel')
kmod('KSteps', L)
MODS = ['KSteps']
for k, f in J['finals'].items():
    a, b = rat(f['c'])
    kmod(f'KFin_{k}', [f'theorem fin_{k} : ZP.eqv (ZP.mul (ZP.const {b}) (Ex.frac T E_{k}).1) (ZP.mul (ZP.const ({a})) (ZP.mul Fs_{k} ({prodf(f["facs"], "g" + k)}))) = true := by decide +kernel',
                       f'theorem finb_{k} : E_{k}.within {len(names)} = true := by decide +kernel']); MODS.append(f'KFin_{k}')
for k, f in J['pull'].items():
    a, b = rat(f['c'])
    kmod(f'KPull_{k}', [f'theorem zd_{k} : Fs_{k}.zdeg {f["d"]} = true := by decide +kernel',
                        f'theorem pull_{k} : ZP.eqv (ZP.mul (ZP.const {b}) (ZP.substH PX PY PZn PZd {f["d"]} Fs_{k})) (ZP.mul (ZP.const ({a})) (ZP.mul Fm_{k} ({prodf(f["facs"], "pf" + k)}))) = true := by decide +kernel'])
    MODS.append(f'KPull_{k}')
for n_ in range(len(TK)):
    t = J['tests'][TK[n_]]; a1, b1 = rat(t['a']); a2, b2 = rat(t['b'])
    kmod(f'KTest_{n_}', [f'theorem tw_{n_} : Q_{n_}.within {len(names)} = true := by decide +kernel',
        f'theorem tzN_{n_} : (Ex.frac T Q_{n_}).1.zdeg {t["d"]} = true := by decide +kernel',
        f'theorem tzD_{n_} : (Ex.frac T Q_{n_}).2.zdeg {t["d"]} = true := by decide +kernel',
        f'theorem tN_{n_} : ZP.eqv (ZP.mul (ZP.const {b1}) (ZP.substH PX PY PZn PZd {t["d"]} (Ex.frac T Q_{n_}).1)) '
        f'(ZP.mul (ZP.const ({a1})) (ZP.mul TN_{n_} (ZP.mul TG_{n_} ({prodf(t["E1"], "ea" + str(n_))})))) = true := by decide +kernel',
        f'theorem tD_{n_} : ZP.eqv (ZP.mul (ZP.const {b2}) (ZP.substH PX PY PZn PZd {t["d"]} (Ex.frac T Q_{n_}).2)) '
        f'(ZP.mul (ZP.const ({a2})) (ZP.mul TD_{n_} (ZP.mul TG_{n_} ({prodf(t["E2"], "eb" + str(n_))})))) = true := by decide +kernel'])
    MODS.append(f'KTest_{n_}')
for ch, cd in J['charts'].items():
    C = CHN[ch]
    for k, f in cd['F'].items():
        a, b = rat(f['c'])
        kmod(f'KC{C}_F{k}', [f'theorem cF_{C}_{k} : ZP.eqv (ZP.mul (ZP.const {b}) (ZP.subst M{C}_0 M{C}_1 M{C}_2 Fm_{k})) (ZP.mul (ZP.const ({a})) (ZP.mul Fc{C}_{k} ({prodf(f["facs"], "cf" + C + k)}))) = true := by decide +kernel'])
        MODS.append(f'KC{C}_F{k}')
    for k, f in cd['T'].items():
        n_ = TK.index(k); a1, b1 = rat(f['a']); a2, b2 = rat(f['b'])
        kmod(f'KC{C}_T{n_}', [f'theorem cN_{C}_{n_} : ZP.eqv (ZP.mul (ZP.const {b1}) (ZP.subst M{C}_0 M{C}_1 M{C}_2 TN_{n_})) (ZP.mul (ZP.const ({a1})) (ZP.mul Nc{C}_{n_} ({prodf(f["EN"], "en" + C + str(n_))}))) = true := by decide +kernel',
            f'theorem cD_{C}_{n_} : ZP.eqv (ZP.mul (ZP.const {b2}) (ZP.subst M{C}_0 M{C}_1 M{C}_2 TD_{n_})) (ZP.mul (ZP.const ({a2})) (ZP.mul Dc{C}_{n_} ({prodf(f["ED"], "ed" + C + str(n_))}))) = true := by decide +kernel'])
        MODS.append(f'KC{C}_T{n_}')
open(os.path.join(OUT, 'mods.txt'), 'w').write('\n'.join('YantraCert.Deriv.' + m for m in MODS) + '\n')
json.dump({'names': names, 'tests': TK}, open(D_('data', 'lean-deriv-index.json'), 'w'), indent=1)
print('wrote', sorted(os.listdir(OUT)))
ok = all(os.path.exists(os.path.join(OUT, f)) for f in ['Data.lean'] + [m + '.lean' for m in MODS])
print('FINAL ok' if ok else 'FINAL FAIL')
