"""Tables of the plate-harmony study, one per family, from the data files. Writes data/tables.md."""
import os, json
from collections import Counter
HERE = os.path.dirname(os.path.abspath(__file__)); STUDY = os.path.dirname(HERE)
D = lambda f: json.load(open(os.path.join(STUDY, "data", f)))
Y = lambda v: "yes" if v is True else ("no" if v is False else ("open" if v is None else str(v)))
KS = ["p3_equiangular", "p4_perp_triples", "p5_equal_area", "p6_rational", "p7_factors", "p9_all_pencils_regular"]


def score(o): return sum(1 for k in KS if o.get(k) is True or o.get(k.replace("area", "volume")) is True)


def pen(o): return " ".join(f"{k}:{v['regular']}/{v['count']}" for k, v in o.get("pencils", {}).items())


def row(name, arr, o):
    sp = o.get("sphericus", {}); tc = o.get("tacitus_crossings", {})
    tb = ("u" + str(tc["unweighted"]["beyond"]) if tc.get("unweighted", {}).get("beyond") else "") + \
         (" w" + str(tc["weighted"]["beyond"]) if tc.get("weighted", {}).get("beyond") else "")
    if "note" in tc: tb = "not run"
    free = Y(o.get("p7_free"))
    return (f"| {name} | {arr} | {o['planes']} | {o.get('regions', '')} | {Y(o.get('simplicial'))} | {Y(o.get('reflection'))} | "
            f"{Y(o.get('p3_equiangular'))} | {Y(o.get('p4_perp_triples'))} | {Y(o.get('p5_equal_area', o.get('p5_equal_volume')))} | "
            f"{Y(o.get('p6_rational'))} | {Y(o.get('p7_factors'))}/{free} | {Y(o.get('p9_all_pencils_regular'))} | {pen(o)} | "
            f"{sp.get('crossing_angle_values', '')}/{sp.get('arc_length_values', '')}/{sp.get('area_values', '')} | {Y(sp.get('harmonious_crossing', ''))} | {tb or '-'} | {score(o)} |")


HEAD = ("| polyhedron | plates | n | regions | simplicial | reflection | (3) equiangular | (4) perp. triples | (5) equal area | (6) rational | "
        "(7) factors/free | (9) all pencils regular | pencils k:regular/count | Sphericus angle/arc/area values | harmonious crossing | Tacitus beyond symmetry | score /6 |\n"
        "|" + "---|" * 17)

out = ["# Plate harmony: tables (generated by scripts/make_tables.py)", "",
       "Score = how many of (3), (4), (5), (6), (7 factoring), (9) hold. Sphericus values: number of distinct crossing angles / arc lengths "
       "between consecutive crossings / region areas (exact; for areas with irrational angles, values certified apart). Tacitus: even degrees "
       "k <= 20 where the crossing points (u unweighted, w weighted by circles per point) are silent beyond their symmetry group.", ""]
cat = D("catalogue-harmony.json")
out += ["## 1. The 163 catalogue polyhedra (Vacuus about the centre or the corner centroid; Johnson: also the volume centroid)", "", HEAD]
fam_order = ["Platonic", "Platonic polar", "Archimedean", "Catalan", "prism", "bipyramid", "antiprism", "trapezohedron", "Johnson"]
for o in sorted(cat, key=lambda o: (fam_order.index(o["family"]), o["name"], o["arrangement"])):
    out.append(row(o["name"], {"vacuus": "Vacuus", "resonus": "Resonus", "vacuus_volume": "Vacuus (vol.)"}[o["arrangement"]], o))
sr = D("stellation-roots.json")
out += ["", "## 2. The stellation cycle (frame of study 2026-11-25-stellation-cycle)", "",
        "M15 = Vacuus of I0, D0, the four Kepler-Poinsot stars and the Dogstar; R6 = Resonus of D0, its stars, the Dogstar and the Sunstar; "
        "R10 = Resonus of I0 and the great icosahedron; H31 = Resonus of the H3 permutahedron; S69 = Vacuus of the Sunstar.", "", HEAD]
for nm, o in sr["cycle"].items(): out.append(row(nm, "", o))
out += ["", "## 3. DICTO's root forms (Q(sqrt5); hub = the 31 planes of H31, as directions)", "", HEAD.replace("| score /6 |", "| score /6 | in hub |") + "---|"]
for nm, r in sr["roots"].items():
    for k in [k for k in r if k.startswith("vacuus")] + ["resonus"]:
        o = r[k]; out.append(row(nm, k, o) + f" {o['inside_hub']}/{o['planes']} |")
out += ["", "Corner positions on the phi-ladder (relative to the dodecahedron D0 the pieces are cut from):", ""]
for nm, r in sr["roots"].items():
    out.append(f"- {nm}: {r['corners']} corners, {r['edges']} edges, faces {r['face_sizes']}; corners at {dict(Counter(r['ladder']))}; "
               f"corner and volume centroids {'equal' if r['centroids_equal'] else 'differ'}")
fd = D("four-d.json")
out += ["", "## 4. The 4D Queens (600-cell, 120-cell)", "", "| arrangement | n | chambers | chi coefficients | simplicial | reflection | (3) | (4) | (5) equal volume | (6) | (7) factors/free | (9) | pencils k:regular/count | max pencil |", "|" + "---|" * 14]
for k in ("H4", "R300"):
    o = fd[k]
    out.append(f"| {o['name']} | {o['planes']} | {o['regions']} | {o['chi_coefficients']} | {Y(o['simplicial'])} | {Y(o['reflection'])} | {Y(o['p3_equiangular'])} | "
               f"{Y(o['p4_perp_triples'])} | {Y(o['p5_equal_volume'])} | {Y(o['p6_rational'])} | {Y(o['p7_factors'])}/{Y(o['p7_free'])} | {Y(o['p9_all_pencils_regular'])} | {pen(o)} | {o['max_pencil']} |")
cp = fd["coxeter_plane"]
out += ["", "Traces on the H4 Coxeter plane:", ""] + [f"- {k}: {v}" for k, v in cp.items() if k != "simple_roots"]
ya = D("yantra.json")
out += ["", "## 5. The spherical yantras (rho = 60 deg) and the stella-octangula frame", ""]
for k in ("kulaichev", "dicto"):
    o = ya[k]
    out += [f"### {o['name']} (u = {o['u'][:22]})", "",
            f"- planes {o['planes']}, crossing points {o['lines']} pairs, multiplicities {o['line_multiplicities']}, regions {o['regions']}, chi = {o['chi']}, simplicial {Y(o['simplicial'])}, reflection {Y(o['reflection'])}",
            f"- (3) {Y(o['p3_equiangular'])}; (4) {Y(o['p4_perp_triples'])} (perpendicular pairs inside the box: {o['perpendicular_pairs_in_box']}); (5) {Y(o['p5_equal_area'])}: {o['p5_how']}",
            f"- (6) {Y(o['p6_rational'])}: {o['p6_how']}; t7 leg angle / pi = {o['t7_leg_angle_over_pi']}",
            f"- (7) factors {Y(o['p7_factors'])}, free {Y(o['p7_free'])} ({o['p7_how']}); (9) {Y(o['p9_all_pencils_regular'])}; pencils {o['pencils']}",
            f"- Sphericus: {o['sphericus']}", f"- Tacitus of the crossings: {o['tacitus_crossings']}", ""]
out += ["### Vacuus of the stella-octangula yantra frame", "", HEAD, row("stella octangula (both tetrahedra)", "Vacuus", ya["stella_frame_vacuus"])]
open(os.path.join(STUDY, "data/tables.md"), "w").write("\n".join(out) + "\n")
print("FINAL ok tables", len(out))
