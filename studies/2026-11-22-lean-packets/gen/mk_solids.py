# Writes Packets/Solids.lean: for each generated solid, independence of the two normals at each edge, the value of
# each edge's dihedral angle (Values.lean), and its set of dihedral angles read from the set = its row of Table 1.
S = [  # prefix, Lean set name, edges, values by kind, Table-1 list, list lemma, edge realizing each list entry
 ("pyrD", "pyrDSet", 10, ["val_pyrDBase", "val_pyrDSide"], ["α", "2 * Real.pi / 3"], "pyrD", [0, 5],
  "the dodecahedron centre pyramid"),
 ("ti", "tiSet", 90, ["val_pentHex", "val_hexHex"], ["3 * Real.pi / 4 - α + β", "3 * Real.pi / 2 - 2 * β"], "ti",
  [60, 0], "the truncated icosahedron"),
 ("pyrI", "pyrISet", 6, ["val_pyrIBase", "val_pyrISide"], ["3 * Real.pi / 4 - β", "2 * Real.pi / 5"], "pyrI", [0, 3],
  "the icosahedron centre pyramid"),
 ("td", "tdSet", 90, ["val_decDec", "val_pentHex"], ["2 * α", "3 * Real.pi / 4 - α + β"], "td", [0, 5],
  "the truncated dodecahedron"),
 ("dh", "dhSet", 30, ["val_decDec"], ["2 * α"], "dod", [0], "the dodecahedron"),
 ("ih", "ihSet", 30, ["val_hexHex"], ["3 * Real.pi / 2 - 2 * β"], "ico", [0], "the icosahedron"),
 ("to", "toSet", 36, ["val_toSqHex", "val_toHexHex"], ["Real.pi / 2 + γ", "Real.pi - 2 * γ"], "toA", [0, 24],
  "the truncated octahedron"),
 ("tco", "tcoSet", 72, ["val_tcoSqHex", "val_tcoSqOct", "val_tcoHexOct"],
  ["Real.pi - γ", "3 * Real.pi / 4", "Real.pi / 2 + γ"], "tcoA", [0, 2, 48], "the truncated cuboctahedron"),
]
o = ['''/-
Lean formalization of DICTO's paper #117 (Zenodo 10.5281/zenodo.24411660). Part 8: Table 1 read from the sets.

For each solid built from exact coordinates (files Gen*.lean, generated by gen/gen_pieces.py; this file by
gen/mk_solids.py): `X_edgeAngle`: its dihedral angles, read from the set, are exactly its row of Table 1.
Solids: the dodecahedron centre pyramid, the truncated icosahedron, the icosahedron centre pyramid, the truncated
dodecahedron, the dodecahedron, the icosahedron, the truncated octahedron, the truncated cuboctahedron.
No `sorry`.
-/
module

public import Packets.Values
public import Packets.GenPyrD
public import Packets.GenTI
public import Packets.GenPyrI
public import Packets.GenTD
public import Packets.GenDH
public import Packets.GenIH
public import Packets.GenTO
public import Packets.GenTCO

@[expose] public section

open Set Module
open scoped RealInnerProductSpace

set_option maxRecDepth 20000

namespace Packets

open DehnCanon.Library (sol R3 sqrt5_sq)
open PacketsGen

lemma fin2_cases : ∀ k : Fin 2, k = 0 ∨ k = 1 := by decide

lemma fin3_cases : ∀ k : Fin 3, k = 0 ∨ k = 1 ∨ k = 2 := by decide

lemma fin5_cases : ∀ k : Fin 5, k = 0 ∨ k = 1 ∨ k = 2 ∨ k = 3 ∨ k = 4 := by decide
''']
for (X, Sn, nE, vals, tab, L, real, nm) in S:
    nK = len(vals)
    if nK >= 2:
        pat = " | ".join(["hk"] * nK)
        kcase = f"rcases fin{nK}_cases ({X}Kd e) with {pat} <;> rw [hk]"
        kcase_at = f"rcases fin{nK}_cases ({X}Kd e) with {pat} <;> rw [hk] at hg hX hY ⊢"
    else:
        kcase = f"rw [show {X}Kd e = 0 from Subsingleton.elim _ _]"
        kcase_at = f"rw [show {X}Kd e = 0 from Subsingleton.elim _ _] at hg hX hY ⊢"
    vec = "![" + ", ".join(tab) + "]"
    simps = f"simp only [{X}Gg, {X}GX, {X}GY, Matrix.cons_val_zero, Matrix.cons_val_one, Matrix.cons_val_two, Matrix.cons_val_three, Matrix.cons_val_four, Matrix.head_cons, Matrix.tail_cons] at hg hX hY ⊢"
    if nK >= 2:
        body = f"""  {kcase_at} <;>
    {simps}
""" + "\n".join(f"  · exact {v} hg hX hY" for v in vals)
    else:
        body = f"""  {kcase_at}
  {simps}
  exact {vals[0]} hg hX hY"""
    reals = "\n".join(f"    · exact ⟨{r}, by rw [{X}_val]; rfl⟩" for r in real)
    pats = " | ".join(["rfl"] * len(real))
    o.append(f"""
/-! ### {nm[0].upper() + nm[1:]} -/

def {Sn} : Set R3 := sol {X}N {X}B

lemma {X}_ind (e : Fin {nE}) : LinearIndependent ℝ ![{X}N ({X}Fi e), {X}N ({X}Fj e)] := by
  obtain ⟨hg, hX, hY⟩ := {X}_gram e
  apply linIndep_of_gram
  rw [hg, hX, hY]
  have h5 := sqrt5_sq
  {kcase} <;> simp [{X}Gg, {X}GX, {X}GY] <;> nlinarith [Real.sqrt_nonneg 5]

lemma {X}_val (e : Fin {nE}) :
    Real.pi - InnerProductGeometry.angle ({X}N ({X}Fi e)) ({X}N ({X}Fj e)) = ({vec} : Fin {nK} → ℝ) ({X}Kd e) := by
  obtain ⟨hg, hX, hY⟩ := {X}_gram e
{body}

/-- **The dihedral angles of {nm}, read from the set, are exactly its row of Table 1.** -/
theorem {X}_edgeAngle (θ : ℝ) : EdgeAngle {Sn} θ ↔ θ ∈ {L} := by
  rw [{Sn}, edgeAngle_edgeData {X}_isEdgeData {X}_interior {X}_ind, {L}_eq]
  constructor
  · rintro ⟨e, rfl⟩
    rw [{X}_val]
    {kcase} <;> simp
  · intro h
    simp only [List.mem_cons, List.not_mem_nil, or_false] at h
    rcases h with {pats}
{reals}
""")
o.append("end Packets\n")
open("../Packets/Solids.lean", "w").write("\n".join(o))
