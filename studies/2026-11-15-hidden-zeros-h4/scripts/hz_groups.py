"""Subgroup catalogue of an ambient group (up to conjugacy):
  R  every reflection subgroup (complete),
  C  every cyclic subgroup (complete),
  P2 every subgroup generated by two elements (complete: first generator over class representatives, second over all elements),
  Q  (H4 only) the quaternion families [L x R], [L x L].2, diagonal and Galois-twisted diagonal groups,
  and the closure of all these under 'rotation part' (intersection with SO) and 'adjoin -I'.
Conjugacy: fingerprint (order, class histogram) then an exact conjugating-element search."""
import numpy as np, multiprocessing as mp, time, sys
from hz_core import *

class Catalogue:
    def __init__(self, A, mats):
        self.A = A; self.mats = mats
        self.det = np.rint(np.linalg.det(mats)).astype(int)
        self.tr = np.trace(mats, axis1=1, axis2=2)
        n = mats.shape[1]
        self.refl = np.nonzero((self.det == -1) & (np.abs(self.tr - (n - 2)) < 1e-9))[0]
        self.minus = np.nonzero(np.abs(mats + np.eye(n)).max(axis=(1, 2)) < 1e-9)[0]
        self.minus = int(self.minus[0]) if len(self.minus) else None
        self.cls = A.classes(); self.ncls = int(self.cls.max()) + 1
        self.groups = []           # list of dict(order, fp, S (indices), gens, src)
        self.byfp = {}

    def fp(self, S):
        return (len(S), tuple(np.bincount(self.cls[S], minlength=self.ncls)))

    def add(self, gens, src):
        S = self.A.closure(gens)
        return self.add_S(S, gens, src)

    def add_S(self, S, gens, src):
        f = self.fp(S)
        for gi in self.byfp.get(f, []):
            G = self.groups[gi]
            if self.A.is_conjugate(S, gens, G['S']):
                if src not in G['src']: G['src'].append(src)
                return gi, False
        gi = len(self.groups)
        self.groups.append({'order': len(S), 'fp': f, 'S': S, 'gens': [int(g) for g in gens], 'src': [src]})
        self.byfp.setdefault(f, []).append(gi)
        return gi, True

    def reflection_subgroups(self):
        A = self.A; todo = []
        for r in self.refl:
            gi, new = self.add([r], 'R')
            if new: todo.append(gi)
        while todo:
            gi = todo.pop(); G = self.groups[gi]
            inG = np.zeros(A.n, bool); inG[G['S']] = True
            for r in self.refl:
                if inG[r]: continue
                gj, new = self.add(G['gens'] + [int(r)], 'R')
                if new: todo.append(gj)

    def cyclic(self):
        for i in range(self.A.n):
            if i == self.A.e: continue
            self.add([i], 'C')

    def derived(self):
        """rotation parts and +-I extensions, iterated to a fixed point"""
        A = self.A; changed = True
        while changed:
            changed = False
            for gi in range(len(self.groups)):
                G = self.groups[gi]
                if G.get('der'): continue
                G['der'] = True
                S = G['S']; rot = S[self.det[S] == 1]
                if 0 < len(rot) < len(S):
                    gens = small_gens(A, rot)
                    _, new = self.add_S(rot, gens, 'rot'); changed |= new
                if self.minus is not None and not np.isin(self.minus, S):
                    _, new = self.add(G['gens'] + [self.minus], 'pm'); changed |= new

def small_gens(A, S):
    """a short generating set of the subgroup S (greedy)"""
    S = np.asarray(S); gens = []; cur = np.array([A.e])
    inS = np.zeros(A.n, bool)
    order = np.random.default_rng(1).permutation(S)
    for g in order:
        if inS[g] and len(gens): continue
        gens.append(int(g)); cur = A.closure(gens); inS[:] = False; inS[cur] = True
        if len(cur) == len(S): break
    return gens

# ---------- two-generated subgroups, in parallel ----------
_GA = None
def _worker(args):
    a, bs = args
    A, cls, ncls = _GA
    found = {}
    for b in bs:
        S = A.closure([a, b])
        f = (len(S), tuple(np.bincount(cls[S], minlength=ncls)))
        lst = found.setdefault(f, [])
        if any(A.is_conjugate(S, [a, b], S2) for S2, _ in lst): continue
        lst.append((S, (int(a), int(b))))
    return [(f, g) for f, lst in found.items() for _, g in lst]

def two_generated(cat, procs=20, log=print):
    global _GA
    A = cat.A; cls = cat.cls; reps = A._reps
    _GA = (A, cls, cat.ncls)
    jobs = []
    for a in reps:
        if a == A.e: continue
        # b over all elements; chunk for balance
        for c in np.array_split(np.arange(A.n), 8):
            jobs.append((a, c))
    t = time.time(); out = []
    with mp.get_context('fork').Pool(procs) as pool:
        for i, res in enumerate(pool.imap_unordered(_worker, jobs)):
            out.extend(res)
            if (i + 1) % max(1, len(jobs) // 20) == 0:
                log(f'PROGRESS {0.05 + 0.25 * (i + 1) / len(jobs):.3f} two-generated {i + 1}/{len(jobs)} chunks, {len(out)} candidates, {time.time() - t:.0f}s')
    for f, g in out:
        cat.add(list(g), 'P2')

# ---------- quaternion families (H4) ----------
def quaternion_families(cat, labels, X):
    """labels[g] = (l, r, s): g(x) = l (x or xbar) rbar.  Subgroups of 2I (as index sets of unit icosians) up to conjugacy are generated
    from a few icosians; we take one representative of each type: 1, {+-1}, C3, C4, C5, C6, C10, Q8, 2D3, 2D5, 2T, 2I."""
    A = cat.A
    lab = {tuple(map(int, t)): i for i, t in enumerate(labels)}
    def el(l, r, s=0):
        k = (l, r, s)
        if k in lab: return lab[k]
        # (l, r) and (-l, -r) give the same map
        return lab[(NEG[l], NEG[r], s)]
    Xf = to_float(X) / 2
    ki = {tuple(np.round(v, 9)): i for i, v in enumerate(Xf)}
    NEG = [ki[tuple(np.round(-v, 9))] for v in Xf]
    one = ki[(1.0, 0.0, 0.0, 0.0)]
    def find(pred):
        return [i for i in range(120) if pred(Xf[i])]
    def qm(a, b):
        a0, a1, a2, a3 = a; b0, b1, b2, b3 = b
        return np.array([a0*b0-a1*b1-a2*b2-a3*b3, a0*b1+a1*b0+a2*b3-a3*b2, a0*b2-a1*b3+a2*b0+a3*b1, a0*b3+a1*b2-a2*b1+a3*b0])
    def closeq(gs):
        S = {one}; fr = [one]
        while fr:
            nf = []
            for x in fr:
                for g in gs:
                    y = ki[tuple(np.round(qm(Xf[x], Xf[g]), 9))]
                    if y not in S: S.add(y); nf.append(y)
            fr = nf
        return sorted(S)
    # generators: an element of order n has real part cos(2pi/n)
    def of_order(n): return [i for i in range(120) if abs(Xf[i][0] - np.cos(2 * np.pi / n)) < 1e-9]
    o3, o4, o5, o6, o10 = (of_order(n) for n in (3, 4, 5, 6, 10))
    m1 = NEG[one]
    subs = {'1': [one], '+-1': [m1], 'C3': [o3[0]], 'C4': [o4[0]], 'C5': [o5[0]], 'C6': [o6[0]], 'C10': [o10[0]]}
    # binary dihedral 2Dn: a cyclic C_2n plus an order-4 element anticommuting (orthogonal pure part)
    def bindih(c):
        v = Xf[c][1:]
        for j in o4:
            if abs(np.dot(Xf[j][1:], v)) < 1e-9: return [c, j]
    subs['Q8'] = bindih(o4[0]); subs['2D3'] = bindih(o6[0]); subs['2D5'] = bindih(o10[0])
    # 2T: Hurwitz units {+-1,+-i,..,(+-1+-i+-j+-k)/2} ; 2I: all
    hur = [i for i in range(120) if np.allclose(np.abs(Xf[i]) * 2 % 1, 0)]
    subs['2T'] = [h for h in hur if abs(Xf[h][0] - 0.5) < 1e-9][:2] + [ki[(0.0, 1.0, 0.0, 0.0)]]
    subs['2I'] = [o5[0], o4[0], o3[0]]
    groups = {k: closeq(v) for k, v in subs.items()}
    expect = {'1': 1, '+-1': 2, 'C3': 3, 'C4': 4, 'C5': 5, 'C6': 6, 'C10': 10, 'Q8': 8, '2D3': 12, '2D5': 20, '2T': 24, '2I': 120}
    for k, v in groups.items():
        if len(v) != expect[k]:
            # fix 2T / 2I by brute closure growth
            pass
    assert {k: len(v) for k, v in groups.items()} == expect, {k: len(v) for k, v in groups.items()}
    star = el(one, one, 1)
    # Galois automorphism of 2I: sigma on coordinates then the fixed coordinate map that returns the 600-cell to itself
    from hz_universes import galois_perm
    sig = galois_perm(X)
    names = list(groups)
    added = []
    for i, Ln in enumerate(names):
        for Rn in names[i:]:
            gens = [el(l, one) for l in subs[Ln]] + [el(one, r) for r in subs[Rn]]
            added.append((f'[{Ln} x {Rn}]', gens))
            if Ln == Rn: added.append((f'[{Ln} x {Ln}].2', gens + [star]))
    for Ln in names:
        gens = [el(l, l) for l in subs[Ln]]
        added.append((f'diag {Ln}', gens)); added.append((f'diag {Ln}.2', gens + [star]))
        added.append((f'+-diag {Ln}', gens + [el(m1, one)]))
        # Galois-twisted diagonal: l -> (l, sigma(l)), only when sigma maps the subgroup into 2I: always (2I is sigma-stable)
        tw = [el(l, int(sig[l])) for l in subs[Ln]]
        try:
            added.append((f'twisted diag {Ln}', tw)); added.append((f'twisted diag {Ln}.2', tw + [star]))
            added.append((f'+-twisted diag {Ln}', tw + [el(m1, one)]))
        except KeyError:
            pass
    for name, gens in added:
        S = A.closure(gens)
        cat.add_S(S, small_gens(A, S) if len(gens) > 3 else gens, 'Q:' + name)
