#!/usr/bin/env python3
"""Tables from data/census-*.json -> data/tables.md"""
import json, os, glob
from collections import Counter
D = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'data')
out = ['# Hidden-zeros census: tables (generated by scripts/hz_report.py)', '']
def fmt(l): return ', '.join(map(str, l)) if l else '-'
for u in ['U600', 'U120', 'U24', 'SNUB', 'E8']:
    p = os.path.join(D, f'census-{u}.json')
    if not os.path.exists(p): out += [f'## {u}: not run', '']; continue
    d = json.load(open(p))
    S = d['sets']
    out += [f'## {d["universe"]} ({d["N"]} points, {d["dim"]}D; symmetry group used for equivalence: order {d["ambient_order"]}; Double Vision map: {"yes" if d["galois"] else "no"})', '',
            f'Subgroup classes: {d["n_groups"]}. Distinct sets (orbits, unions of two orbits, twisted-class unions): {len(S)} '
            f'({Counter(s["kind"] for s in S)}).', '',
            f'Checks: {sum(1 for c in d["checks"] if c[1])}/{len(d["checks"])} passed' + ('' if all(c[1] for c in d['checks']) else ' FAILED: ' + '; '.join(c[0] for c in d['checks'] if not c[1])), '',
            'Degree linkage (rational weightings): T_j = 0 implies T_k = 0 for k in the list:', '']
    for j, ks in d['linkage'].items():
        if ks and len(ks) < 19: out.append(f'- T_{j} = 0 ⇒ {fmt(ks)}')
    tally = Counter()
    for s in S:
        for m in ('G', 'X', 'ZONAL', 'TW', 'SPAN', 'GAL', 'OPEN'):
            tally[m] += len(s.get(m, []))
    out += ['', f'Zeros by mechanism (set, degree pairs): {dict(tally)}', '']
    tw = [s for s in S if s.get('TW') or s.get('TWU')]
    if tw:
        out += ['### Twisted-silent sets (zeros explained only by twisted characters)', '',
                '| size | kind | stabiliser | symmetry | all zeros | twisted-silent degrees | G order | alpha | classes used (sizes) | type per degree |', '|---|---|---|---|---|---|---|---|---|---|']
        for s in sorted(tw, key=lambda s: (s['size'], s['zeros'])):
            t = s['twisted']
            types = '; '.join(f'{k}: {"forced" if t["degrees"][str(k)]["hom_dim"] == 0 else ("char 0" if k in s["TW"] else "union cancellation")}' for k in s['TW'] + s.get('TWU', []))
            out.append(f'| {s["size"]} | {s["kind"]} | {s["stab_order"]} | {s["sym_order"]} | {fmt(s["zeros"])} | **{fmt(s["TW"] + s.get("TWU", []))}** | {t["G_order"]} | '
                       f'{"inner" if t["alpha_inner"] else "OUTER"} | {t["n_classes_used"]} ({fmt(t["class_sizes"])}) | {types} |')
        out.append('')
    op = [s for s in S if s.get('OPEN')]
    out += ['### Unexplained (OPEN) zeros', '']
    if not op: out += ['None.', '']
    else:
        out += ['| size | kind | stabiliser | symmetry | all zeros | explained | OPEN | conditions | Galois-self | source groups |', '|---|---|---|---|---|---|---|---|---|---|']
        for s in sorted(op, key=lambda s: (s['size'], s['zeros'])):
            ex = fmt(sorted(set(s['G'] + s['X'] + s.get('ZONAL', []) + s.get('TW', []) + s['SPAN'] + s['GAL'])))
            src = '; '.join('/'.join(d['groups'][g]['src'][:2]) + f' (|G|={d["groups"][g]["order"]})' for g in s['groups'][:2]) or 'twisted union'
            out.append(f'| {s["size"]} | {s["kind"]} | {s["stab_order"]} | {s["sym_order"]} | {fmt(s["zeros"])} | {ex} | **{fmt(s["OPEN"])}**{" (twisted-union cancellation: " + fmt(s["TWU"]) + ")" if s.get("TWU") else ""} | {s.get("conditions")} | {s.get("galois_self", "-")} | {src} |')
        out.append('')
    gl = [s for s in S if s.get('GAL')]
    if gl:
        out += ['### Zeros explained only with Double Vision (GAL)', ''] + [f'- size {s["size"]} {s["kind"]}: zeros {fmt(s["zeros"])}, GAL {fmt(s["GAL"])}' for s in gl] + ['']
open(os.path.join(D, 'tables.md'), 'w').write('\n'.join(out) + '\n')
print('\n'.join(out))
