# Which ring of each chain view completes a named solid (for the app's build movie, DICTO 2026-10-14). From steps.json (the main
# route, ring by ring, faces counted on the fused solid). Writes src/app/movie-names.js (generated).
import json, os
HERE = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
S = json.load(open(os.path.join(HERE, 'steps.json')))
def name(x):
    sh = x['faceShapes']; F = x['faces']; P = x['planes']
    if x['convex']:
        return {(('3-gon', 20),): 'icosahedron', (('5-gon', 12),): 'dodecahedron', (('3-gon', 20), ('5-gon', 12)): 'icosidodecahedron',
                (('5-gon', 12), ('6-gon', 20)): 'truncatedIcosahedron', (('4-gon', 30),): 'rhombicTriacontahedron',
                (('3-gon', 60), ('4-gon', 30), ('5-gon', 12)): 'hecatodihedron'}.get(tuple(sorted(sh.items())))
    if sh == {'3-gon': 60} and P == 12: return 'greatStellatedDodecahedron'
    if sh == {'3-gon': 60} and P == 20: return 'excavatedDodecahedron'
    if sh == {'4-gon': 60} and P == 30: return 'rhombicHexecontahedron'
    return None
VIEWS = {'karma.lotus': ('karma', 'lotus'), 'karma.step2': ('karma', 'step2'), 'karma.dodeca': ('karma', 'dodeca'), 'dharma.cycle': ('dharma', 'cycle'),
         'dharma.inner': ('dharma', 'inner'), 'dharma.outer': ('dharma', 'outer'), 'dharma.hinge': ('dharma', 'hinge'), 'bodhi.seed': ('bodhi', 'seed'),
         'bodhi.kitB': ('bodhi', 'kitB'), 'bodhi.kitA': ('bodhi', 'kitA'), 'bodhi.hollow': ('bodhi', 'hollow')}
out = {}
for v, (k, view) in VIEWS.items():
    out.setdefault(k, {})[view] = [{'ring': s['added'].split(' ')[0], 'name': name(s)} for s in S[v]]
js = '// Generated by studies/2026-10-13-fused-shells/scripts/movie_names.py: for each chain view, its rings in build order\n'
js += '// (role@distance from the centre) and the named solid each completes (checked counts, steps.json). Do not edit.\n'
js += 'export default ' + json.dumps(out, indent=1, ensure_ascii=False) + ';\n'
open(os.path.join(HERE, '..', '..', 'src', 'app', 'movie-names.js'), 'w').write(js)
for k, vs in out.items():
    for view, L in vs.items(): print(k, view, [x['name'] for x in L if x['name']])
