# Exact stops of the 20-corner sinking (DICTO 2026-10-27), in Q(sqrt5, sqrt3) with sympy.
# Icosaxes = {|x_i| <= phi/2} ∩ {|x|+|y|+|z| <= phi^2/2} (from krp-core golden-split.js); Lotus Jewel Axes = Icosaxes minus 8 Tricaps
# (base: the icosahedron face in the hexagon plane, tip (1/(2 phi))(±1,±1,±1)). Pieces at d*M u, turned by M, u = (1,1,1)/sqrt3.
import itertools, sympy as sp
phi = (1 + sp.sqrt(5)) / 2; s3 = sp.sqrt(3)
a, b = phi / 2, phi ** 2 / 2
# vertices by brute force: intersections of 3 planes among the 14, kept if inside
planes = [(sp.Matrix([1 if j == i else 0 for j in range(3)]) * s, a) for i in range(3) for s in (1, -1)] + \
         [(sp.Matrix(sg), b) for sg in itertools.product([1, -1], repeat=3)]
verts = []
for P in itertools.combinations(planes, 3):
    A = sp.Matrix.hstack(*[p[0] for p in P]).T
    if A.det() == 0: continue
    x = A.solve(sp.Matrix([p[1] for p in P])).applyfunc(sp.nsimplify)
    if all(sp.simplify(n.dot(x) - h) <= 0 for n, h in planes) and not any(sp.simplify((x - y).norm()) == 0 for y in verts): verts.append(x)
print('Icosaxes corners:', len(verts))
# the icosahedral rotations, exact (generated by a three-fold and a five-fold turn of the icosahedron (0, ±1/2, ±phi/2) cyclic)
C3 = sp.Matrix([[0, 0, 1], [1, 0, 0], [0, 1, 0]])
k = sp.Matrix([0, 1, phi]) / sp.sqrt(1 + phi ** 2); th = 2 * sp.pi / 5                # five-fold turn about the corner (0, 1/2, phi/2)
K = sp.Matrix([[0, -k[2], k[1]], [k[2], 0, -k[0]], [-k[1], k[0], 0]])
C5 = (sp.cos(th) * sp.eye(3) + sp.sin(th) * K + (1 - sp.cos(th)) * k * k.T).applyfunc(lambda e: sp.nsimplify(sp.simplify(e), [sp.sqrt(5)]))
ICO = [sp.Matrix(p) for s1 in (1, -1) for s2 in (1, -1) for p in ([0, s1 / sp.S(2), s2 * phi / 2], [s1 / sp.S(2), s2 * phi / 2, 0], [s2 * phi / 2, 0, s1 / sp.S(2)])]
assert sp.simplify(C5 * C5.T - sp.eye(3)) == sp.zeros(3) and sp.simplify(C5.det() - 1) == 0
assert all(any(sp.simplify((C5 * q - r).norm()) == 0 for r in ICO) for q in ICO), 'C5 must keep the icosahedron'
print('C5 =', C5)
G = [sp.eye(3)]; frontier = [sp.eye(3)]
key = lambda M: tuple(sp.N(x, 12) for x in M)
seen = {key(sp.eye(3))}
while frontier:
    nxt = []
    for M in frontier:
        for g in (C3, C5):
            N = (g * M).applyfunc(sp.simplify)
            if key(N) not in seen: seen.add(key(N)); G.append(N); nxt.append(N)
    frontier = nxt
print('rotations:', len(G))
u = sp.Matrix([1, 1, 1]) / s3
sites = {}
for M in G: sites.setdefault(tuple(sp.N(x, 12) for x in M * u), M)
print('corners of the dodecahedron:', len(sites))
S = list(sites.values())
# 1) first touch (separating axes): two convex solids have disjoint insides exactly when a face normal of either, or a cross product
#    of an edge direction of each, separates them. Along axis n the gap is d*n.(c1-c0) - h_A(n) - h_B(-n); the touch is the least d
#    with a gap >= 0 on some axis.
edges = {tuple(sp.N(x, 12) for x in (p - q)): (p - q) for p, q in itertools.combinations(verts, 2)
         if sum(1 for n, hh in planes if sp.simplify(n.dot(p) - hh) == 0 and sp.simplify(n.dot(q) - hh) == 0) >= 2}
dirs = list({tuple(abs(round(float(x), 9)) for x in v): v for v in edges.values()}.values())
nb = sorted(S[1:], key=lambda M: float((M * u - S[0] * u).norm()))[0]   # a nearest neighbour (they meet along a dodecahedron edge)
A, B = S[0], nb; c0v, c1v = A * u, B * u
def supp(M, n): return max((sp.simplify(n.dot(M * v)) for v in verts), key=lambda e: float(e))
axes = [A * n for n, _ in planes] + [B * n for n, _ in planes] + [(A * e).cross(B * f) for e in dirs for f in dirs]
cands = []
for n in axes:
    if float(n.norm()) < 1e-9: continue
    den = n.dot(c1v - c0v)
    for sgn in (1, -1):
        m = sgn * n
        if float(sgn * den) <= 1e-12: continue
        cands.append((sp.simplify((supp(A, m) + supp(B, -m)) / (sgn * den)), m))
d_touch, n_touch = min(cands, key=lambda c: float(c[0]))
d_touch = sp.nsimplify(sp.radsimp(d_touch))
print('first touch d =', d_touch, '=', sp.N(d_touch, 12), '| phi^2 sqrt3/2 =', sp.N(phi ** 2 * s3 / 2, 12), '| equal:', sp.simplify(d_touch - phi ** 2 * s3 / 2) == 0)
# 2) windows close: the five-fold axis through a face centre first meets a piece: max d over {(t, d): t*ax in the piece at d M u},
#    a 2-variable linear programme; its optimum is at the meeting of two constraint lines, checked feasible exactly.
ax = sp.Matrix([0, 1, phi]); ax = ax / ax.norm()
dd, t = sp.symbols('d t', real=True)
best = None
for M in S:
    if float((M * u).dot(ax)) < 0.5: continue
    cons = [sp.expand(n.dot(M.T * (t * ax) - dd * u) - hh) for n, hh in planes]
    for c1_, c2_ in itertools.combinations(cons, 2):
        so = sp.solve([c1_, c2_], [t, dd], dict=True)
        if not so: continue
        dv, tv = sp.simplify(so[0][dd]), sp.simplify(so[0][t])
        if float(dv) <= 0 or any(float(c.subs({t: tv, dd: dv})) > 1e-12 for c in cons): continue
        if best is None or float(dv) > float(best): best = dv
    break                                      # one piece suffices (the five are turned copies)
best = sp.nsimplify(sp.radsimp(best))
print('windows close d =', best, '=', sp.N(best, 12), '| d / touch =', sp.nsimplify(sp.radsimp(best / d_touch)), '| equals 1/phi:', sp.simplify(best / d_touch - 1 / phi) == 0)
# 3) hollow fills (Icosaxes): the centre enters a piece when d = the hexagon's distance b/sqrt3
d_fill = b / s3
print('Icosaxes hollow fills d =', sp.nsimplify(d_fill), '| d / touch =', sp.nsimplify(sp.radsimp(d_fill / d_touch)), '| equals 1/3:', sp.simplify(d_fill / d_touch - sp.Rational(1, 3)) == 0)
# 4) Lotus Jewel Axes: the centre lies in the inward dent until it passes the Tricap's tip, at distance |(1/(2phi))(1,1,1)|
d_lja = sp.sqrt(3) / (2 * phi)
print('Lotus Jewel Axes: centre covered for d <', sp.nsimplify(d_lja), '| d / touch =', sp.nsimplify(sp.radsimp(d_lja / d_touch)), '| equals 1/phi^3:', sp.simplify(d_lja / d_touch - phi ** -3) == 0)
