# shuffle_smooth.py: independent recomputation (our own code, from the paper's definitions) of Kilpatrick, "Shuffle squares in smooth
# binary words and the Kolakoski sequence" (aiXiv 2610.00204, ai-authored; arXiv 2610.02262): Table 1 (smooth words, smooth tangrams
# = even counts of both letters, non-shuffle tangrams for n = 2..40), the 34 exceptions (all of length <= 16, Table 2 orbits) and
# Corollary 1.2 (a Kolakoski prefix is a shuffle square iff both letters occur an even number of times and its length is not 4 or 8),
# checked for prefixes up to length NK.
# Smooth (paper 2.1): runs of length 1 or 2 only; D(w) = run lengths with a first or last run of length 1 deleted; repeat to empty.
# Smooth words are factorial (Lemma 2.2), so all smooth words of length n+1 extend smooth words of length n: generated by extension.
# Shuffle square test: left to right, each letter either opens (appended to the first copy) or closes (matches the oldest unmatched
# letter of the first copy); state (position, unmatched queue), memoised. A word is a shuffle square iff the queue can end empty.
import sys
from functools import lru_cache
NK = int(sys.argv[1]) if len(sys.argv) > 1 else 300
def runs(w):
    out = []; i = 0
    while i < len(w):
        j = i
        while j < len(w) and w[j] == w[i]: j += 1
        out.append(j - i); i = j
    return out
def smooth(w):
    while w:
        r = runs(w)
        if any(x > 2 for x in r): return False
        a, b = 0, len(r)
        if r[0] == 1: a = 1
        if r[-1] == 1: b -= 1
        w = ''.join(str(x) for x in r[a:b]) if a < b else ''
    return True
def shuffle_square(w):
    n = len(w)
    if n % 2: return False
    @lru_cache(maxsize=None)
    def go(i, q):
        if len(q) > n - i: return False
        if i == n: return q == ''
        c = w[i]
        if q and q[0] == c and go(i + 1, q[1:]): return True
        return go(i + 1, q + c)
    r = go(0, ''); go.cache_clear(); return r
level = ['1', '2']; table = {}; exceptions = []; total = 2
for n in range(2, 41):
    level = [w + c for w in level for c in '12' if smooth(w + c)]; total += len(level)
    if n % 2 == 0:
        tang = [w for w in level if w.count('1') % 2 == 0 and w.count('2') % 2 == 0]
        neg = [w for w in tang if not shuffle_square(w)]
        exceptions += neg; table[n] = (len(level), len(tang), len(neg))
claim = {2:(4,2,0),4:(10,6,2),6:(18,6,0),8:(34,18,6),10:(50,22,4),12:(78,42,10),14:(110,54,4),16:(142,74,8),18:(186,66,0),20:(250,150,0),22:(314,146,0),24:(378,222,0),26:(446,206,0),28:(534,274,0),30:(654,282,0),32:(782,414,0),34:(910,466,0),36:(1038,542,0),38:(1166,538,0),40:(1302,674,0)}
for n in sorted(table): print(n, table[n], 'claim', claim[n], 'OK' if table[n] == claim[n] else 'DIFFERS', flush=True)
reps = ['1221','12122112','12212112','1211211221','112122122112','121122122112','122121121221','11221211211221','1212212211211221','1221121121221221']
G = lambda w: {w, w[::-1], w.translate(str.maketrans('12','21')), w[::-1].translate(str.maketrans('12','21'))}
orbit_set = set().union(*[G(r) for r in reps])
print(f'exceptions: {len(exceptions)} (claim 34), max length {max(map(len, exceptions))} (claim <= 16), equal to the union of the Table 2 orbits: {set(exceptions) == orbit_set}')
# Kolakoski
K = [1, 2, 2]; i = 2
while len(K) < NK:
    K += [1 + (len(K) % 2 == 0) if False else (2 if K[-1] == 1 else 1)] * K[i]; i += 1
K = ''.join(map(str, K[:NK]))
kbad = []
for n in range(1, NK + 1):
    p = K[:n]; pred = p.count('1') % 2 == 0 and p.count('2') % 2 == 0 and n not in (4, 8)
    if shuffle_square(p) != pred: kbad.append(n)
print(f'Kolakoski prefixes 1..{NK}: K starts {K[:21]} (paper 122112122122112112212); Corollary 1.2 violations {kbad[:5]} ({len(kbad)})')
print(f'smooth words regenerated through length 40: {total} (paper 16,146)')
ok = all(table[n] == claim[n] for n in claim) and len(exceptions) == 34 and set(exceptions) == orbit_set and not kbad and K[:21] == '122112122122112112212' and total == 16146
print('FINAL ok' if ok else 'FINAL FAIL')
