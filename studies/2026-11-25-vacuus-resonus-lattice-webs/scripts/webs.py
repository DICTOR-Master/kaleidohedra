#!/usr/bin/env python3
"""Do the Vacuus and the Resonus of the five parallelohedra continue into periodic webs of planes? (25 Nov 2026)

Exact arithmetic only: numbers a + b*sqrt(3) with rational a, b (class Q3); every sign is decided exactly
(compare a^2 with 3 b^2). No floating point anywhere.

Frame. Every 3D parallelohedron is a zonotope P = Z(lam_1 u_1, ..., lam_m u_m) = sum of segments [-lam_k u_k/2, lam_k u_k/2]
(Fedorov 1885; Minkowski-Venkov), with u_k one of five fixed unimodular vector systems below (each realised uniquely up to a
linear map), and lam_k > 0. The standard (most symmetric) member has all lam_k = 1 (the elongated dodecahedron with equal
edges has the axis lam = sqrt(3)/2). Its face-to-face lattice tiling has lattice Lambda = G Z^3, G = U D U^T (checked below
against the facet vectors).

Definitions (no new ones):
  Vacuus (#110): one plate through the centre O and each edge.  Resonus (DICTO): one plane through O parallel to each face.
Web test (exact): for a plane through O with normal n, its translates by Lambda meet the interior of the cell P + mu without
passing through mu exactly when 0 < |n.nu| < h(n) for some nu in Lambda, where h(n) = max over P of n.x = sum lam_k |n.u_k| / 2.
So the family continues as a web if and only if n.Lambda is discrete with gap d(n) >= h(n) (and then the plane through a cell's
interior is the cell's own plane, with the same normal through its centre).
"""
import sys, json, itertools
from fractions import Fraction as Fr
from math import gcd


class Q3:
    """a + b sqrt3, a and b rational."""
    __slots__ = ("a", "b")
    def __init__(s, a=0, b=0): s.a = Fr(a); s.b = Fr(b)
    def __add__(s, o): o = q3(o); return Q3(s.a + o.a, s.b + o.b)
    __radd__ = __add__
    def __neg__(s): return Q3(-s.a, -s.b)
    def __sub__(s, o): return s + (-q3(o))
    def __rsub__(s, o): return q3(o) - s
    def __mul__(s, o): o = q3(o); return Q3(s.a * o.a + 3 * s.b * o.b, s.a * o.b + s.b * o.a)
    __rmul__ = __mul__
    def __truediv__(s, o):
        o = q3(o); n = o.a * o.a - 3 * o.b * o.b; assert n != 0
        return s * Q3(o.a / n, -o.b / n)
    def sign(s):
        if s.b == 0: return (s.a > 0) - (s.a < 0)
        if s.a == 0: return (s.b > 0) - (s.b < 0)
        if (s.a > 0) == (s.b > 0): return 1 if s.a > 0 else -1
        # opposite signs: compare a^2 with 3 b^2
        big = s.a * s.a - 3 * s.b * s.b
        return (1 if s.a > 0 else -1) * ((big > 0) - (big < 0))
    def __bool__(s): return s.a != 0 or s.b != 0
    def __eq__(s, o): o = q3(o); return s.a == o.a and s.b == o.b
    def __hash__(s): return hash((s.a, s.b))
    def __lt__(s, o): return (s - o).sign() < 0
    def __le__(s, o): return (s - o).sign() <= 0
    def __abs__(s): return -s if s.sign() < 0 else s
    def rational(s): return s.b == 0
    def __repr__(s):
        if s.b == 0: return str(s.a)
        return f"{s.a}+{s.b}*sqrt3" if s.a else f"{s.b}*sqrt3"


def q3(x): return x if isinstance(x, Q3) else Q3(x)
def dot(u, v): return sum((q3(a) * b for a, b in zip(u, v)), Q3())
def cross(u, v): return (u[1] * v[2] - u[2] * v[1], u[2] * v[0] - u[0] * v[2], u[0] * v[1] - u[1] * v[0])
def det3(a, b, c): return dot(a, cross(b, c))
def scal(t, v): return tuple(q3(t) * x for x in v)
def vadd(*vs): return tuple(sum((q3(v[i]) for v in vs), Q3()) for i in range(3))


def canon(v):
    """Scale a vector so its first nonzero entry is 1 (direction up to sign)."""
    v = tuple(q3(x) for x in v)
    f = next(x for x in v if x)
    return tuple(x / f for x in v)


def commensurable_gcd(xs):
    """gcd of the additive group generated by xs, or None when the group is dense (two incommensurable generators)."""
    xs = [abs(q3(x)) for x in xs if q3(x)]
    if not xs: return Q3()
    g = xs[0]
    rs = []
    for x in xs:
        r = x / g
        if not r.rational(): return None
        rs.append(r.a)
    den = 1
    for r in rs: den = den * r.denominator // gcd(den, r.denominator)
    G = 0
    for r in rs: G = gcd(G, int(r * den))
    return g * Fr(G, den)


def solve3(M, b):
    """Solve M y = b (M given as a list of 3 columns) by Cramer's rule."""
    c0, c1, c2 = M; D = det3(c0, c1, c2)
    return (det3(b, c1, c2) / D, det3(c0, b, c2) / D, det3(c0, c1, b) / D)


def int_lattice_det(vs):
    """|det| of the integer lattice spanned by integer vectors (Hermite reduction)."""
    rows = [list(v) for v in vs if any(v)]
    basis = []
    for col in range(3):
        piv = [r for r in rows if r[col] != 0]
        rest = [r for r in rows if r[col] == 0]
        while len(piv) > 1:
            piv.sort(key=lambda r: abs(r[col]))
            p = piv[0]
            new = [p]
            for r in piv[1:]:
                q = r[col] // p[col]
                r2 = [a - q * b for a, b in zip(r, p)]
                (new if r2[col] != 0 else rest).append(r2)
            piv = new
        if piv: basis.append(piv[0])
        rows = rest
    if len(basis) < 3: return 0
    d = 1
    for i, b in enumerate(basis): d *= b[i]
    return abs(d)


E1, E2, E3 = (1, 0, 0), (0, 1, 0), (0, 0, 1)
TYPES = {   # zone vectors u_k; the first three are the unit vectors, so Lambda = U D U^T Z^3
    "cube": [E1, E2, E3],
    "hexagonal prism": [E1, E2, E3, (1, 1, 0)],
    "rhombic dodecahedron": [E1, E2, E3, (1, 1, 1)],
    "elongated dodecahedron": [E1, E2, E3, (1, 1, 0), (1, 1, 1)],
    "truncated octahedron": [E1, E2, E3, (1, 1, 0), (0, 1, 1), (1, 1, 1)],
}
# Euclidean standard coordinates for reporting (a linear image of the frame with lam_k = 1, up to signs)
SQ3 = Q3(0, 1)


class Zono:
    def __init__(s, name, lam):
        s.name = name; s.U = [tuple(q3(x) for x in u) for u in TYPES[name]]; s.m = len(s.U)
        s.lam = [q3(x) for x in lam]; assert len(s.lam) == s.m and all(l.sign() > 0 for l in s.lam)
        s.V = [scal(l, u) for l, u in zip(s.lam, s.U)]
        # lattice generator columns G e_i = sum_k lam_k u_k (u_k . e_i)
        s.G = [vadd(*[scal(s.lam[k] * s.U[k][i], s.U[k]) for k in range(s.m)]) for i in range(3)]
        s.facets(); s.edges(); s.check_lattice()

    def h(s, n): return sum((s.lam[k] * abs(dot(n, s.U[k])) for k in range(s.m)), Q3()) / 2

    def facets(s):
        fl = {}
        for i, j in itertools.combinations(range(s.m), 2):
            n = cross(s.U[i], s.U[j])
            if any(n): fl.setdefault(canon(n), n)
        s.F = []
        for key, n in fl.items():
            S = [k for k in range(s.m) if not dot(n, s.U[k])]
            t = vadd(*[scal(dot(n, s.V[k]).sign(), s.V[k]) for k in range(s.m) if k not in S])
            s.F.append({"n": key, "S": S, "t": t, "size": 2 * len(S)})   # a facet spanned by |S| zones is a 2|S|-gon

    def edges(s):
        """Edges parallel to u_j <-> regions of the line arrangement {m.u_k = 0} in the covectors m perpendicular to u_j."""
        s.Ed = []
        for j in range(s.m):
            uj = s.U[j]
            a = cross(uj, E1) if any(cross(uj, E1)) else cross(uj, E2)
            b = cross(uj, a)
            others = [k for k in range(s.m) if k != j]
            rays = []
            for k in others:
                r = (dot(a, s.U[k]), dot(b, s.U[k]))         # m = x a + y b, m.u_k = x r0 + y r1
                rays += [(-r[1], r[0]), (r[1], -r[0])]
            sv = set()
            for p, q in itertools.combinations(rays, 2):
                x, y = p[0] + q[0], p[1] + q[1]
                mm = vadd(scal(x, a), scal(y, b))
                sg = tuple(dot(mm, s.U[k]).sign() for k in others)
                if 0 not in sg: sv.add(sg)
            for sg in sv:
                c = vadd(*[scal(Fr(e, 2), s.V[k]) for e, k in zip(sg, others)])
                s.Ed.append({"j": j, "c": c})
        s.nV = 2 - 2 * len(s.F) + len(s.Ed)          # Euler; compared with the catalogue counts below

    def check_lattice(s):
        """Every facet vector t_F lies in G Z^3 and the facet vectors generate G Z^3 (index 1)."""
        ys = []
        for f in s.F:
            y = solve3(s.G, f["t"])
            assert all(c.rational() and c.a.denominator == 1 for c in y), (s.name, "facet vector not in G Z^3")
            ys.append(tuple(int(c.a) for c in y))
        assert int_lattice_det(ys) == 1, (s.name, "facet vectors do not generate G Z^3")
        vol = abs(det3(*s.G))
        s.covol = vol

    def lat_vals(s, n): return [dot(n, g) for g in s.G]

    def test(s, n):
        d = commensurable_gcd(s.lat_vals(n)); h = s.h(n)
        ok = d is not None and d >= h
        w = None
        if not ok:   # witness: a lattice vector nu with 0 < |n.nu| < h
            best = None
            for y in itertools.product(range(-3, 4), repeat=3):
                v = sum((q3(c) * x for c, x in zip(y, s.lat_vals(n))), Q3())
                key = (sum(map(abs, y)), y)
                if v and abs(v) < h and (best is None or key < best[0]): best = (key, y, abs(v))
            assert best is not None
            w = {"y": best[1], "value": str(best[2]), "nu": [str(x) for x in vadd(*[scal(c, g) for c, g in zip(best[1], s.G)])]}
            w["facet_neighbour"] = any(vadd(*[scal(c, g) for c, g in zip(best[1], s.G)]) in (f["t"], scal(-1, f["t"])) for f in s.F)
        return {"d": d, "h": h, "ok": ok, "witness": w}

    def resonus(s): return [(f["n"], f) for f in s.F]

    def vacuus(s):
        pl = {}
        for e in s.Ed:
            n = cross(s.U[e["j"]], e["c"])
            pl.setdefault(canon(n), []).append(e)
        return list(pl.items())


def central_regions(normals):
    """Regions of the central arrangement of planes with these normals (Zaslavsky: sum of |mu| over the flats)."""
    N = [canon(n) for n in normals]
    lines = {}
    for a, b in itertools.combinations(range(len(N)), 2):
        L = cross(N[a], N[b])
        if any(L): lines.setdefault(canon(L), set()).update({a, b})
    r = 1 + len(N) + sum(len(v) - 1 for v in lines.values())
    rank3 = any(det3(N[a], N[b], N[c]) for a, b, c in itertools.combinations(range(len(N)), 3))
    if rank3: r += 1 - len(N) + sum(len(v) - 1 for v in lines.values())
    return r, rank3


def toric(qs):
    """Regions per fundamental domain of the periodic arrangement {q.y in Z} on R^3/Z^3 (q primitive integer vectors),
    by Ehrenborg-Readdy-Slone: regions = sum over vertices p of |mu(p)|, with |mu(p)| = 1 - n_p + sum_L (m_L - 1) locally.
    Also returns the vertex set mod Z^3."""
    verts = set()
    for a, b, c in itertools.combinations(qs, 3):
        D = det3(a, b, c)
        if not D: continue
        D = abs(int(D.a))
        for k in itertools.product(range(D), repeat=3):
            y = solve3([tuple(q3(r[i]) for r in (a, b, c)) for i in range(3)], tuple(q3(x) for x in k))
            # solve3 takes columns; here the matrix rows are a, b, c
            verts.add(tuple(x.a % 1 for x in y))
    tot = 0
    for p in verts:
        thru = [q for q in qs if (sum(Fr(x) * y for x, y in zip(q, p))).denominator == 1]
        lines = {}
        for a, b in itertools.combinations(range(len(thru)), 2):
            L = cross(tuple(q3(x) for x in thru[a]), tuple(q3(x) for x in thru[b]))
            if any(L): lines.setdefault(canon(L), set()).update({a, b})
        tot += 1 - len(thru) + sum(len(v) - 1 for v in lines.values())
    return tot, verts


def web(z, normals):
    """Passing families as integer vectors q in lattice coordinates (x = G y): q = (n.G e_i)/d."""
    qs = []
    for n in normals:
        d = commensurable_gcd(z.lat_vals(n))
        q = tuple(x / d for x in z.lat_vals(n))
        assert all(c.rational() and c.a.denominator == 1 for c in q)
        q = tuple(int(c.a) for c in q)
        f = next(x for x in q if x); q = tuple(x if f > 0 else -x for x in q)
        qs.append(q)
    return qs


def report(z, out):
    row = {"name": z.name, "lam": [str(l) for l in z.lam], "facets": 2 * len(z.F), "edges": len(z.Ed), "vertices": z.nV,
           "covolume": str(z.covol)}
    for lab, fam in (("resonus", z.resonus()), ("vacuus", z.vacuus())):
        fams = []
        for n, info in fam:
            t = z.test(n)
            item = {"normal": [str(x) for x in n], "d": str(t["d"]), "h": str(t["h"]), "pass": t["ok"],
                    "k=2h/d": (str((2 * t["h"]) / t["d"]) if t["d"] else "dense")}
            if lab == "resonus": item["face"] = f"{info['size']}-gon"
            else: item["edges_on_plate"] = len(info); item["edge_zone"] = sorted({e["j"] for e in info})
            if t["witness"]: item["witness"] = t["witness"]
            fams.append((n, item))
        row[lab] = [i for _, i in fams]
        good = [n for n, i in fams if i["pass"]]
        row[lab + "_planes"] = len(fams); row[lab + "_pass"] = len(good)
        row[lab + "_web"] = len(good) == len(fams)
        if good:
            r, rk = central_regions(good)
            row[lab + "_pass_pieces_per_cell"] = r
            if rk:
                qs = web(z, good); reg, vs = toric(qs)
                row[lab + "_pass_regions_per_cell"] = reg; row[lab + "_pass_vertices_per_cell"] = len(vs)
                row[lab + "_pass_q"] = [list(q) for q in qs]
    # both together, if both pass
    if row["resonus_web"] and row["vacuus_web"]:
        alln = {}
        for n, _ in z.resonus() + z.vacuus(): alln[n] = n
        r, rk = central_regions(list(alln))
        qs = web(z, list(alln)); reg, vs = toric(qs)
        row["union_planes"] = len(alln); row["union_pieces_per_cell"] = r; row["union_regions_per_cell"] = reg
        row["union_vertices_per_cell"] = len(vs)
    out.append(row)
    return row


def standard_members():
    return [("cube", [1, 1, 1]), ("hexagonal prism", [1, 1, 1, 1]), ("hexagonal prism", [1, 1, 2, 1]),
            ("hexagonal prism", [1, 1, SQ3, 1]),
            ("rhombic dodecahedron", [1, 1, 1, 1]),
            ("elongated dodecahedron", [1, 1, 1, Fr(1, 2) * SQ3, 1]),   # equal edges
            ("elongated dodecahedron", [1, 1, 1, 1, 1]), ("elongated dodecahedron", [1, 1, 1, 2, 1]),
            ("truncated octahedron", [1, 1, 1, 1, 1, 1])]


if __name__ == "__main__":
    out = []
    mem = standard_members()
    for k, (nm, lam) in enumerate(mem):
        z = Zono(nm, lam); r = report(z, out)
        print(f"PROGRESS {(k + 1) / len(mem):.2f} {nm} lam={r['lam']}: F{r['facets']} E{r['edges']} V{r['vertices']} | "
              f"Resonus {r['resonus_pass']}/{r['resonus_planes']} web={r['resonus_web']} | "
              f"Vacuus {r['vacuus_pass']}/{r['vacuus_planes']} web={r['vacuus_web']}", flush=True)
    json.dump(out, open(sys.argv[1] if len(sys.argv) > 1 else "webs-standard.json", "w"), indent=1, default=str)
