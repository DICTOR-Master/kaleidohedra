# Builds src/app/dodeca-data.js for the DICTO Dodeca world (DICTO 2026-10-13): the DICTO-Star (#14) and DICTO's DICTO-ICOSA star
# (the DICTO-Star with a pyramid, all edges 1, on each of its 152 free faces; studies/2026-10-12-dicto-icosa-star), and its hollow:
# the centre removed and a core icosahedron of edge 1 held by 20 Cleo-Icos on its faces and 12 flat pentagonal pyramids on its corners (DICTO 2026-10-15).
# Input: the DICTO-Star from krp-core idStar() as JSON ({centre, dodecahedra, caps}). Usage: python3 scripts/build-dodeca-data.py star.json
import sys, json, itertools, numpy as np
from scipy.spatial import ConvexHull
S = json.load(open(sys.argv[1]))
P = [('centre', np.array(S['centre']))] + [('dodeca', np.array(V)) for V in S['dodecahedra']] + [('j63', np.array(V)) for V in S['caps']]
def faces(W):
    H = ConvexHull(W); F = []
    for e in H.equations:
        idx = [i for i in range(len(W)) if abs(W[i] @ e[:3] + e[3]) < 1e-7]
        if not any(set(idx) == set(f) for f, _ in F): F.append((idx, e))
    return F
def polys(W):
    out = []
    for idx, e in faces(W):
        Q = W[idx]; c = Q.mean(0); a = Q[0] - c; a /= np.linalg.norm(a); b = np.cross(e[:3], a)
        out.append([idx[i] for i in np.argsort(np.arctan2((Q - c) @ b, (Q - c) @ a))])
    return out
def piece(role, W): return [role, np.round(W, 6).tolist(), polys(W)]
def pyramid(F, n, inward=False):
    c = F.mean(0); h = np.sqrt(max(1 - np.linalg.norm(F[0] - c) ** 2, 0)); return np.vstack([F, c + (-n if inward else n) * h])
def free_faces(skip_centre=False):
    out = []
    for k, (nm, W) in enumerate(P):
        if skip_centre and nm == 'centre': continue
        for idx, e in faces(W):
            c = W[idx].mean(0); cov = False
            for j, (nm2, Q) in enumerate(P):
                if j == k or (skip_centre and nm2 == 'centre'): continue
                on = np.abs(Q @ e[:3] + e[3]) < 1e-7
                if on.sum() >= 3:
                    q = Q[on]; Hq = ConvexHull(np.vstack([q, q.mean(0) + e[:3]]))
                    if np.all(Hq.equations[:, :3] @ c + Hq.equations[:, 3] <= 1e-7): cov = True; break
            if not cov: out.append((nm, W[idx], e[:3]))
    return out
star = [piece(nm, W) for nm, W in P]
outer = [(nm, F, n) for nm, F, n in free_faces()]
pyrs = [piece('pyr5' if len(F) == 5 else 'tet', pyramid(F, n)) for nm, F, n in outer]
# hollow (DICTO 2026-10-15: "holding by Cleo-Icos alone"): the centre removed; a core icosahedron of edge 1 on the five-fold axes,
# held by 20 Cleo-Icos (an edge-1 icosahedron's face pyramids) standing on the centre's triangles, their points on the core's face
# centres, and 12 flat pentagonal pyramids (height 0.425325, side edges = the Cleo-Ico's) on its pentagons, points on the core's corners (exact: the triangles lie at phi^2/sqrt3, a Cleo-Ico is phi^2/(2 sqrt3) tall; studies/2026-10-15-icosa-star-hollow)
ID = P[0][1]; R_ico = np.sqrt(10 + 2 * np.sqrt(5)) / 4; r_ico = (1 + np.sqrt(5)) ** 2 / 4 / (2 * np.sqrt(3)); inner = []; tips = []
for idx, e in faces(ID):
    F = ID[idx]
    if len(F) == 5: tips.append(e[:3] * R_ico); inner.append(piece('fpyr5', np.vstack([F, e[:3] * R_ico])))  # flat pentagonal pyramid, point on a core corner
    else: inner.append(piece('icleo', np.vstack([F, F.mean(0) - e[:3] * r_ico])))
core = piece('core', np.array(tips))
D = {'star': {'views': {'star': star}},
     'icosaStar': {'views': {'pyramids': star + pyrs, 'hollow': star[1:] + pyrs + inner + [core]}}}
open('src/app/dodeca-data.js', 'w').write('// Generated by scripts/build-dodeca-data.py (DICTO-Star #14, DICTO-ICOSA star). Do not edit.\nexport default ' + json.dumps(D, separators=(',', ':')) + ';\n')
print({k: {v: len(L) for v, L in d['views'].items()} for k, d in D.items()}, 'core edge', round(min(np.linalg.norm(a - b) for a, b in itertools.combinations(tips, 2)), 6), 'holders', len(inner))
