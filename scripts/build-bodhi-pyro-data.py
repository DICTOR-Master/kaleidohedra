#!/usr/bin/env python3
# Golden Bodhi Pyrochlore Networks (DICTO 2026-10-15): data for src/app/world-bodhi-pyro.js, from the study
# studies/2026-10-16-ocd-pyrochlore (branch research). All positions come from exact ℚ(√5) values and are rounded for drawing.
#   python3 scripts/build-bodhi-pyro-data.py <folder with chorus-fork.json, gaps.json, chorus-exact-r10.json, fig-window.json>
# Writes src/app/bodhi-pyro-data.js:
#   ocd      the DICTO Ogdoecontahedron (102 corners, 80 faces: 20 regular hexagons, 60 kites);
#   cubes    the five inscribed cubes of its hexagon bonds, in chorus (voice) order, each as a basis M (columns) with
#            bonds = M·s for s in {±1}³, and for each face the bond s it carries (or null);
#   gaps     the 72 gap pieces of one copy's body-centred cubic cell (48 + 12 kite pieces, 12 hexagon pieces), triangulated;
#   chorus   the exact radius-10 five-fold chorus: [x, y, z, wedge (−1 on the axis), removed 0/1], the five-fold axis, the
#            canonical chain heights in the build (window [0, W)), t_c and W.
import json, sys, pathlib, itertools
import numpy as np
from scipy.spatial import ConvexHull

src = pathlib.Path(sys.argv[1])
F = json.load(open(src / 'chorus-fork.json')); G = json.load(open(src / 'gaps.json'))
C = json.load(open(src / 'chorus-exact-r10.json')); W = json.load(open(src / 'fig-window.json'))
V = np.array(F['ocd']); faces = F['faces']
r6 = lambda a: [round(float(x), 6) for x in a]

# hexagon bonds: a copy joined on hexagon (n, d) sits at 2 d n / |n|^2
bond, bond_face = [], []
for fi, f in enumerate(faces):
    if len(f) != 6: continue
    P = V[f]; n = np.cross(P[1] - P[0], P[2] - P[0]); n /= np.linalg.norm(n); d = n @ P.mean(axis=0)
    if d < 0: n, d = -n, -d
    bond.append(2 * d * n); bond_face.append(fi)
B = np.array(bond); U = B / np.linalg.norm(B, axis=1)[:, None]
cubes = [list(s) for s in itertools.combinations(range(20), 8)
         if np.all(np.isin(np.round((U[list(s)] @ U[list(s)].T)[~np.eye(8, dtype=bool)], 6), np.round([1 / 3, -1 / 3, -1.0], 6)))]
assert len(cubes) == 5
# chorus sites and their wedges (voice k fills wedge k)
th0 = C['th0']
a5, e1, e2 = np.array(C['a5']), np.array(C['e1']), np.array(C['e2'])
ALL = np.array(C['all']); SIL = np.array(C['silenced'])
def wedge(p):
    if np.linalg.norm(p - (p @ a5) * a5) < 1e-9: return -1
    return int(((np.arctan2(p @ e2, p @ e1) - th0) % (2 * np.pi)) // (2 * np.pi / 5)) % 5
wk = np.array([wedge(p) for p in ALL])
removed = np.zeros(len(ALL), int)
for s in SIL: removed[int(np.argmin(np.linalg.norm(ALL - s, axis=1)))] = 1
assert removed.sum() == len(SIL)
def basis(cube):
    b0 = B[cube[0]]; adj = [i for i in cube[1:] if abs(U[i] @ U[cube[0]] - 1 / 3) < 1e-6]
    assert len(adj) == 3
    return np.array([(b0 - B[i]) / 2 for i in adj]).T          # columns: the cube's three half-edge axes
def integral(M, p):
    c = np.linalg.solve(M, p); return np.allclose(c, np.round(c), atol=1e-6) and len(set(np.round(c).astype(int) % 2)) == 1
order = []
for k in range(5):                                            # cube whose lattice holds the wedge-k sites
    pts = ALL[wk == k][:12]
    cand = [j for j in range(5) if all(integral(basis(cubes[j]), p) for p in pts)]
    assert len(cand) == 1, (k, cand); order.append(cand[0])
cubes = [cubes[j] for j in order]
out_cubes = []
for cube in cubes:
    M = basis(cube); Mi = np.linalg.inv(M)
    face_bond = [None] * len(faces)
    for i in cube:
        s = np.round(Mi @ B[i]).astype(int); assert np.allclose(Mi @ B[i], s, atol=1e-6) and set(np.abs(s)) == {1}
        face_bond[bond_face[i]] = s.tolist()
    out_cubes.append({'M': [r6(M[:, j]) for j in range(3)], 'faceBond': face_bond})
# gap pieces, triangulated, with their kind (48 small kite wedges, 12 kite pieces, 12 hexagon pieces)
gp = []
for P in G['pieces']:
    P = np.array(P); h = ConvexHull(P); kind = {6: 'kiteWedge', 11: 'kite', 13: 'hex'}[len(P)]
    tris = []
    for t in h.simplices:                                      # orient outward
        a, b, c = P[t]; n = np.cross(b - a, c - a)
        tris.append(t.tolist() if n @ (a - P.mean(axis=0)) > 0 else [t[0], t[2], t[1]])
    gp.append({'kind': kind, 'v': [r6(p) for p in P], 't': [[int(x) for x in t] for t in tris]})
from collections import Counter
assert Counter(g['kind'] for g in gp) == {'kiteWedge': 48, 'kite': 12, 'hex': 12}
# canonical chain heights inside the build (|h| < 10): plane lattice points with 0 <= t < W
Wl, tc = W['L'], W['tc']
chain = sorted(round(h, 4) for h, t in W['points'] if 0 <= t < Wl and abs(h) < 10)
data = {'ocd': {'v': [r6(p) for p in V], 'f': faces}, 'cubes': out_cubes, 'gaps': gp,
        'chorus': {'axis': r6(a5), 'sites': [[*r6(p)[:3], int(w), int(r)] for p, w, r in zip(ALL, wk, removed)],
                   'chain': chain, 'tc': round(tc, 6), 'W': round(Wl, 6)}}
js = ('// Generated by scripts/build-bodhi-pyro-data.py from studies/2026-10-16-ocd-pyrochlore (branch research); exact values rounded.\n'
      'export default ' + json.dumps(data, separators=(',', ':')) + ';\n')
pathlib.Path('src/app/bodhi-pyro-data.js').write_text(js)
print('written', len(js), 'bytes;', len(ALL), 'chorus sites,', int(removed.sum()), 'removed;', len(chain), 'chain heights; cube order', order)
