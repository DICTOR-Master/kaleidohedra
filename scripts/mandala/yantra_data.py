"""The DICTO Yantra's numbers for the Mandala World (src/app/mandala-data.js), copied digit for digit from the study's exact data:
k-research studies/2026-11-08-sri-yantra/figures/golden_family.json, GF1 (the Cleo-Antonius yantra, the DICTO Yantra). For each triangle
1..9: b (base depth), w (base half-width) and apex (apex depth), in a diameter-1 frame with depth measured down from the top of the
circle. The strings are written out unchanged as JavaScript number literals (the nearest double to each).
Run: python3 scripts/mandala/yantra_data.py [path/to/golden_family.json]"""
import json, os, re, sys
src = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser('~/k-research/studies/2026-11-08-sri-yantra/figures/golden_family.json')
G = json.load(open(src))['GF1']
num = re.compile(r'^-?\d+(\.\d+)?$')
def row(field):
    vals = [G[field][str(i)]['a'] for i in range(1, 10)]
    assert all(num.match(v) for v in vals), field
    return '[' + ', '.join(vals) + ']'
out = os.path.join(os.path.dirname(__file__), '..', '..', 'src', 'app', 'mandala-data.js')
with open(out, 'w') as f:
    f.write('// The DICTO Yantra (GF1, the Cleo-Antonius yantra), triangles 1..9 in order: b = base depth, w = base half-width, apex = apex\n')
    f.write('// depth, in a diameter-1 frame, depth measured down from the top of the circle. Generated by scripts/mandala/yantra_data.py from\n')
    f.write('// k-research studies/2026-11-08-sri-yantra/figures/golden_family.json (GF1); the study\'s strings copied unchanged. Do not edit.\n')
    f.write(f"export const YANTRA_LABEL = {json.dumps(G['label'])};\n")
    for k in ('b', 'w', 'apex'):
        f.write(f'export const YANTRA_{k.upper()} = {row(k)};\n')
print('wrote', os.path.normpath(out))
