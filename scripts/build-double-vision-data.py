# Builds src/app/double-vision-data.js for the Double Vision world (DICTO 2026-10-16; paper "Double Vision – Both Cycles in One Space",
# DICTO DOI 10.5281/zenodo.23407106): the Spheres of Dharma and their polar reversal in one space, in the paper's two settings (ends
# shared, ρ² = φ²/4; middle shared, ρ² = 3φ²/4). Per setting: the stations of both cycles (two turns of the original, the reversed
# turns that meet them, as in the paper's Figure 2), and one turn of the interlock (536 / 502 exact convex pieces), each piece with its
# original layer, its reversed layer and its kind (DICTO Interlock set 1 (Dharma-Ends) I1·n, set 2 (Dharma-Middle) I2·n).
# Inputs: studies/2026-10-16-interlock/data/ (p4-render-*, p4-xray-*, interlock-*). Usage: python3 scripts/build-double-vision-data.py
import json, numpy as np
from scipy.spatial import ConvexHull
D = 'studies/2026-10-16-interlock/data/'
r6 = lambda V: [[round(x, 6) for x in v] for v in V]
# the paper's Tables 1 and 2: code, count, original layer, reversed layer (kinds in the order of the render data, numbered from 1: volume, largest first)
KINDS = {
    'ends': [('12f', 12), ('TBP', 60), ('7f', 60), ('7f', 60), ('12f', 12), ('7f', 60), ('QPy', 60), ('PPy', 60), ('PPy', 12), ('Tet', 60), ('QPy', 60), ('Tet', 20)],
    'middle': [('7f', 30), ('11f', 12), ('7f', 60), ('HPy', 20), ('7f', 60), ('6f', 60), ('Tet', 20), ('QPy', 60), ('Tet', 60), ('Tet', 60), ('Tet', 60)],
}
out = {'paperDoi': '10.5281/zenodo.23407106', 'settings': {}}
for s, setNo in (('ends', 1), ('middle', 2)):
    R = json.load(open(D + f'p4-render-{s}.json')); X = json.load(open(D + f'p4-xray-{s}.json')); L = json.load(open(D + f'interlock-{s}.json'))
    # reversed layer of each render piece: matched by centroid with interlock-*.json (unique match, same original layer checked)
    def cen(V):  # volume centroid (the two files list extra points on edges differently, so corner means differ)
        W = np.array(V); h = ConvexHull(W); o = W.mean(0); T = W[h.simplices]
        vol = np.abs(np.einsum('ij,ij->i', T[:, 0] - o, np.cross(T[:, 1] - o, T[:, 2] - o))) / 6
        return ((T.sum(1) + o) / 4 * vol[:, None]).sum(0) / vol.sum()
    LC = np.array([cen(p['v']) for p in L['pieces']])
    pieces = []
    for p in R['pieces']:
        d = np.linalg.norm(LC - cen(p['v']), axis=1); j = int(np.argmin(d))
        assert d[j] < 1e-4 and np.partition(d, 1)[1] > 1e-3 and L['pieces'][j]['o'][0] == p['o'], (s, d[j])
        pieces.append({'v': r6(p['v']), 'f': p['f'], 'o': p['o'], 'r': L['pieces'][j]['f'][1], 't': L['pieces'][j]['f'][0], 'k': p['k'] - 1})
    counts = [sum(1 for p in pieces if p['k'] == k) for k in range(len(KINDS[s]))]
    assert counts == [n for _, n in KINDS[s]], (s, counts)
    assert len(pieces) == {'ends': 536, 'middle': 502}[s]
    kinds = [{'name': f'I{setNo}·{k + 1}', 'code': c, 'n': n} for k, (c, n) in enumerate(KINDS[s])]
    stations = [{'name': t['name'], 'side': t['side'], 'turn': t['turn'], 'shared': t['shared'], 'v': r6(t['v']), 'f': t['f']} for t in X['stations']]
    out['settings'][s] = {'rho': X['rho'], 'pieces': pieces, 'kinds': kinds, 'stations': stations,
                          'origLayers': L['orig_layers'], 'revLayers': L['flip_layers'], 'view': R['views']['B']}
    print(s, len(pieces), 'pieces', len(kinds), 'kinds', len(stations), 'stations', 'rho', X['rho'])
js = ('// Generated by scripts/build-double-vision-data.py from studies/2026-10-16-interlock (DICTO 2026-10-16). Do not edit by hand.\n'
      'export default ' + json.dumps(out, separators=(',', ':'), ensure_ascii=False) + ';\n')
open('src/app/double-vision-data.js', 'w').write(js); print(len(js), 'bytes')
