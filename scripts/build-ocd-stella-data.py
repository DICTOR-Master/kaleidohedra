# Builds src/app/ocd-stella-data.js for the OCD Stella Crystals world (DICTO 2026-10-16): the DICTO OCD Stella (the stella cut of the
# Ogdoecontahedron's companion solid) on one network of the OCD's bcc packing, and on the other network a partner: icosahedra (the OCD's
# 20 hexagon planes; fill 1523/32 − 669√5/32 ≈ 84.60%, exact), regular octahedra (the cell's 8 joint planes; ≈ 96.33%, float; every OCD Stella
# notched by 6 octahedron tips), or OCD Stellas again (alone, 151/2 − 267√5/8 ≈ 87.12%, exact). Sites carry their growth layer (joint steps
# from the central OCD Stella). Gap pieces: the 4 kinds of the exact pass (crystal_gap_exact.py), drawn from the float pieces.
# Inputs (research branch): studies/2026-10-16-ocd-pyrochlore/data/{network,crystal-render,octa-pyro-render,crystal-gap-pieces}.json.
# Usage, from the research checkout: python3 <this> <out.js>   (needs manifold3d for the notched OCD Stella)
import sys, json, itertools, numpy as np, manifold3d as m3
from scipy.spatial import ConvexHull
D = 'studies/2026-10-16-ocd-pyrochlore/data/'
N = json.load(open(D + 'network.json')); T = np.array(N['T']); Lb = np.array(N['Lb']).T
R = json.load(open(D + 'crystal-render.json')); OP = json.load(open(D + 'octa-pyro-render.json')); G = json.load(open(D + 'crystal-gap-pieces.json'))
r5 = lambda V: [[round(float(x), 5) for x in v] for v in V]
def solid(S): return {'v': r5(S['v']), 'f': S['f']}
def hull(P): return m3.Manifold.hull_points(np.asarray(P, dtype=np.float32))
# the notched OCD Stella: the OCD Stella minus the 6 octahedron tips that nest in it
St = hull(R['stella']['v'])
for t in OP['tips']: St = St - hull(t['v'])
M = St.to_mesh(); V = np.array(M.vert_properties)[:, :3]; F = np.array(M.tri_verts)
nrm = np.cross(V[F[:, 1]] - V[F[:, 0]], V[F[:, 2]] - V[F[:, 0]]); nrm /= np.linalg.norm(nrm, axis=1)[:, None]
adj = {}
for i, f in enumerate(F):
    for a, b in ((f[0], f[1]), (f[1], f[2]), (f[2], f[0])): adj.setdefault((min(a, b), max(a, b)), []).append(i)
E = [list(map(int, e)) for e, ts in adj.items() if len(ts) != 2 or abs(nrm[ts[0]] @ nrm[ts[1]]) < 1 - 1e-6 or nrm[ts[0]] @ nrm[ts[1]] < 0]
vS = ConvexHull(np.array(R['stella']['v'])).volume
notched = {'v': r5(V), 'f': F.tolist(), 'e': E}
print('notched OCD Stella: volume', round(St.volume(), 6), 'of', round(vS, 6), f'({1 - St.volume() / vS:.2%} notched); feature edges', len(E))
# sites: network 1 (k = 0, 1) and network 2 (k = 2, 3); growth layers by joint steps from the central network-1 site
pts = [(Lb @ np.array(m, float) + k * T[0], 1 if k < 2 else 2) for m in itertools.product(range(-6, 7), repeat=3) for k in range(4)]
pts = [(p, n) for p, n in pts if np.linalg.norm(p) < 7.0]
J = np.linalg.norm(T[0]); P = np.array([p for p, _ in pts]); layer = {0: 0}; front = [0]; c0 = int(np.argmin(np.linalg.norm(P, axis=1)))
layer = {c0: 0}; front = [c0]; MAXL = 4
while front:
    nxt = []
    for i in front:
        if layer[i] >= MAXL: continue
        for j in np.where(np.abs(np.linalg.norm(P - P[i], axis=1) - J) < 1e-6)[0]:
            if int(j) not in layer: layer[int(j)] = layer[i] + 1; nxt.append(int(j))
    front = nxt
sites = [[*[round(float(x), 5) for x in pts[i][0] - P[c0]], pts[i][1], L] for i, L in sorted(layer.items(), key=lambda kv: kv[1])]
print('sites', len(sites), 'per layer', np.bincount([s[4] for s in sites]).tolist())
# gap pieces, kind: 0 icosahedron wedge, 1 OCD Stella cap (companion triangle), 2 slab (golden hexagon), 3 thin wedge (golden quadrilateral)
KIND = {('ico', 3): 0, ('stella', 3): 1, ('stella', 6): 2, ('stella', 4): 3}
gap = {'stella': [], 'ico': []}
for p in G['pieces']: gap[p['solid']].append({'k': KIND[(p['solid'], p['face'])], 'v': r5(p['v']), 'f': p['f']})
out = {'solids': {'stella': solid(R['stella']), 'notched': notched, 'ico': solid(R['ico']), 'octa': solid(OP['octa'])}, 'sites': sites, 'gap': gap,
       'axis': [round(float(x), 6) for x in R['axis']], 'joint': round(float(J), 6)}
js = ('// Generated by scripts/build-ocd-stella-data.py (DICTO OCD Stella Crystals world). Do not edit by hand.\n'
      'export default ' + json.dumps(out, separators=(',', ':')) + ';\n')
open(sys.argv[1], 'w').write(js); print('wrote', sys.argv[1], len(js), 'bytes')
