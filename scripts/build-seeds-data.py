# Builds src/app/seeds-data.js for the three DICTO seed worlds (DICTO 2026-10-13): Chain of Karma (#22), Spheres of Dharma (#23),
# Bodhi Seed (#24). Inputs are the checked study data; each piece becomes [role, vertices, faces] with faces as outward polygons.
# Usage: python3 scripts/build-seeds-data.py <3D-page data.json> <twin network json (exact)> <bodhi-data.json>
import sys, json, numpy as np
from scipy.spatial import ConvexHull
page, tw, bod = (json.load(open(p)) for p in sys.argv[1:4])
def polys(V):
    # Coordinates are rounded to 5 places, so a flat face's corners sit up to ~3e-5 off its plane: gather them with a looser
    # tolerance and keep each face once, whole (no leftover triangles or split lines across a flat face; DICTO 2026-10-13).
    V = np.array(V, float); H = ConvexHull(V); out = []
    cands = [([i for i in range(len(V)) if abs(V[i] @ e[:3] + e[3]) < 2e-4], e) for e in H.equations]
    for idx, e in sorted(cands, key=lambda c: -len(c[0])):
        if any(set(idx) <= set(f) for f in out): continue
        P = V[idx]; c = P.mean(0); a = P[0] - c; a /= np.linalg.norm(a); b = np.cross(e[:3], a)
        out.append([idx[i] for i in np.argsort(np.arctan2((P - c) @ b, (P - c) @ a))])
    return out
def piece(role, V):
    V = [[round(x, 5) for x in v] for v in V]; return [role, V, polys(V)]
def plist(L): return [piece(r, V) for r, V, *_ in L]
def bpoly(p): return p['v']
D = {
 'karma': {'views': {'lotus': plist(page['s1']), 'step2': plist(page['s2']), 'dodeca': plist(page['d0'])}},
 'dharma': {'views': {'cycle': plist(tw['twNi'] and [(r, V) for r, V, *_ in tw['twNi']] + [(r, V) for r, V, *_ in tw['twNo']]),
                      'inner': plist([(r, V) for r, V, *_ in tw['twNi']]), 'outer': plist([(r, V) for r, V, *_ in tw['twNo']]),
                      'hinge': plist([(r, V) for r, V, *_ in tw['twNi']] + [(r, V) for r, V, *_ in tw['twLo']])}},
 'bodhi': {'views': {'seed': [piece('outer', bpoly(bod['outer']))] + [piece('copy', bpoly(c)) for c in bod['copies']] + [piece('centre', bpoly(bod['centre']))],
                     'kitB': [piece('copy', bpoly(c)) for c in bod['copies']] + [piece('centre', bpoly(bod['centre']))] + [piece(k, bpoly(p)) for k, p in bod['B']],
                     'kitA': [piece('copy', bpoly(c)) for c in bod['copies']] + [piece('centre', bpoly(bod['centre']))] + [piece(k, bpoly(p)) for k, p in bod['A']],
                     'hollow': [piece('centre', bpoly(bod['centre']))] + [piece(k, bpoly(p)) for k, p in bod['B'] if k == 'B1']}},
}
open('src/app/seeds-data.js', 'w').write('// Generated by scripts/build-seeds-data.py from the checked study data (DICTO #22-#24). Do not edit.\nexport default ' + json.dumps(D, separators=(',', ':')) + ';\n')
print({w: {v: len(L) for v, L in d['views'].items()} for w, d in D.items()})
