# Builds krp-core's src/polyhedra/star-cores-shapes.js: the Star Cores shapes (the 52 convex D-numbered shapes of research studies
# 2026-10-30-star-cores and 2026-11-01-star-cores-book) in Polyhedraverse's catalogue (DICTO 2026-11-02: every shape in PV first).
# The ones not yet in PV are added from DICTO Solids v7, centred on their corners' mean and shown at circumradius 1.1 (proportions
# intact); the ones PV already has keep their own id. STAR_CORES_LIST: all 52, newest first, with the PV id of each.
# Usage: pv_shapes.py <DICTO Solids v7 solids dir> <star-cores-list.json> <out .js>
import json, sys, numpy as np
DS, LIST, OUT = sys.argv[1:4]
DISPLAY_R = 1.1
IN_PV = {'D106': 'DICTO_CUBE_PEARL', 'D107': 'DICTO_GOLDEN_CLASP', 'D108': 'DICTO_HAMLET', 'D109': 'DICTO_OPHELIA', 'D71': 'DICTO_SAMSON',
         'D7': 'DICTO_DODECA13_NEEDLE', 'D6': 'DICTO_DODECA13_WEDGE', 'D3': 'DICTO_SKEWED_ED_18', 'D2': 'DICTO_SKEWED_ED_16', 'D1': 'DICTO_SKEWED_RD'}
R = lambda x: round(float(x), 12) + 0.0
raw, lst = {}, []
for D, fn in json.load(open(LIST)):
    d = json.load(open(f'{DS}/{fn}'))
    key = fn[len('dicto-'):-len('.json')]
    pid = IN_PV.get(D) or 'DICTO_SC_' + key.upper().replace('-', '_')
    lst.append(dict(D=D, key=key, name=d['name'], symmetry=d.get('symmetry', {}).get('schoenflies'), id=pid))
    if D in IN_PV: continue
    V = np.array([[float(x) for x in v['decimal']] for v in d['vertices']]); V = V - V.mean(0); V *= DISPLAY_R / np.linalg.norm(V, axis=1).max()
    raw[pid] = dict(name=d['name'], vertices=[[R(x) for x in v] for v in V], faces=d['faces'])
lst.sort(key=lambda r: -int(r['D'][1:]))
ids = [r['id'] for r in lst if r['id'] in raw]
head = ('// Generated by k-mix scripts/star-cores/pv_shapes.py from DICTO Solids v7 (DICTO 2026-11-02). Do not edit.\n'
        '// The Star Cores shapes in Polyhedraverse: the 52 convex D-numbered shapes given the star core treatment (papers #79-#81, the Star\n'
        '// Cores book). Those PV did not have yet, centred and shown at circumradius 1.1 (proportions intact); STAR_CORES_LIST, all 52\n'
        '// newest first with their PV ids (the Star Cores world takes them from here). Credit: DICTO (idea, names). CC BY-SA 4.0.\n'
        "import { specOf } from './stellaJewel.js';\n")
js = (head + 'const RAW = ' + json.dumps(raw, separators=(',', ':')) + ';\n'
      'export const STAR_CORES_SHAPE_ADDITIONS = Object.fromEntries(Object.entries(RAW).map(([id, p]) => [id, specOf(id, p.name, p.vertices, p.faces, false, 1)]));\n'
      'export const STAR_CORES_SHAPE_IDS = ' + json.dumps(ids) + ';\n'
      'export const STAR_CORES_LIST = ' + json.dumps(lst, ensure_ascii=False, separators=(',', ':')) + ';\n')
open(OUT, 'w').write(js)
print(len(raw), 'added;', len(lst), 'listed')
