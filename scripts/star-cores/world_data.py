# Builds src/app/star-cores-data.js: the 52 convex Star Cores shapes (D-numbered, centre inside every face) of DICTO Solids v7,
# the list of research studies 2026-10-30-star-cores (star-cores.json) + 2026-11-01-star-cores-book (star-cores-new4.json).
import json, sys
DS, LIST, OUT = sys.argv[1:4]   # usage: world_data.py <DICTO Solids v7 solids dir> <list.json: [[D, file]]> src/app/star-cores-data.js
rows = []
for D, fn in json.load(open(LIST)):
    d = json.load(open(f'{DS}/{fn}'))
    pv = {'D106': 'DICTO_CUBE_PEARL', 'D107': 'DICTO_GOLDEN_CLASP', 'D108': 'DICTO_HAMLET', 'D109': 'DICTO_OPHELIA'}.get(D)
    if pv:   # in Polyhedraverse's catalogue already (krp-core star-cores-solids.js): the world takes them from there
        rows.append(dict(D=D, key=fn[len('dicto-'):-len('.json')], name=d['name'], symmetry=d.get('symmetry', {}).get('schoenflies'), pv=pv)); continue
    V = [[round(float(x), 10) + 0.0 for x in v['decimal']] for v in d['vertices']]
    rows.append(dict(D=D, key=fn[len('dicto-'):-len('.json')], name=d['name'], symmetry=d.get('symmetry', {}).get('schoenflies'), vertices=V, faces=d['faces']))
rows.sort(key=lambda r: -int(r['D'][1:]))          # DICTO's newest work first
head = ('// Generated by k-mix scripts/star-cores/world_data.py from DICTO Solids v7 (list: research studies 2026-10-30-star-cores, 2026-11-01-star-cores-book).\n'
        '// Do not edit. The 52 convex Star Cores shapes with a D-number (centre inside every face), newest first: { D, key, name, symmetry,\n'
        '// vertices, faces, or pv: the Polyhedraverse id of a shape already in its catalogue } at the dataset\'s own scale. Credit: DICTO (idea, names); exact computation with Claude (Anthropic). CC BY-SA 4.0.\n')
open(OUT, 'w').write(head + 'export const STAR_CORES_SHAPES = ' + json.dumps(rows, separators=(',', ':')) + ';\n')
print(len(rows), [r['key'] for r in rows])
