# Builds src/app/vajrayana-data.js for the Vajrayana world (DICTO 2026-10-17; paper "Vajrayana", DICTO DOI 10.5281/zenodo.23429911):
# the twelve-station golden cycle I ⊂ Cleo star ⊂ D′ ⊂ ID ⊂ O ⊂ rTI ⊂ TI ⊂ H ⊂ jtI ⊂ RT ⊂ M ⊂ I·φ³ (one turn, outer I·φ³ = the next
# turn's I), the Cleo star's 20 spikes, and the two closing layers as pieces: RT → M (30, one kind) and M → I·φ³ (60, one kind).
# Inputs (copied from the research branch, studies/2026-10-16-progenitors/data): full-cycle.json (stations, the 60-piece layer),
# gap-pieces.json (the 30-piece layer), cleo-build.json (I, the Cleo-Icos, D′). All float corners of exact stations (the paper's checks).
# Usage: python3 scripts/build-vajrayana-data.py
import json, numpy as np
from scipy.spatial import ConvexHull
D = 'studies/2026-10-16-progenitors/data/'
F = json.load(open(D + 'full-cycle.json')); C = json.load(open(D + 'cleo-build.json')); G = json.load(open(D + 'gap-pieces.json'))
r6 = lambda V: [[round(float(x), 6) for x in v] for v in V]
def faces(V):
    V = np.array(V); h = ConvexHull(V); out, seen = [], []
    for e in h.equations:
        if any(np.allclose(e, q, atol=1e-7) for q in seen): continue
        seen.append(e); idx = [i for i in range(len(V)) if abs(V[i] @ e[:3] + e[3]) < 1e-6]
        c = V[idx].mean(0); u = V[idx[0]] - c; w = np.cross(e[:3], u)
        idx.sort(key=lambda i: np.arctan2((V[i] - c) @ w, (V[i] - c) @ u)); out.append(idx)
    return out
nine = {s['name']: s for s in C['nine']}
def same(a, b): a, b = np.array(a), np.array(b); return len(a) == len(b) and all(np.min(np.linalg.norm(b - x, axis=1)) < 1e-5 for x in a)
assert same(nine['RT']['v'], F['st']['RT']['v']) and same(nine['ID']['v'], F['st']['ID']['v']), 'frames differ'
shell = lambda V, f=None: {'v': r6(V), 'f': f if f is not None else faces(V)}
st = [('I', shell(nine['I']['v'])), ('star', None), ('Dp', shell(C['Dp']['v'] if isinstance(C['Dp'], dict) else C['Dp'])),
      ('ID', shell(F['st']['ID']['v'], F['st']['ID']['f'])), ('O', shell(F['st']['O']['v'], F['st']['O']['f'])), ('rTI', shell(F['st']['rTI']['v'], F['st']['rTI']['f'])),
      ('TI', shell(F['st']['TI']['v'], F['st']['TI']['f'])), ('H', shell(F['st']['H']['v'], F['st']['H']['f'])), ('hull', shell(F['st']['hull']['v'], F['st']['hull']['f'])),
      ('RT', shell(F['st']['RT']['v'], F['st']['RT']['f'])), ('M', shell(F['st']['G']['v'], F['st']['G']['f'])), ('Ip3', shell(F['st']['Ip3']['v'], F['st']['Ip3']['f']))]
spikes = [shell(p['v'] if isinstance(p, dict) else p) for p in C['spikes']]
piece = lambda P: shell(P)
out = {'paperDoi': '10.5281/zenodo.23429911', 'stations': [{'key': k, **(s or {})} for k, s in st], 'spikes': spikes,
       'rtM': [piece(p) for p in G['RT -> G']], 'mI': [piece(p) for p in G['G -> icosahedron']], 'view': F['view']}
# checks: the outer station is the inner one times φ³ (the cycle repeats), and the pieces count as the paper says
phi = (1 + 5 ** .5) / 2
rI = np.linalg.norm(np.array(out['stations'][0]['v']), axis=1).max(); rO = np.linalg.norm(np.array(out['stations'][-1]['v']), axis=1).max()
assert abs(rO / rI - phi ** 3) < 1e-5, (rI, rO); assert len(out['rtM']) == 30 and len(out['mI']) == 60 and len(spikes) == 20
print('stations', [s['key'] for s in out['stations']], 'spikes', len(spikes), 'pieces', len(out['rtM']), len(out['mI']), 'ratio', rO / rI)
js = '// Generated by scripts/build-vajrayana-data.py (DICTO 2026-10-17). Do not edit by hand.\nexport default ' + json.dumps(out, separators=(',', ':')) + ';\n'
open('src/app/vajrayana-data.js', 'w').write(js); print(len(js), 'bytes')
