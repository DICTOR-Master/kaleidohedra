# Builds src/app/hecatogdo-data.js for Vajrayana's second view (DICTO 2026-10-18; paper "The DICTO Hecatogdoecontahedron",
# DICTO DOI 10.5281/zenodo.23430868): the DICTO Hecatodihedron H and its polar in the truncated icosahedron's midsphere, the DICTO
# Ogdoecontahedron O, interlocked; their common core (the rectified truncated icosahedron) and hull (the joined truncated icosahedron),
# each face tagged by type for the paper's colours. Input (copied from the research branch): studies/2026-10-16-progenitors/data/oh-render.json.
# Usage: python3 scripts/build-hecatogdo-data.py
import json, numpy as np
d = json.load(open('studies/2026-10-16-progenitors/data/oh-render.json'))
# checks: the paper's counts (H 102 faces / 80 corners, O 80 / 102, core 92 / 90, hull 90 / 92) and one common outer radius (H's corners on the hull)
for k, nf, nv in (('H', 102, 80), ('O', 80, 102), ('core', 92, 90), ('hull', 90, 92)): assert (len(d[k]['f']), len(d[k]['v'])) == (nf, nv), k
r = lambda k: np.linalg.norm(np.array(d[k]['v']), axis=1).max()
assert abs(r('H') - r('hull')) < 1e-6
s = 1.6 / r('hull')   # scale so the hull reaches 1.6 (Vajrayana's units), as in the research renders
out = {'paperDoi': '10.5281/zenodo.23430868', 'view': d['view'],
       **{k: {'v': [[round(x * s, 6) for x in v] for v in d[k]['v']], 'f': d[k]['f'], 't': d[k]['t']} for k in ('H', 'O', 'core', 'hull')}}
js = '// Generated by scripts/build-hecatogdo-data.py (DICTO 2026-10-18). Do not edit by hand.\nexport default ' + json.dumps(out, separators=(',', ':')) + ';\n'
open('src/app/hecatogdo-data.js', 'w').write(js); print(len(js), 'bytes')
