# Builds src/app/thirteens-data.js for the 13 world (DICTO 2026-10-13, docs/PLAN-13.md) from scripts/dump-thirteens.mjs output,
# checking every piece (closed, consistently wound, flat faces) and every kit (piece volumes against the hull's).
# Usage: python3 scripts/build-thirteens-data.py thirteens-raw.json
import sys, json, numpy as np
from scipy.spatial import ConvexHull
D = json.load(open(sys.argv[1]))
def check(V, F):
    V = np.array(V, float); edges = {}
    for f in F:
        for i, a in enumerate(f):
            b = f[(i + 1) % len(f)]; edges[(a, b)] = edges.get((a, b), 0) + 1
    closed = all(edges.get((b, a)) == 1 and n == 1 for (a, b), n in edges.items())
    flat = 0.0
    for f in F:
        if len(f) > 3:
            P = V[f]; c = P.mean(0); n = np.cross(P[1] - P[0], P[2] - P[0]); n /= np.linalg.norm(n) or 1
            flat = max(flat, float(np.abs((P - c) @ n).max()))
    c = V.mean(0); vol = 0.0
    for f in F:
        for i in range(1, len(f) - 1):
            vol += np.linalg.det(np.array([V[f[0]] - c, V[f[i]] - c, V[f[i + 1]] - c])) / 6
    return closed, flat, vol
report, out = [], {}
for name, kits in D.items():
    out[name] = {'views': {}}
    for kit, pieces in kits.items():
        bad, worst, total = 0, 0.0, 0.0
        for role, V, F in pieces:
            closed, flat, vol = check(V, F)
            if not closed or vol <= 0: bad += 1
            worst = max(worst, flat); total += abs(vol)
        pts = np.array([v for _, V, _ in pieces for v in V], float)
        hull = ConvexHull(pts).volume
        report.append(f'{name:9s} {kit:8s} {len(pieces):4d} pieces  open/inverted {bad:3d}  flatness {worst:.1e}  volume {total:10.5f}  hull {hull:10.5f}  ratio {total / hull:.6f}')
        out[name]['views'][kit] = [[r, [[round(x, 6) for x in v] for v in V], F] for r, V, F in pieces]
print('\n'.join(report))
open('src/app/thirteens-data.js', 'w').write('// Generated by scripts/build-thirteens-data.py (the 13s, docs/PLAN-13.md). Do not edit.\nexport default ' + json.dumps(out, separators=(',', ':')) + ';\n')
