# Builds src/app/bull-horns-data.js: DICTO's "Bull-horns OG adaptor" (DICTO 2026-10-18; research studies/2026-10-18-bcc-hole-pieces) for
# the Golden Bodhi Pyrochlore Networks world's double view: the resin round the OG (Ogdoecontahedron) double network cut at the holes
# between 6 OGs -- one piece shape, 3 per OG, filling the gap exactly (OGs 77.4332 %, adaptors 22.5668 %, exact in the study).
# Frame = the world's cube 0 (sites M.q, q integer, all one parity): holes = M.h with h having one or two odd entries; each OG owns the
# holes M.(q + e_k), k = 0, 1, 2. Piece = Voronoi cell of the hole among all holes minus the OGs (manifold3d; run on dicto-node).
# Usage: python3 scripts/build-bull-horns-data.py   (reads src/app/bodhi-pyro-data.js, writes src/app/bull-horns-data.js)
import json, itertools, numpy as np, manifold3d as m3
from scipy.spatial import HalfspaceIntersection
s = open('src/app/bodhi-pyro-data.js').read(); D = json.loads(s[s.index('{'):s.rindex('}') + 1])
V = np.array(D["ocd"]["v"]); M = np.array(D["cubes"][0]["M"], float)
Mc = M.T   # the world sets its Matrix3 from M transposed (columns of M are the basis)
pos = lambda q: Mc @ np.asarray(q, float)
hull = lambda P: m3.Manifold.hull_points(np.asarray(P, float)); U = lambda ms: m3.Manifold.batch_boolean(ms, m3.OpType.Add)
OG = hull(V)
# sanity: the OG's 8 bond neighbours M.s (s in {+-1}^3) must touch it hexagon to hexagon (no overlap)
nb = [pos(s_) for s_ in itertools.product((1, -1), repeat=3)]
ov = max((OG ^ OG.translate(p)).volume() for p in nb); print('bond-neighbour overlap (rounding only):', ov)
assert ov < 1e-5, 'frame check failed: bond neighbours overlap'
holes = [h for h in itertools.product(range(-5, 6), repeat=3) if sum(x % 2 for x in h) in (1, 2)]
og_sites = [q for q in itertools.product(range(-5, 6), repeat=3) if len({x % 2 for x in q}) == 1]
cell_of = lambda q: np.linalg.det(Mc) * 4   # volume of one OG's share: 2 OGs per (2x2x2 in q) cube of volume 8 det -> 4 det
pieces = []
for k in range(3):
    h0 = np.zeros(3, int); h0[k] = 1; c = pos(h0)
    hs = [np.r_[pos(h) - c, -(pos(h) - c) @ ((pos(h) + c) / 2)] for h in holes if 0 < np.linalg.norm(pos(h) - c) < 3.5 * np.linalg.norm(pos([1, 0, 0]))]
    cell = hull(HalfspaceIntersection(np.array(hs), c).intersections)
    near = [pos(q) for q in og_sites if np.linalg.norm(pos(q) - c) < 3.0 * np.linalg.norm(pos([1, 1, 1]))]
    piece = cell - U([OG.translate(p) for p in near])
    me = piece.to_mesh(); pieces.append(dict(v=np.round(np.asarray(me.vert_properties[:, :3], float), 6).tolist(), t=np.asarray(me.tri_verts).tolist(), volume=piece.volume(),
                                             parts=len([p for p in piece.decompose() if p.volume() > 1e-9])))
share = abs(np.linalg.det(Mc)) * 4
fill = 3 * pieces[0]['volume'] / share
print('pieces', [(round(p['volume'], 6), p['parts'], len(p['t'])) for p in pieces], 'adaptor share %.4f%%' % (100 * fill), 'OG share %.4f%%' % (100 * OG.volume() / share))
assert all(p['parts'] == 1 for p in pieces) and abs(fill - 0.225668) < 2e-5
open('src/app/bull-horns-data.js', 'w').write('// Generated by scripts/build-bull-horns-data.py (Bull-horns OG adaptor, DICTO 2026-10-18; research studies/2026-10-18-bcc-hole-pieces). Do not edit.\nexport default '
    + json.dumps(dict(pieces=[dict(v=p['v'], t=p['t']) for p in pieces], ogShare=OG.volume() / share, adaptorShare=fill), separators=(',', ':')) + ';\n')
