phi = (1 + 5 ** 0.5) / 2
BG = (20, 22, 28)
EDGE = '#efe9d8'; FIN = '#8fa9c4'; RES = '#d9b98c'; VPL = '#8fa9c4'; CORE = '#f4f0e6'
